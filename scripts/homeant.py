def _win_service_stop() -> bool:
    """Stop it and wait for the SCM to confirm.

    The start type is deliberately *not* touched here.  Changing it needs
    ``SERVICE_CHANGE_CONFIG``, which only an administrator may hold — granting
    it to interactive users would let them repoint the binary — so a Windows
    ``stop`` stops the process and leaves start-at-boot alone.  Linux has no
    such split: `disable` there is unprivileged, which is why `cmd_stop` does
    both verbs on that side and one here.
    """
    scm = _win_scm()
    if scm is None:
        return False
    if _win_service_state() != "running":
        return True
    win32service = scm[0]
    try:
        # Same minimal mask as `start`: STOP alone would be enough for the
        # control call, but QUERY_STATUS is what lets the wait below read a
        # state the SCM will actually hand an interactive user.
        hscm, hs = _win_open_service(
            win32service,
            win32service.SERVICE_STOP | win32service.SERVICE_QUERY_STATUS)
        try:
            win32service.ControlService(hs, win32service.SERVICE_CONTROL_STOP)
        finally:
            win32service.CloseServiceHandle(hs)
            win32service.CloseServiceHandle(hscm)
    except Exception as e:
        log_state("FAIL", f"cannot stop the service — {e}")
        return False
    # The SCM reports STOPPED once our SvcStop's tree-kill has finished; wait
    # for it instead of assuming, because the caller may delete the tree next.
    for _ in range(STOP_WAIT_SEC * 2):
        if _win_service_state() != "running":
            return True
        time.sleep(0.5)
    log_state("FAIL", f"service still running after {STOP_WAIT_SEC}s")
    return False


def _service_stop_now() -> bool | None:
    """Stop the supervisor's process without touching its start type.

    ``None`` means nothing supervises this host, so the caller keeps its own way
    of stopping.  Same single verb as ``cmd_stop`` — the difference is only who
    asks: this runs *inside* ``start``, which is about to bring the home back,
    and it also runs inside ``uninstall``, which clears the registration next.
    Both branches wait for the manager to confirm, so a caller that deploys
    files next never races a process still flushing stores.
    """
    kind = _service_kind()
    if kind == "systemd-user" and UNIT_PATH.exists():
        r = _systemctl("stop", SERVICE_NAME)
        if r is None or r.returncode != 0:
            chatter = ((r.stderr or "") + (r.stdout or "")).strip() if r else ""
            why = (chatter.splitlines()[-1] if chatter
                   else f"systemctl exited {r.returncode}" if r
                   else "systemctl is unavailable")
            log_state("FAIL", f"cannot stop the service — {why}")
            return False
        return True
    if kind == "service" and _win_service_installed():
        return _win_service_stop()
    if kind == "launchd" and UNIT_PATH.exists():
        # bootout unloads the job; it does not delete the plist, which is what
        # makes this the "stop, keep the registration" verb `start` expects.
        return _launchd_bootout()
    return None


def _stop_own_hass() -> bool:
    """Stop the instance that owns HA_ROOT, by the one rule this host allows.

    Under a supervisor the request goes to the supervisor, never to the pid:
    killing its child behind its back is indistinguishable from a crash, and the
    SCM/systemd then restarts the home about ten seconds later — right in the
    middle of the redeploy that asked for the stop (measured on Windows: exit
    code 1066 plus the failure actions).  With no supervisor there is nothing to
    ask, so the pid is the only tool; when not even that is readable, report
    failure rather than pretend the port will free itself.
    """
    by_service = _service_stop_now()
    if by_service is not None:
        return by_service
    pid = _ha_instance()
    if pid:
        return _stop_pid(pid)
    return not port_in_use(PORT)


def _win_service_unregister() -> tuple[bool, str | None]:
    """Stop it if it runs, then delete the registration."""
    if not _win_service_installed():
        return True, None
    if not _win_service_stop():
        return False, None
    scm = _win_scm()
    if scm is None:
        log_state("FAIL", "pywin32 is required to remove the service")
        return False, None
    try:
        scm[1].RemoveService(SERVICE_NAME)
    except Exception as e:
        log_state("FAIL", f"cannot delete the service — {e}")
        if not _is_admin():
            log("      removing a service needs administrator rights — "
                "re-run from an elevated prompt")
        return False, None
    return True, f"service removed: {SERVICE_NAME}"


def _service_host_main() -> int:
    """Be the Windows service: hand the SCM a well-behaved supervised child.

    The SCM insists on a process that calls ``StartServiceCtrlDispatcherW``
    within 30 seconds and then answers control requests; a plain ``python.exe``
    does neither, which is why ``sc create`` around one fails with error 1053.
    This function supplies exactly that handshake and nothing else — the work
    stays in ``start --foreground``, spawned as a child and watched, so the
    SCM's restart policy sees a real exit code.

    A stop request is not a failure: the child is killed and we exit 0, so the
    failure actions do not resurrect a home the user just stopped.
    """
    try:
        import servicemanager
        # win32service is not optional here: SvcStop reads SERVICE_STOP_PENDING
        # from it, and this module deliberately imports it lazily everywhere
        # else, so leaving it out made the stop handler raise NameError at the
        # first line — the report, the kill and the event were all skipped and
        # the service stayed RUNNING, unstoppable, with nothing in the log.
        import win32event
        import win32service
        import win32serviceutil
    except ImportError as e:
        # No console here, so log() would raise on a None stdout: the one place
        # this line can go is the service log itself.
        try:
            HA_ROOT.mkdir(parents=True, exist_ok=True)
            with open(SERVICE_LOG, "a", encoding="utf-8") as fh:
                fh.write("[homeant] FAIL  pywin32 is required for service "
                         f"mode — {e}\n")
        except OSError:
            pass
        return 1

    # Session 0 has no console: sys.stdout/sys.stderr are None, and the first
    # print() inside a start the SCM cannot report would raise AttributeError.
    # Rebind both before anything speaks.  The child gets *this* handle, not a
    # second open() of the same path: two independent append streams each seek
    # to EOF before writing on Windows, so the second writer overwrites the
    # tail of the first — measured, the host's "service: starting hass" line
    # came out as a stray "...ipts\python.exe)" fragment.  Inheriting one handle
    # means one shared file position, and appends stay in order.
    try:
        HA_ROOT.mkdir(parents=True, exist_ok=True)
        stream = child_log = open(SERVICE_LOG, "a", encoding="utf-8",
                                  buffering=1)
    except OSError:
        stream = child_log = open(os.devnull, "w", encoding="utf-8")
    sys.stdout = stream
    sys.stderr = stream

    state = {"rc": 0}
    py = PROJECT_ROOT / ".venv" / "Scripts" / "python.exe"
    script = PROJECT_ROOT / "scripts" / "homeant.py"

    class _HomeAnt(win32serviceutil.ServiceFramework):
        _svc_name_ = SERVICE_NAME
        _svc_display_name_ = SERVICE_DISPLAY_NAME
        _svc_description_ = SERVICE_DESCRIPTION

        def __init__(self, args):
            super().__init__(args)
            self.stop_event = win32event.CreateEvent(None, 0, 0, None)
            self.child: subprocess.Popen | None = None
            self.stopping = False

        def ServiceCtrlHandlerEx(self, control, event_type, data):
            # Every control the SCM delivers lands here first.  Logged because
            # `ControlService` answering 1061 ("cannot accept control at this
            # time") cannot tell "the SCM never delivered it" apart from "we
            # were called and did nothing" — and that difference is the whole
            # diagnosis.  Volume is a line per start/stop, not per second.
            log(f"service: control {control}")
            return super().ServiceCtrlHandlerEx(control, event_type, data)

        def SvcStop(self):
            # First line, before anything that can raise: whether the control
            # reached this instance at all is the fact worth having.  The
            # parenthesis carries the second half of that fact — reporting
            # returns *silently* when self.ssh is None, and killing returns
            # silently when self.child is None, so a control delivered to an
            # instance that never ran SvcDoRun looks exactly like one delivered
            # here and then ignored.  Printing both handles is what tells the
            # two apart.
            child = self.child
            log(f"service: stop requested (ssh={'set' if self.ssh else 'NONE'}, "
                f"child={child.pid if child else 'NONE'})")
            # Report first: the SCM gives a stop request 30s by default, and a
            # service that says nothing for that long is terminated outright.
            # Guarded because everything after it *is* the stop: an exception
            # in this one call skipped the kill and the event and left a
            # service that still reads RUNNING, refuses every further control
            # with 1061, and cannot be stopped except by killing the process.
            try:
                self.ReportServiceStatus(win32service.SERVICE_STOP_PENDING,
                                         waitHint=STOP_WAIT_SEC * 1000)
            except Exception as e:
                log_state("FAIL", f"service: cannot report STOP_PENDING — {e}")
            self.stopping = True
            try:
                self._kill_child()
            finally:
                # The event must be set even if the kill raises.  A control
                # handler that dies half-way leaves the service running with a
                # stop already queued, and from then on the SCM refuses every
                # further control with 1061 ("cannot accept control at this
                # time") while the state still reads RUNNING — the service is
                # then unstoppable except by killing the process.  Measured on
                # this machine.
                win32event.SetEvent(self.stop_event)

        def _kill_child(self) -> None:
            """End the whole tree: the wrapper is only the middle layer.

            ``child.kill()`` would TerminateProcess the wrapper and leave hass —
            its child — holding the venv and the port, which is the one outcome
            a stop must never produce.  ``taskkill /T`` is the same call
            ``_stop_pid`` makes for an unsupervised instance.
            """
            child = self.child
            if child is None or child.poll() is not None:
                return
            subprocess.run(["taskkill", "/PID", str(child.pid), "/F", "/T"],
                           capture_output=True,
                           creationflags=_no_console_flags())
            with contextlib.suppress(subprocess.TimeoutExpired):
                child.wait(timeout=STOP_WAIT_SEC)

        def SvcDoRun(self):
            log(f"service: starting hass ({py})")
            try:
                self.child = subprocess.Popen(
                    [str(py), str(script), "start", "--foreground"],
                    stdin=subprocess.DEVNULL, stdout=child_log, stderr=child_log,
                    cwd=str(PROJECT_ROOT), creationflags=_no_console_flags())
            except OSError as e:
                log_state("FAIL", f"cannot start hass — {e}")
                state["rc"] = 1
                return
            while True:
                rc = self.child.poll()
                if rc is not None:
                    break
                # Both signals are checked, not just the event: if SetEvent ever
                # fails to reach this thread, depending on the event alone means
                # waiting forever while the SCM shows RUNNING and refuses every
                # control with 1061.  The flag is set by the control thread
                # before it touches the child, so it is the cheaper witness.
                if self.stopping or (win32event.WaitForSingleObject(
                        self.stop_event, 1000) == win32event.WAIT_OBJECT_0):
                    self._kill_child()
                    rc = 0
                    break
            log(f"service: hass exited with {self.child.returncode}")
            if self.stopping or not rc:
                # Neither a stop the user asked for nor a clean exit is a
                # failure: returning reports SERVICE_STOPPED with 0 and the
                # failure actions stay quiet, which is exactly what a home the
                # user just stopped needs.
                return
            # hass died on its own with a non-zero code, so the SCM has to see
            # a failure or it will not restart anything.  Returning normally
            # reports STOPPED with exit code 0, i.e. "stopped on purpose" —
            # measured on this machine: flags=True, 3x RESTART/10s configured,
            # and the service still sat at (STOPPED, dwWin32ExitCode=0) for
            # minutes after hass was killed.  The failure *actions* only fire
            # when the exit code is non-zero, which is the one thing
            # FailureActionsOnNonCrashFailures is about.
            try:
                self.ReportServiceStatus(
                    win32service.SERVICE_STOPPED,
                    win32ExitCode=WIN_ERROR_SERVICE_SPECIFIC,
                    svcExitCode=rc)
            except Exception as e:
                log_state("FAIL", f"service: cannot report the failure — {e}")
            # os._exit rather than return: pywin32's dispatcher reports STOPPED
            # one more time, with 0, as soon as SvcDoRun returns, which would
            # overwrite the code just reported.  Flush first — os._exit skips
            # every buffer flush there is, and the line above is the evidence
            # the next start needs.
            try:
                sys.stdout.flush()
            except Exception:
                pass
            os._exit(rc)

    try:
        servicemanager.Initialize()
        servicemanager.PrepareToHostSingle(_HomeAnt)
        servicemanager.StartServiceCtrlDispatcher()
    except Exception as e:
        log_state("FAIL", f"cannot talk to the service manager — {e}")
        return 1
    return state["rc"]


# ── config deployment ─────────────────────────────────────────────────────────

_CONFIG_DIR = PROJECT_ROOT / "config"

# Files whose top-level keys are seed-owned: a template entry REPLACES the same
# key in the deployed copy, while keys only the deployed file has (UI-created
# entries) are kept.
#
# scripts.yaml: keys are script IDs, and a script's `sequence` is an ordered
# action chain — merging it item-wise appends new steps to a stale chain instead
# of replacing it, which corrupts the script. Replacing the file wholesale is
# not an option either: HA's script UI (components/config/script.py,
# EditKeyBasedConfigView) rewrites the whole file, so any script created in the
# UI lives in the same mapping and would be dropped.
_SEED_ENTRY_REPLACE_FILES = {"scripts.yaml"}


def _deep_merge_dict(tpl: dict, cur: dict) -> dict:
    """Recursive merge: add template keys missing in cur, never overwrite.

    - dict in both → recurse into children
    - list in both → de-duplicate merge (by dict identity or element equality)
    - scalar/list in cur only → keep cur (user wins)
    - key only in tpl → add from tpl

    A bare ``key:`` parses as ``None`` and is carried through untouched: HA
    itself rewrites every top-level ``None`` to ``{}`` while loading the config
    (homeassistant/config.py, load_yaml_config_file), so normalising it here
    would only make two equivalent files compare as different and force a
    pointless rewrite of the deployed copy.
    """
    result = dict(cur)
    for k, tv in tpl.items():
        if k not in result:
            result[k] = tv
        elif isinstance(tv, dict) and isinstance(result[k], dict):
            result[k] = _deep_merge_dict(tv, result[k])
        elif isinstance(tv, list) and isinstance(result[k], list):
            result[k] = _merge_lists(tv, result[k])
        # else: cur has scalar/list/None, leave as-is
    return result


def _dict_id_key(d: dict) -> tuple | None:
    """Return a best-effort identity key for a dict element in a list.

    Recognises common ID field patterns used by HA storage files:
      - issues:         (domain, issue_id)
      - entries/devices: id / entry_id / device_id
      - areas:          area_id / name
    Returns None if no known ID fields found — caller falls back to full-content compare.
    """
    if "domain" in d and "issue_id" in d:
        return ("domain", "issue_id", d["domain"], d["issue_id"])
    if "id" in d:
        return ("id", d["id"])
    if "entry_id" in d:
        return ("entry_id", d["entry_id"])
    if "device_id" in d:
        return ("device_id", d["device_id"])
    if "area_id" in d:
        return ("area_id", d["area_id"])
    return None


def _freeze(value):
    """Hashable full-content key for list de-duplication.

    YAML/JSON elements nest arbitrarily (an action's ``if: then: - service:``
    chain), so ``frozenset(d.items())`` raises TypeError on any dict or list
    value. Freeze recursively instead: dicts become key-sorted tuples, lists
    become tuples, scalars pass through.
    """
    if isinstance(value, dict):
        return ("dict", tuple(sorted(((k, _freeze(v)) for k, v in value.items()),
                                     key=lambda kv: str(kv[0]))))
    if isinstance(value, (list, tuple)):
        return ("list", tuple(_freeze(v) for v in value))
    try:
        hash(value)
    except TypeError:
        return ("repr", repr(value))
    return ("scalar", value)


def _merge_lists(tpl: list, cur: list) -> list:
    """Merge two lists: keep all cur items, append tpl items not already present.

    For lists of dicts with recognisable ID fields (domain+issue_id, id, etc.),
    de-duplicate by that identity key so user's entry wins over template.
    For scalar lists or unknown dict shapes, de-dup by full value/content.
    """
    if not cur:
        return list(tpl)
    if not tpl:
        return list(cur)

    # Detect if we're merging dicts with a known identity key
    first_cur = cur[0]
    if isinstance(first_cur, dict):
        id_key = _dict_id_key(first_cur)
        if id_key is not None:
            # Build set of existing identity keys from cur
            cur_keys = {_dict_id_key(c) for c in cur
                        if isinstance(c, dict) and _dict_id_key(c) is not None}
            merged = list(cur)
            for t_item in tpl:
                if isinstance(t_item, dict):
                    tk = _dict_id_key(t_item)
                    if tk is not None and tk not in cur_keys:
                        merged.append(t_item)
                        cur_keys.add(tk)
            return merged

    # Fallback: scalar lists or unknown dict shapes → full-content dedup
    merged = list(cur)
    cur_frozen = {_freeze(c) for c in cur}
    for t_item in tpl:
        frozen = _freeze(t_item)
        if frozen not in cur_frozen:
            merged.append(t_item)
            cur_frozen.add(frozen)
    return merged


def _merge_file(tpl_path: Path, dst_path: Path) -> bool:
    """Merge template file into dst. Auto-detect format (.yaml / .json).

    Merge rules:
      - keys missing in dst are added from the template; existing values win
      - HA storage entries present in both adopt the template: on entry_id
        match the data dict is replaced; on a unique-domain match the whole
        entry is (id included), so the merge de-duplicates instead of
        appending — the sole overwrite path, for seed entries whose *values*
        changed (mcp_server) on an already-initialized install; skipped while
        hass is running (HA rewrites these files from memory on shutdown)
      - YAML carrying custom tags (!include & co.) is merged at text level by
        _merge_file_tags — safe_load cannot construct those tags
      - files in _SEED_ENTRY_REPLACE_FILES replace per top-level key instead
        (see the constant): seed-owned entries follow the template, deployed-only
        entries survive

    Returns True if dst was written (something new was merged in).
    """
    if not dst_path.exists():
        return False  # nothing to merge into (fresh files are copied, not merged)
    suffix = tpl_path.suffix.lower()
    is_yaml = suffix in (".yaml", ".yml")
    is_json = suffix == ".json" or suffix == "" \
        or ".storage" in (tpl_path.parent.name, dst_path.parent.name)
    if not (is_yaml or is_json):
        return False  # unknown format

    if is_yaml:
        import yaml
        tpl_text = tpl_path.read_text(encoding="utf-8")
        dst_text = dst_path.read_text(encoding="utf-8")
        try:
            tpl = yaml.safe_load(tpl_text) or {}
            cur = yaml.safe_load(dst_text) or {}
        except yaml.YAMLError:
            # Custom tags (!include / !secret / !include_dir_*) are not
            # constructible by safe_load. Skipping those files is what kept
            # deployed configs from ever picking up new keys — merge at text
            # level instead.
            return _merge_file_tags(tpl_text, dst_text, dst_path)
    else:
        # HA storage files are JSON: no suffix (auth) or dotted core.*
        # naming under .storage/ (core.config_entries)
        try:
            tpl = json.loads(tpl_path.read_text(encoding="utf-8"))
            cur = json.loads(dst_path.read_text(encoding="utf-8"))
        except Exception as e:
            log(f"  merge skipped (parse error: {e})")
            return False

    if not isinstance(tpl, dict) or not isinstance(cur, dict):
        return False

    entries_synced = _sync_storage_entries(tpl, cur)
    if tpl_path.name in _SEED_ENTRY_REPLACE_FILES:
        replaced = False
        for key, val in tpl.items():
            if key not in cur or cur[key] != val:
                cur[key] = val  # seed-owned entry: template wins over deployed
                log(f"  {dst_path.name}: seed entry '{key}' adopted")
                replaced = True
        if not replaced and not entries_synced:
            return False  # deployed already matches the seed
        merged = cur
    else:
        merged = _deep_merge_dict(tpl, cur)
        if merged == cur and not entries_synced:
            return False  # nothing new to add

    # Write back
    dst_path.parent.mkdir(parents=True, exist_ok=True)
    if is_yaml:
        if (tpl_path.name in _SEED_ENTRY_REPLACE_FILES
                and set(cur) <= set(tpl)):
            # Nothing deployed-only to preserve → adopt the seed file verbatim
            # so its comments and formatting survive (safe_dump drops both).
            dst_path.write_bytes(tpl_path.read_bytes())
            return True
        import yaml
        dst_path.write_text(
            yaml.safe_dump(merged, allow_unicode=True, sort_keys=False),
            encoding="utf-8",
        )
    else:
        dst_path.write_text(
            json.dumps(merged, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
    return True


def _merge_file_tags(tpl_text: str, dst_text: str, dst_path: Path) -> bool:
    """Add-only merge for YAML carrying custom tags (!include / !secret ...).

    ``yaml.safe_load`` cannot construct custom tags, so include-bearing
    configs used to fall through as "parse error" and silently never picked
    up new template keys (a deployed configuration.yaml kept its old content
    forever). Re-serialising the loaded dict is not an option either: dumping
    would inline every ``!include`` target and destroy the wiring that lets
    the UI own scenes.yaml / automations.yaml.

    So only the *text* of each missing template key is spliced into dst
    (indentation-adjusted, nested mappings recursed into), leaving the rest
    of the file byte-identical. The result is re-composed before writing and
    dropped if the top-level keys still do not all show up.

    Returns True if dst was written.
    """
    import yaml

    try:
        tpl_root = yaml.compose(tpl_text, Loader=yaml.SafeLoader)
        dst_root = yaml.compose(dst_text, Loader=yaml.SafeLoader)
    except yaml.YAMLError as e:
        log(f"  merge skipped (parse error: {e})")
        return False

    if not isinstance(tpl_root, yaml.MappingNode):
        return False  # only mapping-shaped configs can be key-merged
    if dst_root is None:  # empty dst adopts the template verbatim
        dst_path.write_text(tpl_text, encoding="utf-8")
        return True
    if not isinstance(dst_root, yaml.MappingNode):
        return False

    edits: list[tuple[int, list[str]]] = []
    _collect_yaml_inserts(tpl_text.splitlines(), tpl_root, dst_root, 0, edits)
    if not edits:
        return False  # dst already has every template key

    merged = dst_text.splitlines()
    for line, block in sorted(edits, key=lambda e: e[0], reverse=True):
        merged[line + 1:line + 1] = block
    merged_text = "\n".join(merged) + "\n"

    try:
        check = yaml.compose(merged_text, Loader=yaml.SafeLoader)
    except yaml.YAMLError as e:
        log(f"  merge skipped (merged yaml unparsable: {e})")
        return False
    if not _yaml_mapping_keys(tpl_root) <= _yaml_mapping_keys(check):
        log("  merge skipped (keys still missing after splice)")
        return False

    dst_path.parent.mkdir(parents=True, exist_ok=True)
    dst_path.write_text(merged_text, encoding="utf-8")
    return True


def _collect_yaml_inserts(tpl_lines: list[str], tpl_map, dst_map,
                          indent: int, edits: list) -> None:
    """Queue text insertions for template keys absent from dst_map.

    ``indent`` is the column dst_map's children sit at; template blocks are
    shifted by the difference so they land at the right depth.
    """
    import yaml

    dst_children: dict[str, object] = {}
    for k, v in dst_map.value:
        if isinstance(k, yaml.ScalarNode):
            dst_children.setdefault(k.value, v)

    missing = []
    nested = []
    for tk, tv in tpl_map.value:
        if not isinstance(tk, yaml.ScalarNode):
            continue
        dv = dst_children.get(tk.value)
        if dv is None:
            missing.append((tk, tv))
        elif (isinstance(tv, yaml.MappingNode) and not tv.flow_style
              and isinstance(dv, yaml.MappingNode) and not dv.flow_style):
            nested.append((tv, dv))

    if missing:
        anchor = _yaml_insert_anchor(dst_map)
        delta = indent - missing[0][0].start_mark.column
        if anchor is not None and delta >= 0:
            block: list[str] = []
            for tk, tv in missing:
                piece = _yaml_slice(tpl_lines, tk, tv, delta)
                if not piece:
                    continue
                if block and indent == 0:
                    block.append("")  # blank line between new top-level keys
                block += piece
            if block:
                if indent == 0:
                    block.insert(0, "")  # blank line before the new section
                edits.append((anchor, block))

    for tv, dv in nested:
        child_indent = _yaml_child_indent(dv)
        if child_indent is not None:
            _collect_yaml_inserts(tpl_lines, tv, dv, child_indent, edits)


def _yaml_insert_anchor(map_node) -> int | None:
    """Line index after which a new sibling key can be spliced in."""
    if not map_node.value or map_node.flow_style:
        return None  # empty or flow mapping: no block anchor
    key, value = map_node.value[-1]
    end = value.end_mark
    if end.column == 0 and end.line > key.start_mark.line:
        return end.line - 1  # end mark already points past the content
    return end.line


def _yaml_child_indent(map_node) -> int | None:
    """Column of map_node's children (None when it has none)."""
    if not map_node.value:
        return None
    return map_node.value[0][0].start_mark.column


def _yaml_slice(tpl_lines: list[str], key_node, val_node, delta: int) -> list[str]:
    """Raw text of one template key/value pair, shifted by ``delta`` columns."""
    start = key_node.start_mark.line
    end = val_node.end_mark.line
    if val_node.end_mark.column == 0 and end > start:
        end -= 1
    out: list[str] = []
    for line in tpl_lines[start:end + 1]:
        if not line.strip():
            out.append("")
        elif delta > 0:
            out.append(" " * delta + line)
        elif delta < 0:
            if line[:-delta].strip():
                return []  # cannot de-indent safely: skip this insertion
            out.append(line[-delta:])
        else:
            out.append(line)
    return out


def _yaml_mapping_keys(node) -> set[str]:
    import yaml

    if not isinstance(node, yaml.MappingNode):
        return set()
    return {k.value for k, _ in node.value if isinstance(k, yaml.ScalarNode)}


def _sync_storage_entries(tpl: dict, cur: dict) -> bool:
    """Reconcile HA storage entries with the template (in place on cur).

    _deep_merge_dict never overwrites existing values, so an install whose
    storage entry predates a seed value change (mcp_server) would keep stale
    data forever. Runs before the merge, pairing template entries against the
    pre-merge runtime state:

      - entry_id match                  → runtime entry adopts the seed data
      - else unique domain on both sides → runtime entry adopts the seed entry
        wholesale (data + entry_id), so the merge de-duplicates by id instead
        of appending a second entry for the same domain

    Only safe while hass is not running: HA holds entries in memory and
    rewrites these files on shutdown.
    """
    tpl_data = tpl.get("data")
    cur_data = cur.get("data")
    if not isinstance(tpl_data, dict) or not isinstance(cur_data, dict):
        return False
    tpl_entries = [e for e in tpl_data.get("entries", []) if isinstance(e, dict)]
    cur_entries = cur_data.get("entries")
    if not tpl_entries or not isinstance(cur_entries, list):
        return False

    pairs = []
    for te in tpl_entries:
        hit = next((e for e in cur_entries
                    if isinstance(e, dict)
                    and e.get("entry_id") == te.get("entry_id")), None)
        if hit is None:
            same = [e for e in cur_entries
                    if isinstance(e, dict)
                    and e.get("domain") == te.get("domain")]
            if len(same) != 1:
                continue  # absent (merge deploys it) or ambiguous (leave alone)
            pairs.append((same[0], te, True))
        elif hit.get("data") != te.get("data"):
            pairs.append((hit, te, False))
    if not pairs:
        return False

    if _ha_instance() or _hass_via_service():
        # Rewriting a live instance's .storage is undone by its next flush, and
        # `_hass_via_service()` covers the case where the lock is gone and no
        # pid can be named: the home is up either way.
        return False
    for hit, te, wholesale in pairs:
        if wholesale:
            hit.clear()
            hit.update(te)
        else:
            hit["data"] = te.get("data", {})
    return True


def _deploy_config_files() -> None:
    """Walk config/ dir, copy or merge each file into HA_ROOT.

    Rules per file:
      - dst missing  → copy template
      - dst exists   → _merge_file (add missing keys; HA storage entries synced)
    """
    import shutil as _shutil

    if not _CONFIG_DIR.exists():
        return

    for tpl in _CONFIG_DIR.rglob("*"):
        if not tpl.is_file():
            continue

        rel = tpl.relative_to(_CONFIG_DIR)
        dst = HA_ROOT / rel

        if not dst.exists():
            dst.parent.mkdir(parents=True, exist_ok=True)
            _shutil.copy(tpl, dst)
        else:
            _merge_file(tpl, dst)

    log(f"deploying config → {HA_ROOT}")


# ── seed gate: deploy once per seed fingerprint ────────────────────────────

def _seed_digest() -> str | None:
    """sha256 over config/ — every path plus its bytes, in sorted order.

    The fingerprint is the *input* (what this release ships), never "when did we
    last run": a version bump that changes a seed file deploys, a bump that does
    not, does not.  Byte comparison also means an edit to a seed that ships the
    same content as the last release is not mistaken for a change.
    """
    import hashlib

    if not _CONFIG_DIR.is_dir():
        return None
    h = hashlib.sha256()
    for p in sorted(_CONFIG_DIR.rglob("*")):
        if not p.is_file() or "__pycache__" in p.parts or p.suffix == ".pyc":
            continue
        h.update(p.relative_to(_CONFIG_DIR).as_posix().encode("utf-8"))
        h.update(b"\0")
        h.update(p.read_bytes())
        h.update(b"\0")
    return h.hexdigest()


def _seed_marker() -> dict:
    """Read .seed-state as a dict; anything unreadable reads as "no marker"."""
    try:
        d = json.loads(SEED_MARKER.read_text(encoding="utf-8"))
        return d if isinstance(d, dict) else {}
    except (OSError, ValueError):
        return {}


def _seed_ready() -> bool:
    """True when the deployed seed matches the one this release ships.

    Also checks that the vendored custom_components landed: they come from
    vendor/, so they are not covered by the config/ fingerprint, and deleting
    ~/.homeant/custom_components would otherwise leave the fingerprint intact
    while xiaomi_home silently stopped existing.
    """
    seed = _seed_digest()
    if not seed or _seed_marker().get("seed") != seed:
        return False
    cc_src = PROJECT_ROOT / "vendor" / "ha_xiaomi_home" / "custom_components"
    if cc_src.is_dir():
        for d in cc_src.iterdir():
            if d.is_dir() and not d.name.startswith("_") \
                    and not (HA_ROOT / "custom_components" / d.name).is_dir():
                return False
    return True


def _seed_present() -> bool:
    """True when configuration.yaml — the seed's marker file — is on disk.

    Deliberately weaker than ``_seed_ready``: this answers "was this tree
    deleted", not "is the deployed copy current".  A new release changes the
    fingerprint, and treating that as "missing" would turn every `start` on a
    healthy running instance into a restart — the idempotency this command
    promises.  configuration.yaml is the marker because _ensure_seed always
    writes it and merely merges the rest.

    Both `status` (reports it) and `start` (recovers from it) ask this one
    question, so the two commands cannot disagree about the state of the tree.
    """
    return (HA_ROOT / "configuration.yaml").exists()


def _write_seed_marker() -> None:
    """Record the fingerprint of what was deployed.

    ``seed`` is the only field read back (by ``_seed_ready``), so the marker
    carries nothing else — a timestamp or a host name would be write-only.
    """
    SEED_MARKER.write_text(
        json.dumps({"seed": _seed_digest()}), encoding="utf-8")


def _install_custom_components() -> None:
    """Copy vendored integrations into HA_ROOT/custom_components.

    config/custom_components/ is deployed separately by _deploy_config_files();
    this one only covers what ships under vendor/.
    """
    import shutil as _shutil

    cc_src = PROJECT_ROOT / "vendor" / "ha_xiaomi_home" / "custom_components"
    cc_dst = HA_ROOT / "custom_components"
    if not cc_src.exists():
        return
    cc_dst.mkdir(parents=True, exist_ok=True)
    for domain in cc_src.iterdir():
        if domain.is_dir() and not domain.name.startswith("_"):
            _shutil.copytree(domain, cc_dst / domain.name, dirs_exist_ok=True)
            log(f"installed custom_components/{domain.name}")


def _ensure_seed() -> None:
    """Deploy the repo seed if — and only if — the fingerprint says so.

    Satisfied means nothing happens, which is what keeps a hand-edited
    ~/.homeant/configuration.yaml alive across runs.  The whole body is
    copy-or-merge, so a partial deploy can never roll anything back.
    """
    if _seed_ready():
        return
    HA_ROOT.mkdir(parents=True, exist_ok=True)
    if _CONFIG_DIR.exists():
        _deploy_config_files()
    _install_custom_components()
    _write_seed_marker()


# ── version check ──────────────────────────────────────────────────────────


def _vtuple(v: str) -> tuple:
    """'0.1.0' -> (0, 1, 0). Non-numeric segments collapse to 0."""
    parts = [int(p) if p.isdigit() else 0 for p in v.split(".")]
    return tuple((parts + [0, 0, 0])[:3])


def _local_version() -> str | None:
    try:
        text = (PROJECT_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    except OSError:
        return None
    m = re.search(r'(?m)^\s*version\s*=\s*"([^"]+)"', text)
    return m.group(1) if m else None


def _remote_version() -> str | None:
    """Latest released version, read off the online installer on the release
    host.

    The stamp INSTALLER_URL points at doubles as the version manifest — see the
    comment on that constant. Any failure is non-fatal: start must never block
    on this.
    """
    try:
        import urllib.request as _ur
        with _ur.urlopen(INSTALLER_URL, timeout=CONNECT_TIMEOUT) as resp:
            body = resp.read().decode("utf-8", "replace")
    except Exception:
        return None
    m = re.search(VERSION_RE, body)
    return m.group(1) if m else None


def _ask_update(version: str) -> bool:
    """Y/n prompt. Never updates unattended (no tty / piped stdin)."""
    try:
        if not sys.stdin or not sys.stdin.isatty():
            return False
        ans = input(f"[homeant] install {version} now? [Y/n] ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        return False
    return ans in ("", "y", "yes")


def _run_installer(version: str | None, repairing: bool = False) -> int:
    """Hand the work to the online installer; return the child's exit code.

    Two callers, one channel. A newer release (`repairing=False`) and a venv
    that no longer matches uv.lock (`repairing=True`) both need the same thing:
    the installer's download → stop → replace → uv sync → `start` sequence.
    Nothing of that is duplicated here — a second implementation is how an
    upgrade ends up behaving differently from a fresh install. There is also no
    fallback to "just start what is in memory": by the time the installer
    fails, the files under our feet may already be the new ones, so the honest
    answer is its exit code.

    Four decisions, each one measured before it landed here:
      * No stdio capture: the download progress redraws itself with \\r, so
        the child must own the real terminal or every frame becomes a line.
      * stdin is never the terminal: Windows passes DEVNULL, unix passes the
        fetched script to `sh -s`, so nothing down there can compete with the
        user for keystrokes.
      * unix feeds the script on stdin instead of `curl | sh`: a pipeline
        discards curl's exit status, so a 404 body would run as an empty
        script and report success.
      * Windows lets PowerShell fetch it, because `.Content` is a byte[] for
        `application/octet-stream` — the text has to be decoded explicitly
        from RawContentStream. `scriptblock::Create` then parses it before a
        single line runs, and `-ExecutionPolicy Bypass` is pointless:
        in-memory evaluation is not subject to it.
    """
    if repairing:
        log("dependencies incomplete — handing over to the online installer ...")
    else:
        log(f"installing {version} — handing over to the online installer ...")

    if IS_WIN:
        inner = (
            "$ProgressPreference='SilentlyContinue';"
            f"$r=Invoke-WebRequest -UseBasicParsing -Uri '{INSTALLER_URL}' -TimeoutSec {CONNECT_TIMEOUT};"
            "$s=[Text.Encoding]::UTF8.GetString($r.RawContentStream.ToArray());"
            "& ([scriptblock]::Create($s)) --upgrade"
        )
        argv = ["powershell", "-NoProfile", "-Command", inner]
        body = None
    else:
        import urllib.request as _ur

        try:
            with _ur.urlopen(INSTALLER_URL, timeout=CONNECT_TIMEOUT) as resp:
                body = resp.read()
        except Exception as e:
            log_red(f"update: cannot fetch the installer — {e}")
            return 1
        # same two checks install.sh makes on the script it fetches: a non-2xx
        # status raises above, and an empty body would otherwise run as a
        # successful no-op
        if not body.strip():
            log_red("update: the installer came back empty")
            return 1
        argv = ["sh", "-s", "--", "--upgrade"]

    try:
        if body is None:                    # Windows: PowerShell fetches it
            return subprocess.run(
                argv, cwd=str(PROJECT_ROOT), stdin=subprocess.DEVNULL).returncode
        # unix: the text we just fetched *is* stdin for `sh -s`
        return subprocess.run(
            argv, input=body, cwd=str(PROJECT_ROOT)).returncode
    except OSError as e:
        log_red(f"update: cannot run the installer — {e}")
        return 1


def _cfg_values(text: str) -> dict[str, str]:
    """KEY -> value, using load_cfg()'s own rules (skip blank / #, strip both)."""
    out: dict[str, str] = {}
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        k, v = s.split("=", 1)
        out[k.strip()] = v.strip()
    return out


def _cfg_new_keys_block(template_text: str, have: dict[str, str]) -> str:
    """Template lines for the keys the live file lacks, comments included.

    A bare ``KEY=value`` would leave the user guessing what the key does, and
    the template already documents every key right above it, so carry the
    comment block over with the key. The closing comment before the *next*
    key belongs to that key, not this one, which is why the buffer is reset
    both on a known key and on the first unknown one.

    The header block at the top describes the two files as a pair, not any
    single key, so it is skipped: iterating starts at the first real key.
    """
    lines = template_text.splitlines()
    start = next((i for i, line in enumerate(lines)
                  if line.strip() and not line.strip().startswith("#")
                  and "=" in line), len(lines))
    out: list[str] = []
    pending: list[str] = []
    for line in lines[start:]:
        s = line.strip()
        if not s or s.startswith("#"):
            pending.append(line)
            continue
        key = s.split("=", 1)[0].strip()
        if key in have:
            pending.clear()
            continue
        out.extend(pending)
        out.append(line)
        pending.clear()
    return "\n".join(out).strip("\n")


def _reconcile_cfg() -> None:
    """Bring homeant.cfg up to date with the shipped template.

    Additive only — it never rewrites a value the user already set:

      ① no live cfg      → copy the template (fresh install)
      ② nothing missing  → return without touching the file, mtime included
      ③ keys missing     → append those keys at the end, comments and all

    Rule ② is what makes this safe to call on every `start`: a no-op run must
    not look like a change, or every reinstall would show a modified config.
    Rule ③ is what lets a version bump add a key without resetting USERNAME /
    PASSWORD / per-machine paths.
    """
    if not CFG_TEMPLATE.is_file():
        return                       # release without a template: nothing to do
    import shutil as _shutil

    if not CONFIG_FILE.is_file():
        try:
            _shutil.copyfile(CFG_TEMPLATE, CONFIG_FILE)
            # copyfile() gives the new file the process umask - 0644 on a stock
            # Linux - and this file holds PASSWORD in clear text.  Windows has no
            # mode bits to set here (only the read-only flag) and cannot deny the
            # owner, so a refusal is swallowed rather than turned into a dead
            # install: an unreadable config would be the worse failure.
            try:
                os.chmod(CONFIG_FILE, 0o600)
            except OSError:
                pass
        except OSError as e:
            log_red(f"config: cannot create {CONFIG_FILE.name} — {e}")
            return
        log(f"config created from {CFG_TEMPLATE.name}")
        return

    # Same rule on every start, not only at creation: an install that predates
    # this line still carries a 0644 config, and rule ② returns without touching
    # the file at all - so the mode has to be asserted here, before the early
    # returns, or those installs would never converge.
    try:
        os.chmod(CONFIG_FILE, 0o600)
    except OSError:
        pass

    tpl_text = CFG_TEMPLATE.read_text(encoding="utf-8", errors="replace")
    # newline="" on the read as well as the write: read_text() would fold CRLF
    # into LF in memory, so the check below could never see a "\r\n" and a
    # CRLF config would come out with every line rewritten.
    with CONFIG_FILE.open("r", encoding="utf-8", errors="replace", newline="") as fh:
        text = fh.read()
    have = _cfg_values(text)
    missing = [k for k in _cfg_values(tpl_text) if k not in have]
    if not missing:
        return

    block = _cfg_new_keys_block(tpl_text, have)
    if not block:
        return
    # Keep the file's own line endings: writing "\n" into a CRLF file (or the
    # reverse) rewrites every existing line, which is exactly the "diff noise
    # on a no-op upgrade" this function is supposed to avoid.
    nl = "\r\n" if "\r\n" in text else "\n"
    if text and not text.endswith(("\n", "\r")):
        text += nl
    text += nl + f"# --- keys added by this version (from {CFG_TEMPLATE.name}) ---" + nl
    text += block.replace("\n", nl) + nl
    try:
        with CONFIG_FILE.open("w", encoding="utf-8", newline="") as fh:
            fh.write(text)
    except OSError as e:
        log_red(f"config: cannot append to {CONFIG_FILE.name} — {e}")
        return
    log(f"config: added {len(missing)} key(s) to {CONFIG_FILE.name}: "
        f"{', '.join(missing)}")


def _check_newer_version() -> str | None:
    """Detect-only: return the version the user agreed to install, else None.

    Nothing is written here — a check stays a check until the answer is yes.
    This is the one place we deliberately differ from the installers: they
    never compare versions (running them *is* the install), while an already
    installed tree has to notice the newer release itself.
    """
    local, remote = _local_version(), _remote_version()
    if not local or not remote or _vtuple(remote) <= _vtuple(local):
        return None
    log(f"new version available: {remote} (you have {local})")
    if not _ask_update(remote):
        # Declining is a normal answer, not a failure — just say so and move on.
        log(f"staying on {local}")
        return None
    return remote


def cmd_status(args) -> int:
    """Health check.  Normal lines carry no marker; a marker means trouble.

    Only FAIL / WARN are prefixed.  A passing check needs no badge — the
    absence of one is the pass signal — and that keeps every healthy line in
    the same plain ``key: value`` shape as the rest of the CLI's output.
    """
    checks = [
        ("HA_ROOT", HA_ROOT.exists(), str(HA_ROOT)),
    ]
    all_ok = True
    for name, ok, path in checks:
        if not ok:
            all_ok = False
            log(f"FAIL  {name}: {path}")
        else:
            log(f"{name}: {path}")

    # configuration.yaml gets no success line — its path is implied by HA_ROOT
    # above — so only its absence is worth reporting.
    if HA_ROOT.exists() and not _seed_present():
        all_ok = False
        log(f"FAIL  configuration.yaml: missing under {HA_ROOT}")

    # Same instance detection as start/stop — one predicate, so the two commands
    # cannot tell different stories.  That used to happen: after HA_ROOT was
    # deleted while hass kept serving from memory, start found the process by
    # scanning and said "running" while status, left with a deleted pid file,
    # said "not running" and blamed a stranger for holding the port.
    #
    # Two questions now that T11 removed the scan.  The lock names the pid when
    # it can; when it cannot, the supervisor plus a bound port still prove an
    # instance of ours is up — and saying so is the only way to keep that case
    # from reading as "some stranger has 8123".
    listening = port_in_use(PORT)
    pid = _ha_instance() if listening else None
    if pid:
        log(f"hass: running (PID {pid})")
    elif listening and _hass_via_service():
        log("hass: running (via service)")
    else:
        all_ok = False
        if listening:
            log(f"FAIL  hass: not running — port {PORT} held by another process")
        else:
            log(f"FAIL  hass: not running")

    # The supervisor's state, and deliberately short: three states plus one
    # suffix.  The suffix says autostart is unambiguously off — a choice the
    # user made with `disable`, not a fault, so it is not a FAIL marker and it
    # does not touch the exit code.  `hass:` above answers "is the process
    # there" and nothing else: folding the two together would make "not
    # running" ambiguous between "never came back" and "came back and stopped".
    # Position matters as much as wording — "hass: not running" and "service:
    # not installed" have completely different fixes, so the cause sits directly
    # under the symptom.
    kind = _service_kind()
    autostart_off = " (autostart off)" if _autostart_state() is False else ""
    if kind == "service":
        if not _win_service_installed():
            log("service: not installed")
        else:
            # Three states, no more.  The SCM has no "failed" state — a service
            # that exited nonzero is simply stopped — and a pending transition
            # reports "stopped" because the line above already says whether hass
            # is answering.  Ownership is not checked here either: the parent
            # link that answers it on Linux needs /proc.
            log(f"service: {'running' if _win_service_state() == 'running' else 'stopped'}"
                f"{autostart_off}")
    elif kind == "launchd":
        if not UNIT_PATH.exists():
            log("service: not installed")
        else:
            state, main = _launchd_info()
            if state == "running":
                log(f"service: running{autostart_off}")
                # launchd names the wrapper's pid, not hass's, exactly like
                # MainPID — so the same parent-link test decides ownership.
                if pid and main and _parent_pid(pid) != main:
                    log(f"WARN  service: does not own hass (PID {pid}) — run: homeant stop then start")
            else:
                # No "failed" state here: launchd just stops the job, and
                # KeepAlive has already retried it one ThrottleInterval later.
                # HA's own log lives in HA_ROOT — `homeant logs` is the
                # diagnostic path here; there is no journal to point at.
                log(f"service: stopped{autostart_off}")
    elif kind != "systemd-user" or not UNIT_PATH.exists():
        log("service: not installed")
    else:
        r = _systemctl("is-active", SERVICE_NAME)
        state = ((r.stdout or "").strip() if r is not None else "") or "inactive"
        if state == "active":
            log(f"service: running{autostart_off}")
            main = _service_main_pid()
            # MainPID is the wrapper, never hass, so ownership is decided by the
            # parent link; comparing the two pids directly would warn on every
            # healthy host.
            if pid and main and _parent_pid(pid) != main:
                log(f"WARN  service: does not own hass (PID {pid}) — run: homeant stop then start")
        else:
            log(f"service: stopped{autostart_off}")
            if state == "failed":
                # "failed" is the unit's last result, not necessarily a failed
                # start: a stop that ends in a non-zero exit lands here too, so
                # the line names the state and points at the journal instead of
                # claiming which half went wrong.
                log("WARN  service: failed — journalctl --user -u homeant -n 20")

    # OAuth gets no success badge either, and deliberately no effect on the exit
    # code: it is the one stage that waits on a browser, so "not configured"
    # describes an install still in progress, not a broken one — `start` is what
    # resumes it.  Same predicate as the gate in _finish_setup (a live config
    # entry), read from disk, so the two commands cannot disagree and no probe
    # request is spent finding out.
    #
    # A flow that is still open is reported apart from a missing one, because
    # the storage file cannot tell them apart and the user's next move differs:
    # one wants the login page, the other only a form nobody is looking at.
    #
    # Where the flow is parked cannot be read from disk — data_entry_flow keeps
    # no store, and core.config_entries holds entries only — so the one way to
    # ask is `GET /api/config/config_entries/flow/{id}` (200 for a known id;
    # the list endpoint is POST-only).  That costs one loopback request, spent
    # only when the marker exists, and it never mints a token or logs in: the
    # cached LLAT is used as-is.  Every failure — no token, hass down, 404 after
    # a restart — falls back to the wording that is true either way, so the line
    # is never worse than the stat() it replaced.
    if _xiaomi_already_configured():
        log("oauth: xiaomi_home configured")
    elif XIAOMI_FLOW_FILE.exists():
        state = _xiaomi_flow_state()
        if state == "authorizing":
            log("WARN  oauth: xiaomi_home waiting for authorization — run: homeant start to open the login page")
        elif state == "advancing":
            log("WARN  oauth: xiaomi_home authorized, entry not created — run: homeant start to finish it")
        elif state == "lost":
            log("WARN  oauth: xiaomi_home flow no longer exists — run: homeant start to begin again")
        else:
            log("WARN  oauth: xiaomi_home flow unfinished — run: homeant start to finish it")
    else:
        log("WARN  oauth: xiaomi_home not configured (run: homeant start)")

    if pid and listening:
        m_ok, m_msg = _mcp_diag()
        log(f"mcp: {m_msg}" if m_ok else f"WARN  mcp: {m_msg}")
        tok = _mcp_token(create=False)
        if tok:
            log("mcp config — paste into your MCP client:")
            print(json.dumps(_mcp_client_config(tok), indent=2, ensure_ascii=False))
            # Endpoint probe reports only on failure.  "token valid" above is
            # already the answer to the question the reader came with, so a
            # success line just restates it; a *failing* probe is the one fact
            # the token check cannot see (route not registered yet), so it keeps
            # its line — and being a marker, it also carries the WARN badge.
            why = _mcp_probe(tok, timeout=5)
            if why:
                log(f"WARN  mcp endpoint: not answering — {why}")
        # Two blocks, split by the machine each line is typed on — that is the
        # distinction the reader needs, and it is what one shared heading got
        # wrong before ("sudo ufw allow" sat under a "from another machine"
        # heading although it runs here).
        #
        # "on this server" and not "checked on this server": nothing in this
        # block is a measurement.  Whether 8123 is *allowed* needs root on every
        # platform (ufw status, iptables -S), and a non-root reading misleads in
        # both directions — it alarms on an allowed port and hides a blocked
        # one.  Detecting which firewall is installed (ufw, firewalld, none) only
        # decided whether to show a reminder; it never answered the question, so
        # it does not get to print a status either.  All platforms, all states,
        # one line, phrased as the action to take.
        #
        # No address is printed, deliberately.  Any single value would be the
        # default route's source — a VPN tunnel or a Hyper-V switch as easily as
        # the NIC the client sits behind — so on a multi-homed box it is right
        # for one subnet and wrong for the next (the dev box here has eight IPv4
        # addresses and two default routes).  The user knows which address they
        # are testing against; naming one only invites the wrong check.
        #
        # No port line either: this block only runs inside
        # `if pid and listening`, and pid was derived from listening, so it
        # could only ever print "listening".  Whether HA is bound to all
        # interfaces needs the socket table, which is not read here.
        log("on this server:")
        print(f"  firewall: not checked, please allow tcp/{PORT}", flush=True)
        log("needs another machine:")
        print(f"  ping: {MCP_HOSTNAME} — must answer this server's IP,"
              " not 127.0.0.1", flush=True)
    else:
        # Both blocks describe how to reach a running server, so they are skipped
        # entirely when there is none — the FAIL line above already says why.
        log("WARN  mcp: hass not running")

    return 0 if all_ok else 1


def _login_rejected_hint() -> None:
    """Print the one FAIL line for a refused credential, split by what the stores say.

    HA answers ``invalid_auth`` both for "no such user" and for "wrong password"
    (deliberately — no enumeration), so the API cannot say which.  The files
    can, and the two causes have opposite fixes:

    * user missing from the password store → half provisioned; re-provisioning
      adds it from nothing, so nothing can be lost.
    * user present but the bcrypt does not match ``PASSWORD`` → somebody changed
      the password (in the UI, most likely).  We must NOT rewrite it: the cfg
      is the copy that is out of date, and ``async_change_password`` here would
      silently undo the user's own change.
    """
    username = cf("USERNAME", "admin")
    if _provider_has_user(username):
        log_state("FAIL", f"admin login rejected — the password in {PROVIDER_STORE.name} "
                          f"does not match PASSWORD in {CONFIG_FILE}; fix whichever one "
                          f"is wrong, then re-run")
    else:
        log_state("FAIL", f"admin login rejected — '{username}' is missing from "
                          f"{PROVIDER_STORE.name}; run 'homeant stop' then "
                          f"'homeant start' to re-provision")


def _finish_setup(mcp_cfg: str | None, mcp_fail: dict | None = None) -> int:
    """Run the post-start stages in order, each gating the next.

    The chain is hosts → OAuth → MCP, and every exit prints one of three words —
    ``SUCCESS`` (done), ``PENDING`` (waiting on a human step — re-running this
    command is the retry) or ``FAIL`` (broken) — while returning 0 or 1.  The
    word is for the reader; the code says only whether anything needs fixing,
    which is why PENDING returns 0.  A stage that is not satisfied returns
    without running the next one, and nothing is cached between runs, so the
    sequence resumes from the top every time and is idempotent by construction.

    1. **hosts** (WSL only) — the Windows hosts file must map both names to
       127.0.0.1.  Every other platform ignores this stage: HA's own zeroconf
       broadcast does the job there.  No networking mode is exempt — measured
       11-10 under ``mirrored``: the host still could not resolve the guest's
       own announcements even with the A record forced to ``127.0.0.1``, while
       other LAN devices resolved fine.  Consulted only while OAuth is still
       incomplete — once the config entry exists the callback host is history,
       so a finished install goes straight to MCP instead of demanding a hosts
       entry forever.
    2. **oauth** — xiaomi_home must have a config entry.  Never waited on: the
       run advances the flow as far as it goes, surfaces the URL, and returns
       pending.  MCP is NOT printed here — setup is not done.
    3. **mcp** — ``mcp_cfg`` was produced before this call but after the
       RUNNING gate: the token is minted early (the gate needs it), the probe
       runs only once the core is up.  Its stanza opens the final block and the
       config follows, so nothing scrolls past what users copy out.
    """
    if _xiaomi_already_configured():
        log("xiaomi_home already configured — skipping OAuth")
        # Any id remembered from an earlier run is spent: the entry exists, so
        # there is no flow left to resume.
        XIAOMI_FLOW_FILE.unlink(missing_ok=True)
    else:
        # ── stage 1: callback host (WSL, every networking mode) ──────────────
        # No mode is exempt.  Under ``mirrored`` — the one mode documented to
        # carry multicast onto the LAN — the Windows host still could not
        # resolve the guest's own announcements (measured 11-10, both with the
        # A record at the guest's address and forced to 127.0.0.1), while the
        # same host resolved other LAN devices normally.
        if is_wsl() and not _hosts_has_ha_local():
            log_state("PENDING", "add the hosts entry, then re-run")
            # WSL cannot write it: the 9p server re-applies the Windows ACL even
            # to root, so the entry has to be created from the Windows side.
            # The address stays the IPv4 literal — see _hosts_has_ha_local for
            # why neither a name nor ::1 can stand in for it.  One line, both
            # names: hosts syntax allows several names per address, and two
            # entries would be two chances to drift apart.
            hosts_line = f"127.0.0.1 {OAUTH_HOSTNAME} {MCP_HOSTNAME}"
            print(r"    # PowerShell as Administrator at Windows")
            print(rf'    Add-Content -Path "$env:windir\System32\drivers\etc\hosts" -Value "{hosts_line}"')
            return 0
        # ── stage 2: OAuth, never waited on ──────────────────────────────────
        state, oauth_url = _xiaomi_advance()
        if state == "waiting":
            if oauth_url:
                # One sentence carrying both halves of the old two-line message —
                # what to do and what to re-run.  The URL follows on its own bare
                # line: it gets copied, and a prefix would be pasted with it.
                where = "your Windows browser" if is_wsl() else "your browser"
                log_state("PENDING", f"open this URL in {where} to finish setup, then re-run: homeant start")
                print(f"  {oauth_url}", flush=True)
            else:
                log_state("PENDING", "finish OAuth in the browser, then re-run: homeant start")
            return 0
        if state == "rejected":
            # The only way to get here is a rejected login.  Which of the two
            # causes it is decides the fix, and it is not always the cfg — see
            # _login_rejected_hint.  Not a browser problem either way.
            _login_rejected_hint()
            return 1
        # `done` means HA itself returned a create_entry result — that is the
        # integration's own terminal answer, so nothing is re-checked here.
        # Re-reading core.config_entries cannot confirm it anyway: HA writes
        # that file through async_delay_save(SAVE_DELAY=1), so a fresh entry is
        # still in memory when this line runs, and the `state` field is never
        # persisted at all.  The only thing a disk check adds is a one-second
        # race against a file that is guaranteed to be stale.
        if state != "done":
            log_state("FAIL", "xiaomi_home setup did not complete — see the lines above")
            return 1
        log("xiaomi_home setup complete")

    # ── stage 3: MCP config, last ────────────────────────────────────────────
    if not mcp_cfg:
        # Different failures, different fixes: a rejected credential is a
        # missing user or an out-of-date cfg (see _login_rejected_hint); a
        # refused token mint means the login worked and the core is the one
        # saying no; an endpoint that does not answer means the token is fine
        # but the integration behind it is not serving.  Collapsing them into
        # one line would send half the users to the wrong file.
        kind = (mcp_fail or {}).get("kind")
        if kind == "login":
            _login_rejected_hint()
        elif kind == "llat":
            log_state("FAIL", "signed in, but the core refused to create the MCP token — see the lines above, then re-run")
        elif kind == "endpoint":
            log_state("FAIL", (mcp_fail or {}).get("why") or "the MCP endpoint did not answer")
        else:
            log_state("FAIL", "no MCP token available — see the lines above")
        return 1
    log_state("SUCCESS", "mcp ready — paste this config into your client:")
    print(mcp_cfg, flush=True)
    return 0


def _run_foreground() -> int:
    """Run hass in the foreground and exit with its status.

    This is the contract handed to every supervisor — systemd, launchd, the
    Windows SCM, docker.  They own start-at-boot, restart-on-crash and log
    collection; all this layer does is keep hass attached to the same process
    tree and turn one stop signal into an orderly shutdown.

    Deliberately *not* the orchestrator: no release probe, no unit writing, no
    MCP token, no setup gates, no config reconcile.  Those belong to the plain
    ``start``, and repeating them here would run them again on every crash
    restart — and, on the network probe, would stall a reboot behind a timeout.
    The one exception is waiting for a local address (``_wait_for_ipv4``), which
    is a precondition of hass rather than of the install: it is bounded, silent
    when there is nothing to wait for, and it has to sit where every supervisor
    will run it.
    """
    HA_ROOT.mkdir(parents=True, exist_ok=True)

    # One instance per HA_ROOT.  A second hass fails its 8123 bind halfway
    # through start-up and leaves a half-written .storage behind, so refuse
    # before spawning — and say which of the two cases this is, because the
    # fixes differ.
    pid = _ha_instance()
    if pid:
        log_state("FAIL", f"hass already running (PID {pid}) — stop it first: homeant stop")
        return 1
    if _hass_via_service():
        # Same refusal, different evidence: the supervisor owns an instance and
        # something answers on 8123, but the lock cannot name the pid.  Falling
        # through would let this foreground run fight it for the socket.
        log_state("FAIL", "hass is already running under the service — "
                          "stop it first: homeant stop")
        return 1
    if port_in_use(PORT):
        log_state("FAIL", f"port {PORT} is already in use by another program — "
                          f"stop it first, a second instance would fail its bind")
        return 1

    hb = hass_bin()
    if hb is None:
        # Foreground mode never installs anything: the supervisor's restart
        # policy would turn a download into an invisible retry loop, and the
        # installer is the only thing allowed to replace a tree.
        log_state("FAIL", "hass is not installed in this tree — run 'homeant start' once "
                          "(or uv sync) before using --foreground")
        return 1

    # Bounded wait for a local address: hass refuses to set up zeroconf without
    # one, and a supervisor's boot start runs before DHCP is done.  Here rather
    # than in the unit because systemd, launchd, the SCM and docker all pass
    # through this function, while the unit text is per-platform.
    _wait_for_ipv4()

    cmd = [str(hb), "--ignore-os-check", "--config", str(HA_ROOT)]
    # stdout/stderr are inherited on purpose: journald and `docker logs` want
    # hass's own lines, not ours relayed through a pipe.  No start_new_session
    # either — the supervisor's cgroup/job must be able to collect the whole
    # tree when it stops this process.
    try:
        child = subprocess.Popen(cmd, creationflags=_no_console_flags())
    except OSError as e:
        log_state("FAIL", f"cannot start hass — {e}")
        return 1

    log(f"foreground: hass PID {child.pid} — send SIGTERM here to stop it")

    forward = {"signum": 0, "at": 0.0, "killed": False}

    def _on_signal(signum, _frame) -> None:
        """Forward the first stop signal; ignore the rest.

        A second Ctrl+C must not shorten hass's flush window — .storage is being
        rewritten at that moment, and `homeant stop` would have waited the full
        STOP_WAIT_SEC for exactly this reason.
        """
        if forward["signum"]:
            return
        forward["signum"] = signum
        forward["at"] = time.monotonic()
        log("foreground: stopping hass ...")
        try:
            if IS_WIN:
                # Windows hass has no console to receive Ctrl+C and no signal to
                # catch, so TerminateProcess is the only stop there is — the
                # same conclusion _stop_pid reached for /F.
                child.kill()
            else:
                child.send_signal(signal.SIGTERM)
        except OSError:
            pass        # already gone; wait() below reports how it went

    saved: dict = {}
    for name in ("SIGTERM", "SIGINT"):
        sig = getattr(signal, name, None)
        if sig is None:
            continue
        try:
            saved[sig] = signal.signal(sig, _on_signal)
        except (OSError, ValueError, RuntimeError):
            pass        # not the main thread, or the platform refuses this one

    try:
        while True:
            try:
                rc = child.wait(timeout=1.0)
                break
            except subprocess.TimeoutExpired:
                if (forward["signum"] and not forward["killed"]
                        and time.monotonic() - forward["at"] > STOP_WAIT_SEC):
                    forward["killed"] = True
                    log(f"foreground: hass ignored the stop signal for {STOP_WAIT_SEC}s — killing it")
                    with contextlib.suppress(OSError):
                        child.kill()
    finally:
        for sig, old in saved.items():
            with contextlib.suppress(OSError, ValueError, RuntimeError):
                signal.signal(sig, old)

    if rc < 0:
        # Died by a signal: report the shell convention (128+n) rather than -n,
        # so the number a supervisor logs matches what an operator would see.
        rc = 128 + (-rc)
    log(f"foreground: hass exited with {rc}")
    return rc


def cmd_start(args) -> int:
    """Start hass, first bringing the install up to date.

    The single entry point: a fresh install, an upgrade and a plain "is it up?"
    all land here.  Every stage it runs is a gate, so a second invocation finds
    nothing left to do.
    """
    global SPAWNED_PID
    # Supervisor mode, first of all: the unit's ExecStart runs exactly this
    # command, and it must behave like a well-mannered child — no network
    # probe, no installer hand-off, no gates, and no exit until hass does.
    if getattr(args, "foreground", False):
        return _run_foreground()
    # The SCM host: same "be a well-mannered child" contract as --foreground,
    # one layer up, and equally free of gates, probes and setup stages.
    if getattr(args, "service_host", False):
        return _service_host_main()

    # Version check comes first: a newer release may ship a different
    # dependency probe, so the old build must not be the one deciding whether
    # this host is usable. Detection is read-only — nothing is touched until
    # the user says yes.
    # `--no-install` is what the installer passes to its own tail: it has just
    # unpacked the newest release and synced the venv, so probing the release
    # host and handing back to the installer are the two things that must not
    # happen again. Without it the chain py → installer → py would only end when the
    # network did.
    newer = None if args.no_install else _check_newer_version()
    if newer:
        return _run_installer(newer)

    # Dependency gate. Repair is never done here: the installer is the only
    # thing that knows how to download, replace and sync, and a second in-tree
    # copy of that is how two paths drift apart.
    #
    # An unsatisfied gate is not an error to be confirmed — it is a statement
    # that this tree is not the released one: uv reports the environment as
    # outdated, or hass is missing outright. `start` is defined as "make this
    # host serve the release", so it converges instead of asking: hand-editing
    # uv.lock is a deliberate deviation, and a prompt would only ask the user
    # to re-decide something they already decided by editing the file. The one
    # exception is `--no-install`: we just came from the installer and it is
    # still not fixed, so looping would only re-download the same bytes.
    why = _deps_why()
    if why:
        if args.no_install:
            log_state("FAIL", f"dependencies incomplete — {why}. "
                              f"Re-run the installer: {INSTALLER_URL}")
            return 1
        log(f"deps: {why}")
        return _run_installer(None, repairing=True)

    HA_ROOT.mkdir(parents=True, exist_ok=True)

    # Which supervisor this host has decides the whole launch path, and it is
    # decided before anything is stopped: "hass running with no unit" needs a
    # hand-over stop, "unit owns hass" must not be stopped at all, and a stop
    # between the two verdicts would leave neither state.
    svc = _service_kind()

    # Privilege gate, at the entry and before anything is touched.  Keeping the
    # home alive across a reboot is the one thing this design cannot do
    # unprivileged, and finding that out *after* a successful start is how a
    # promise becomes a postscript.  Refuse up front, name the exact command,
    # and leave the tree exactly as it was — the user fixes it in one line and
    # re-runs.  There is no "warning" variant of this verdict on purpose: a
    # start that cannot survive a reboot is not a start this layer may report
    # as done, whatever loginctl's wording happens to be.
    if svc == "systemd-user" and not _linger_ensure():
        return 1

    # Windows has a gate of the same shape for a different reason: the
    # registration lives in HKLM, so creating it needs administrator rights, and
    # an unattended `start` can never answer a UAC dialog.  Say it before
    # anything is touched — the files are already in place at this point, and
    # re-running the same command from an elevated prompt is the whole fix.
    if svc == "service" and not _service_registered() and not _is_admin():
        # The two lines are read together: "run as administrator" is the
        # condition, the command is what to run *once you are*.  The command is
        # deliberately the plain relative one — an absolute path or a
        # Start-Process incantation is harder to retype than to remember, and
        # this process still cannot elevate itself without blocking on a
        # prompt, which the design forbids everywhere.
        log_state("FAIL", "run as administrator")
        log("      run: .\\homeant start")
        return 1

    # An elevated `start` is the only moment this user can reach the SCM, so
    # spend it on the one setting an upgrade cannot reach.  A service registered
    # by an earlier build has the failure *actions* but not the flag that makes a
    # non-zero exit count as a failure, so a dead hass is never restarted.
    #
    # It sits before the "already running" branch on purpose: repairing a live
    # install is exactly how a user meets it, and that branch returns before
    # _win_service_ensure ever runs (measured on the real machine: an elevated
    # `start` on a running home printed nothing at all).  Guarded by _is_admin()
    # so the unprivileged path still makes zero SCM calls.
    if svc == "service" and _is_admin():
        _win_ensure_crash_recovery()

    # Windows counterpart of the autostart gate above, for a platform where the
    # change needs a right this prompt may not hold.  Two facts decide it: the
    # registry says the service is demanded-only (free to read), and this prompt
    # is not elevated.  Failing here is the point — bringing hass up first and
    # then admitting autostart stays off would be the half-success that makes
    # `start` and `disable` disagree about what "done" means.  A missing value
    # means "could not read", not "needs fixing", so it never blocks a start.
    if svc == "service" and _win_service_installed():
        start_type = _win_reg_value("Start")
        if start_type not in (None, "2"):
            if not _is_admin():
                log_state("FAIL", "run as administrator")
                log("      the service is set to start on demand — "
                    "putting it back to automatic needs an elevated prompt")
                log("      run: .\\homeant start")
                return 1
            if not _win_service_set_start(True):
                return 1

    # Autostart is part of what this verb promises: `start` means "serve the
    # release, and keep serving it after a reboot", and `disable` is the only
    # way out of that.  It therefore belongs *before* the "already running"
    # branch below, which returns early: a home left disabled but still running
    # would otherwise answer "already running", return, and never get its
    # autostart back — silently breaking this verb's own contract.  The cost is
    # one `systemctl is-enabled` per start, spent only when a unit exists.
    if svc == "systemd-user" and UNIT_PATH.exists() and not _service_enable():
        # Nothing was started or stopped here: a home that is already running
        # keeps running, it just will not come back at the next boot.
        return 1

    # macOS counterpart of the gate above.  launchd's `disable` is a mask, so a
    # label left disabled cannot be bootstrapped at all — it answers with a bare
    # "5: Input/output error" (measured 11-07).  Clearing the record here means
    # the cold path below finds a loadable label, and the running path (which
    # returns early) still restores the setting it is responsible for.
    if svc == "launchd" and UNIT_PATH.exists() and not _launchd_set_enabled(True):
        return 1

    # `start` is idempotent: a running hass already *is* the state we were asked
    # for, so stopping it would only interrupt the user.  Hand-edited config
    # therefore needs an explicit stop + start, not a bare `start`.
    #
    # Two witnesses for "running", because T11 removed the process scan: the
    # lock names the pid, and when the lock cannot (deleted while hass keeps
    # serving from memory) the supervisor plus a bound port still prove that an
    # instance of ours is up — the service cannot be alive with its hass dead,
    # and 8123 is the only port this home ever binds.
    pid = _ha_instance()
    running = bool(pid) or _hass_via_service()
    if pid:
        log(f"hass already running (PID {pid})")
    elif running:
        log("hass already running (via service)")

    # A hass started by a build that had no service still answers on 8123, so
    # starting the supervisor would fail its bind while this process reported
    # "already running" and returned — the tree would stay one version behind
    # forever.  Stop it, then let the cold path bring it up the new way.
    #
    # T11 wanted this gone, and it cannot be: the audit found that removing it
    # makes a pre-service tree unable to ever register (the idempotent branch
    # above returns first).  `_stop_own_hass` reaches its pid branch here by
    # definition — the condition itself says nothing is registered.
    if running and svc in ("systemd-user", "service", "launchd") and not _service_registered():
        manager = {"systemd-user": "systemd", "service": "the Windows service",
                   "launchd": "launchd"}[svc]
        log(f"hass running outside the service manager — "
            f"moving it under {manager}")
        if not _stop_own_hass():
            log_state("FAIL", "the running hass did not exit — "
                              "cannot hand it over to the service manager")
            return 1
        pid = None
        running = False

    # A hass still running out of a HA_ROOT that lost its configuration.yaml is
    # answering from memory alone: .storage writes fail, so every stage below
    # would report a success that evaporates on the next boot.  That is not the
    # state `start` was asked for, so it recovers instead of reporting — stop,
    # fall through, and let the cold path deploy the seed again.  Same predicate
    # `status` uses for its FAIL line: one fact, so the two cannot disagree.
    #
    # The stop goes to the supervisor when there is one: killing its child
    # directly is indistinguishable from a crash, and the SCM/systemd would
    # restart the home about ten seconds later — in the middle of this redeploy
    # (measured on Windows: exit code 1066 plus the failure actions).
    if running and not _seed_present():
        log(f"hass running without configuration.yaml under {HA_ROOT} — redeploying")
        if not _stop_own_hass():
            # Deploying under a live hass would be undone by its own shutdown
            # flush, so this path stops rather than tries.
            log_state("FAIL", "the running hass did not exit — "
                              "cannot redeploy its configuration under it")
            return 1
        pid = None
        running = False

    if running:
        # The three setup stages are still owed, and this rerun is exactly how a
        # first install resumes: the user just added the hosts entry or finished
        # OAuth in a browser.  Returning `status` here would answer a question
        # nobody asked and never move the chain forward.
        #
        # "Already running" can also mean "started 3 seconds ago", so the same
        # ordering as the cold path applies: token first, gate, then the probe.
        mcp_fail: dict = {}
        tok = _mcp_token(fail=mcp_fail)
        if mcp_fail.get("kind") == "login" and not _provider_has_user(cf("USERNAME", "admin")):
            # Half provisioned: .storage/auth has the owner but the password
            # store has no such user, so *no* password can ever match and
            # editing the cfg is a dead end.  Provisioning needs hass stopped,
            # so fall through to the cold path — it re-provisions and spawns in
            # the same pass, which also bounds the recovery to one attempt (the
            # cold path never returns here).
            log("admin user missing from the password store — re-provisioning")
            if not _stop_own_hass():
                log_state("FAIL", "the running hass did not exit — cannot re-provision "
                                  "its admin account under a running instance")
                return 1
            pid = None
            running = False
        else:
            _wait_for_ha_running()
            return _finish_setup(_ensure_mcp_ready(mcp_fail, tok=tok), mcp_fail)

    # No hass of ours is running at this point, so a listening 8123 belongs to
    # somebody else: the boot below would fail its bind, while the readiness
    # loop cheerfully reported "ready in 0.4s" because all it asks is whether
    # *something* answers on the socket.  The installer refuses the same case
    # before it downloads anything; this is the same verdict for the
    # `start`-only path, and it runs before the seed and the auth provisioning
    # touch anything.
    if port_in_use(PORT):
        log_state("FAIL", f"port {PORT} is already in use by another program — "
                          f"stop it, then run 'homeant start' again")
        return 1

    # Deploy the repo seed while hass is down (copy-or-merge per file; storage
    # entry sync refuses while hass is running).  Skipped outright when the
    # seed fingerprint already matches — see _ensure_seed.
    _ensure_seed()

    # Provision the owner into .storage/auth while hass is down — HA has no
    # runtime API for "create user with password".
    _ensure_auth_offline()

    hb = hass_bin()
    assert hb is not None
    cmd = [str(hb), "--ignore-os-check", "--config", str(HA_ROOT)]

    if svc == "none":
        # Containers and bare hosts: nothing to register with, and inventing a
        # supervisor is what this design refuses to do.  Say the one thing that
        # is actionable and carry on the old way.  Printed before the progress
        # line, which is a partial line waiting for its first dot.
        log("no service manager here — to supervise it yourself: ./homeant start --foreground")

    t_boot = time.monotonic()

    if svc == "systemd-user":
        # From here the unit is the only start source: install, enable, start,
        # then wait for HTTP exactly as the spawned case does.  Popen here would
        # put two owners on one port — and systemd would then keep racing us.
        child_pid = _service_up()
        if not child_pid:
            return 1
        alive = _service_active
    elif svc == "service":
        # The SCM is the only start source on Windows, for the same reason, and
        # the gate above guaranteed there is a registration to start (or the
        # rights to create one).  `_win_service_ensure` usually has nothing to
        # do: ImagePath and the profile value already point at this tree.
        if not _win_service_ensure():
            return 1
        if not _win_service_start():
            _win_reap()
            return 1
        # The SCM reports no MainPID — hass writes its own lock, and the ready
        # branch below reads the pid from there, exactly as `status` does.
        child_pid = 0
        alive = lambda: _win_service_state() == "running"  # noqa: E731
    elif svc == "launchd":
        # Same rule as systemd: once the plist exists, launchd is the only
        # start source, and a Popen here would put two owners on one port.
        # launchd does report a pid, but it is the wrapper's — the log line
        # below wants hass's, which the ready branch reads from the lock.
        child_pid = _service_up_launchd()
        if not child_pid:
            return 1
        alive = _launchd_active
    else:
        # No supervisor at all (containers and bare hosts).  The detached spawn
        # is the last resort on purpose: two start sources on one port is the
        # failure this whole section exists to prevent, so it only runs where
        # there is nothing to register with.
        p = subprocess.Popen(
            cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            start_new_session=True, creationflags=_no_console_flags(),
        )
        child_pid = p.pid
        # Only a child *this* process launched may be killed by its atexit hook.
        # In service mode SPAWNED_PID deliberately stays 0: hass belongs to the
        # supervisor, and killing it on our way out would look like a crash and
        # trigger the restart policy.
        SPAWNED_PID = child_pid
        if callable(globals().get("_mark_we_started_hass")):
            _mark_we_started_hass()  # type: ignore[name-defined]  # noqa: F821  (monkey-patched by _register_cleanup)
        alive = lambda: pid_exists(child_pid)  # noqa: E731

    # The progress line opens *after* the start verb, not before it: registering
    # the service prints "service installed: …" exactly once, and that line used
    # to land inside this half-finished one — `starting hass [homeant] service
    # installed: homeant`, dots on a line of their own.  Anything the supervisor
    # has to say about itself belongs above the wait, not in the middle of it.
    log_partial("starting hass ")

    # wait for HA ready - one dot per second, same cadence as the installer's
    # extract ticker: a cold start takes tens of seconds and a silent console
    # reads as a hang.  "Ready" means answering HTTP, not just holding the port:
    # 0.5s (or much more, cold) passes between the socket being bound and the
    # server accepting, and anything we send in that gap is dropped.
    #
    # The ceiling is 5 minutes, not 1, because a cold start is only fast on a
    # local filesystem.  Measured on WSL2 with the tree on /mnt/d (drvfs/9p):
    # the first boot after a fresh extract needed 86s to answer HTTP, the same
    # tree warm needed 8s - the difference is the first read of ~19k source
    # files through the 9p server, not anything wrong with HA.  A 60s ceiling
    # killed that boot 26 seconds before it finished, and reported it as
    # "did not come up".  Only the clock got longer: a dead process still
    # breaks out on the next tick, so a genuinely broken boot is reported just
    # as fast as before.
    for _ in range(SERVICE_START_TIMEOUT):
        log_tick()
        time.sleep(1)
        if alive() and _hass_serving():
            print(flush=True)
            if not child_pid:
                # Only the Windows service path lands here: the SCM reports no
                # MainPID, so the pid comes from HA's own lock file — the same
                # record `status` reads.  Zero means it was not written yet;
                # "service" then names the owner honestly instead of "PID 0".
                child_pid = _ha_instance() or 0
            who = f"PID {child_pid}" if child_pid else "service"
            log(f"hass started ({who}, ready in {time.monotonic() - t_boot:.1f}s)")
            # Two separate moments, in this order:
            #
            # 1. Mint/cache the MCP token BEFORE the RUNNING gate: the gate
            #    authenticates with it, so on a fresh install (no .mcp-token
            #    yet) it would otherwise bail out immediately with "core state
            #    probe skipped" — dead exactly when it matters most.
            # 2. Probe the endpoint only AFTER the gate.  "Answering HTTP" and
            #    "integrations loaded" are seconds apart — measured on this
            #    machine: port ready 4.1s, core RUNNING 11.4s — and mcp_server's
            #    /api/mcp route exists only once its config entry is set up.
            #    Probing in that gap 404s, and since the verdict is frozen into
            #    mcp_fail it survives the gate and is printed as the final
            #    answer a minute later.
            mcp_fail: dict = {}
            tok = _mcp_token(fail=mcp_fail)
            _wait_for_ha_running(t0=t_boot)
            return _finish_setup(_ensure_mcp_ready(mcp_fail, tok=tok), mcp_fail)
        if not alive():
            break
    print(flush=True)
    log_state("FAIL", f"hass did not come up — check {HASS_LOG}")
    if svc == "systemd-user":
        # Restart=on-failure would retry every 10s from here, invisibly, while
        # the port stays free and nothing explains why.
        _service_reap()
    elif svc == "service":
        # Same reason: the SCM's failure actions would keep restarting a home
        # that cannot boot, and the evidence is in the service log.
        _win_reap()
    return 1


def _stop_pid(pid: int) -> bool:
    """Kill the hass at `pid`; True once it is provably gone.

    Windows: /F from the first attempt.  ``taskkill /T`` without /F cannot touch
    a detached console process — measured: exit 128, "can only be terminated
    forcefully" — so the old nice-then-force dance burned a guaranteed 10s on
    every stop.  There is no graceful path to preserve anyway: hass is started
    with DETACHED_PROCESS, so it has no console to receive Ctrl+C.

    POSIX: SIGTERM the process *group* when the pid leads one.  `start` uses
    start_new_session=True, so pid == pgid, and this is exactly what install.sh
    does with `kill -TERM -$pid` — signalling only the leader would leave the
    workers holding the venv.  A hass started some other way may share the
    caller's group, and signalling *that* would take the user's shell down with
    it, hence the pgid == pid test.

    The return value matters: SIGKILL is asynchronous, and the caller may be
    about to rewrite .storage/auth or .storage/core.config_entries.  A dying
    hass flushes its own stores on the way out, so "sent the signal" is not
    "safe to write" — both platforms therefore wait for the process to actually
    disappear before reporting success.
    """
    log(f"stopping hass (PID {pid}) ...")
    if IS_WIN:
        subprocess.run(["taskkill", "/PID", str(pid), "/F", "/T"],
                       capture_output=True, creationflags=_no_console_flags())
        for _ in range(20):
            if not pid_exists(pid):
                return True
            time.sleep(0.5)
        return False
    try:
        pgid = os.getpgid(pid)
    except ProcessLookupError:
        pgid = None
    signal_fn = os.killpg if pgid == pid else os.kill
    target = pgid if pgid == pid else pid
    try:
        signal_fn(target, signal.SIGTERM)
    except (ProcessLookupError, PermissionError):
        pass
    for _ in range(60):
        if not pid_exists(pid):
            return True
        time.sleep(0.5)
    try:
        signal_fn(target, signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        pass
    # SIGKILL cannot be ignored, but the process still needs scheduling time to
    # die; without this wait the very next write races its exit flush.
    for _ in range(20):
        if not pid_exists(pid):
            return True
        time.sleep(0.5)
    return False


def cmd_stop(args) -> int:
    """Stop the home.  Registration and autostart both stay as they are.

    One verb, spelled the same way on every platform, because the underlying
    operation is the same one everywhere: end the process.  ``systemctl stop``,
    ``launchctl bootout`` and ``SERVICE_CONTROL_STOP`` differ in name only, and
    each is the *single* word its supervisor has for it.

    ``disable`` is deliberately not part of it.  Autostart is a property of the
    registration, not of this run, and the three platforms cannot agree on who
    may change it: `systemctl --user disable` and `launchctl disable` are
    unprivileged, while changing a Windows service's start type needs
    ``SERVICE_CHANGE_CONFIG`` — the same right that would let its holder repoint
    the binary somewhere else (measured 11-07: ``OpenService`` with that mask →
    access denied for a plain user, and install grants ``IU`` only ``RP``/``WP``
    for exactly this reason).  Disabling here would therefore mean doing it on
    two platforms and quietly not doing it on the third — one flag, three
    behaviours.  So it happens in neither: ``uninstall`` removes the
    registration, and a removed registration does not come back.

    Consequence, stated plainly rather than discovered later: a stopped home
    that is still installed starts again at the next boot or GUI login.

    Measured 11-05: leaving the unit enabled does *not* bring the process back
    by itself either — ``Restart=on-failure`` reacts to unexpected exits, and a
    stop request is an expected one — so there is nothing to undo here and no
    ordering trick to play.

    Linger is left untouched too: it says whether the user's manager survives a
    logout, which has nothing to do with this home.

    An unregistered tree — and any host with no supervisor at all — keeps the
    old path exactly: find the process, kill it, wait for it to be gone.
    """
    service_stopped = False
    if _service_kind() == "systemd-user" and UNIT_PATH.exists():
        r = _systemctl("stop", SERVICE_NAME)
        if r is None or r.returncode != 0:
            # Silence here would read as "stopped" while systemd keeps the
            # home alive behind us — the one outcome this must never fake.
            chatter = ((r.stderr or "") + (r.stdout or "")).strip() if r else ""
            why = (chatter.splitlines()[-1] if chatter
                   else f"systemctl exited {r.returncode}" if r
                   else "systemctl is unavailable")
            log_state("FAIL", f"cannot stop the service — {why}")
            return 1
        service_stopped = True
    elif _service_kind() == "service" and _win_service_installed():
        # Same one verb as Linux.  Start-at-boot was set once at install and is
        # left alone here — see the docstring for why it cannot be otherwise.
        if not _win_service_stop():
            return 1
        service_stopped = True
    elif _service_kind() == "launchd" and UNIT_PATH.exists():
        # Same one verb again: `bootout` unloads the job and leaves the plist in
        # place.  `launchctl disable` exists and is unprivileged, but it is not
        # used here on purpose — the contract is identical on all three
        # platforms, and "stays stopped across a reboot" belongs to `uninstall`.
        if not _launchd_bootout():
            return 1
        service_stopped = True

    # Asked *after* the supervisor, and by the same predicate start and status
    # use: a hass the unit never owned (a bare `start` from before this tree was
    # registered) is still ours to stop.
    pid = _ha_instance()
    if not pid:
        log("hass stopped" if service_stopped else "hass not running")
        return 0

    if not _stop_pid(pid):
        log_state("FAIL", f"hass (PID {pid}) is still running — "
                          f"it may be stuck in shutdown; try again or kill it by hand")
        # A hass the service left behind runs as LocalSystem, so taskkill is
        # refused outright — measured: rc=255, "access denied" — and a hand-run
        # kill from the same window is refused for the same reason.  Saying so
        # beats repeating advice that cannot work here.
        if IS_WIN and not _is_admin():
            log("      if it belongs to the service, killing it needs an elevated prompt")
        return 1
    log("hass stopped")
    return 0


def cmd_disable(args) -> int:
    """Turn off start-at-boot.  The running home is not touched.

    The mirror image of what `start` does to autostart, and one of only two
    verbs that change it (`uninstall` is the other, by removing the
    registration).  `stop` deliberately does not, on every platform and for the
    same reason: it ends a process and nothing else.

    Calling `start` afterwards turns autostart back on.  That is the documented
    price of keeping `start` as the single "make this host serve" verb, so the
    help text says it instead of letting it be discovered.

    A host with no registration has nothing to disable.  That is a failure
    rather than a quiet no-op: the only reason to run this verb is to change a
    boot setting, so answering "done" when there is none would be a lie.
    """
    kind = _service_kind()
    if kind == "systemd-user":
        if not UNIT_PATH.exists():
            log_state("FAIL", "nothing is registered — run: homeant start first")
            return 1
        if not _service_disable():
            return 1
        log("autostart off")
        return 0
    if kind == "service":
        if not _win_service_installed():
            log_state("FAIL", "nothing is registered — run: homeant start first")
            return 1
        if not _win_service_set_start(False):
            return 1
        log("autostart off")
        return 0
    if kind == "launchd":
        if not UNIT_PATH.exists():
            log_state("FAIL", "nothing is registered — run: homeant start first")
            return 1
        if not _launchd_set_enabled(False):
            return 1
        log("autostart off")
        return 0
    log_state("FAIL", "nothing is registered — run: homeant start first")
    return 1


# ── uninstall ────────────────────────────────────────────────────────────────

def _service_unregister() -> tuple[bool, str | None]:
    """Stop the supervisor and delete its registration.

    Returns ``(ok, what was removed)``.  ``ok`` is False only when the service
    is still standing: deleting the data directory under a running home is how
    the stores get written back from memory after they are already gone.
    """
    kind = _service_kind()
    if kind == "systemd-user":
        if not UNIT_PATH.exists():
            return True, None
        # Two verbs here, and this is the only place that uses the first one.
        # `stop` alone deliberately leaves autostart enabled (see cmd_stop);
        # uninstall is the verb that means "do not come back", so it is also
        # the one that clears the autostart symlink.  Both must succeed before
        # the unit file goes, otherwise the supervisor is still watching a
        # directory we are about to empty.
        for verb in ("disable", "stop"):
            r = _systemctl(verb, SERVICE_NAME)
            if r is None or r.returncode != 0:
                chatter = ((r.stderr or "") + (r.stdout or "")).strip() if r else ""
                why = (chatter.splitlines()[-1] if chatter
                       else f"systemctl exited {r.returncode}" if r
                       else "systemctl is unavailable")
                log_state("FAIL", f"cannot {verb} the service — {why}")
                return False, None
        UNIT_PATH.unlink(missing_ok=True)
        _systemctl("daemon-reload")
        return True, f"service unit removed: {UNIT_PATH}"
    if kind == "service":
        # pywin32 speaks SCM directly.  The old version shelled out to `sc.exe`
        # and swallowed a missing binary as "nothing registered" — which made a
        # refused deletion look like success.  Every failure below is real, and
        # uninstall keeps the data when one of them happens.
        return _win_service_unregister()
    if kind == "launchd":
        had_plist = UNIT_PATH.exists()
        # bootout first: deleting a plist under a loaded job leaves launchd
        # running a definition that is no longer on disk, and uninstall is about
        # to empty the directory that job serves.
        if had_plist:
            if not _launchd_bootout():
                return False, None
            UNIT_PATH.unlink(missing_ok=True)
        # `launchctl disable` writes a record into the GUI domain that outlives
        # the plist (measured 11-07): a leftover "disabled" label is a mask the
        # next `start` cannot bootstrap through, and its enable gate skips the
        # repair precisely when the plist is gone.  Clearing the ledger belongs
        # to removing the registration; it is a no-op when no record exists.
        ledger_disabled = _autostart_state() is False
        if ledger_disabled and not _launchd_set_enabled(True):
            return False, None
        notes = [f"service plist removed: {UNIT_PATH}"] if had_plist else []
        if ledger_disabled:
            notes.append("launchd disabled record cleared")
        return True, "; ".join(notes) or None
    return True, None


def _uninstall_guard() -> str | None:
    """Why deleting HA_ROOT must be refused, or None when it is safe.

    Typing ``uninstall`` is the decision, so none of this asks a question.  The
    checks exist for a *wrong* HA_ROOT — a bug, a hand-edited path, a symlink
    planted where the data dir should be — and each one is cheaper than the
    deletion it prevents.
    """
    if HA_ROOT.is_symlink():
        return f"refusing to delete {HA_ROOT} — it is a symbolic link"
    if not HA_ROOT.is_dir():
        return f"refusing to delete {HA_ROOT} — it is not a directory"
    resolved = HA_ROOT.resolve()
    if resolved.name != ".homeant":
        return (f"refusing to delete {resolved} — its last component is "
                f"not '.homeant'")
    for wrong in (Path.home().resolve(), PROJECT_ROOT.resolve(),
                  Path(resolved.anchor)):
        if resolved == wrong:
            return f"refusing to delete {resolved} — that is {wrong}"
    return None


def _tree_size(path: Path) -> tuple[int, int]:
    """(entry count, bytes) of a directory, counting links as links."""
    files = 0
    total = 0
    for dirpath, _dirnames, filenames in os.walk(path, followlinks=False):
        for name in filenames:
            files += 1
            try:
                total += os.lstat(os.path.join(dirpath, name)).st_size
            except OSError:
                pass            # vanished mid-walk; the count is documentary
    return files, total


def _discard(path: Path) -> bool:
    """Delete ``path`` outright: no trash, no prompt, no second copy.

    Typing `uninstall` is the decision, and the expected outcome is a direct
    delete (jiqia 21:4x).  The data directory is the only thing ever passed
    here; the program tree is deliberately left in place.
    """
    try:
        shutil.rmtree(path)
    except OSError as e:
        log_state("FAIL", f"cannot remove {path} — {e}")
        return False
    return not path.exists()


def cmd_uninstall(args) -> int:
    """Remove the service registration and the data dir.

    Order is the whole safety story: the supervisor goes first (so nothing
    restarts it), then any hass the supervisor never owned (so nothing flushes
    its stores into a directory that is being emptied), and only then the files.
    The source tree is never touched — it is where this script lives, and this
    is a portable install.  Every file this project creates lives in HA_ROOT,
    so removing that one directory is the whole cleanup.

    There is no --keep-data and no prompt: typing this verb is the decision.
    Keeping the data is what `stop` is for.  The delete is outright — no
    Recycle Bin — and `status` / a second `uninstall` deliberately keep their
    current behaviour (jiqia 21:4x).
    """
    ok, removed = _service_unregister()
    if not ok:
        return 1
    notes = [removed] if removed else []

    # One last process check after the service is gone: a hass started by hand
    # (or by a build from before this tree was registered) is invisible to the
    # supervisor but writes to HA_ROOT all the same.
    pid = _ha_instance()
    if pid:
        if not _stop_pid(pid):
            log_state("FAIL", f"hass (PID {pid}) is still running — it may be "
                              f"flushing its stores; nothing was deleted")
            return 1
        notes.append(f"stopped hass (PID {pid})")

    if not HA_ROOT.exists():
        for note in notes:
            log(note)
        log("data already gone" if notes else "nothing to uninstall")
        return 0

    why = _uninstall_guard()
    if why:
        log_state("FAIL", why)
        return 1

    files, size = _tree_size(HA_ROOT)
    # Printed before the deletion, and phrased as a record rather than a
    # question: after it runs, this line is the only account of what was there.
    log(f"removing {HA_ROOT} ({files} files, {size / 1e6:.1f} MB)")
    if not _discard(HA_ROOT):
        return 1
    for note in notes:
        log(note)
    log("data removed")
    return 0


def cmd_logs(args) -> int:
    if not HASS_LOG.exists():
        log(f"no hass log at {HASS_LOG}")
        return 1
    log(f"streaming {HASS_LOG} (Ctrl+C to exit)")
    try:
        with open(HASS_LOG, "r", encoding="utf-8", errors="replace") as f:
            f.seek(0, 2)
            while True:
                line = f.readline()
                if not line:
                    time.sleep(0.2)
                    continue
                sys.stdout.write(line)
                sys.stdout.flush()
    except KeyboardInterrupt:
        print()
        return 0



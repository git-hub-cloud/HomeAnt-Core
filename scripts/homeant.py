# ── process helpers ─────────────────────────────────────────────────────────

# pid of the hass *this process* spawned, 0 when it spawned none.  In memory on
# purpose: its only consumer is the atexit/signal cleanup, which by definition
# cannot run after this process is gone — writing it to disk would keep a record
# alive for a run that no longer exists, which is exactly what .hass.pid used to
# do and why a stale copy could be mistaken for a running instance.
SPAWNED_PID = 0


def pid_exists(pid: int) -> bool:
    if IS_WIN:
        # tasklist emits ANSI code page text on zh-CN Windows; text=True would
        # decode as UTF-8 and leave stdout=None. Pin the preferred encoding.
        r = subprocess.run(
            ["tasklist", "/FI", f"PID eq {pid}"], capture_output=True, text=True,
            encoding=locale.getpreferredencoding(False), errors="ignore")
        return r.stdout is not None and str(pid) in r.stdout
    try:
        os.kill(pid, 0)
        return True
    except (ProcessLookupError, PermissionError):
        return False


def _cmdline_is_hass(cmd: str) -> bool:
    """True when a full command line is an HA that serves HA_ROOT.

    ``--config`` is part of the test on purpose.  Without it any process that
    merely *mentions* the config dir passes — a `grep hass ~/.homeant/...`, a
    `tail -f` on the log, an editor holding it open — and the caller is about
    to kill whatever this function approves.

    Windows does not require the word "hass": the launcher hands the entry point
    over inside ``-c``, so the child's argv is only ``--ignore-os-check
    --config <root>``.  Root plus --config is specific enough there, and both
    sides are normalised because the same root reaches a process as
    ``C:\\Users\\x\\.homeant`` or ``C:/Users/x/.homeant`` depending on who
    typed it (measured: Git Bash rewrites the backslashes).
    """
    if IS_WIN:
        c = cmd.replace("\\", "/").lower()
        return "--config" in c and str(HA_ROOT).replace("\\", "/").lower() in c
    return "--config" in cmd and str(HA_ROOT) in cmd and "hass" in cmd


def _proc_image(pid: int) -> str:
    """Kernel's name for `pid` (/proc/<pid>/comm), lowercased; '' if unreadable."""
    try:
        return Path(f"/proc/{pid}/comm").read_text(
            encoding="utf-8", errors="replace").strip().lower()
    except OSError:
        return ""


def _pid_is_hass(pid: int) -> bool:
    """Cheap pid-reuse guard for a pid read out of .ha_run.lock.

    That file outlives every instance that ever ran in this config dir, so by
    the time we read it the number inside may belong to something unrelated —
    and the caller is about to SIGTERM or taskkill it.  Looking at what the
    process actually is costs microseconds and turns "probably ours" into
    "provably hass".
    """
    if IS_WIN:
        r = subprocess.run(
            ["tasklist", "/FI", f"PID eq {pid}", "/FO", "CSV", "/NH"],
            capture_output=True, text=True,
            encoding=locale.getpreferredencoding(False), errors="ignore")
        image = (r.stdout or "").lower()
        # HA records the real python child's pid, not the hass.exe trampoline's.
        return "hass" in image or "python" in image
    try:
        raw = Path(f"/proc/{pid}/cmdline").read_bytes()
    except OSError:
        return True   # no /proc (macOS): liveness alone has to do
    image = _proc_image(pid)
    if image and not (image.startswith("python") or "hass" in image):
        return False
    return _cmdline_is_hass(raw.replace(b"\x00", b" ").decode("utf-8", "replace"))


def _scan_hass_process() -> int | None:
    """Find the HA that serves HA_ROOT by looking at processes, not at files.

    Reached whenever .ha_run.lock cannot answer: it is missing, unreadable or
    truncated, or the pid inside has died or been recycled onto something that
    is not hass.  Missing counts — the records are plain files and can be
    deleted while hass keeps running, and then this scan is the only thing left
    that can find it.

    On Windows the answer is usually python.exe: hass.exe is only the launcher
    and it forwards --config to the child.  When the launcher shows up too it is
    preferred, because `taskkill /T` on it reaps the child in one call.
    """
    if IS_WIN:
        # No tasklist field exposes the command line, so this has to go through
        # CIM (costs a PowerShell start-up, ~1s).  Acceptable on a rare path —
        # and stop has to wait for the process to disappear anyway.  The filter
        # only narrows by image name; matching happens back in Python so both
        # platforms use one rule.
        ps = (
            "Get-CimInstance Win32_Process "
            "-Filter \"Name='python.exe' OR Name='hass.exe'\" | "
            "ForEach-Object { '{0}|||{1}|||{2}' -f $_.ProcessId, $_.Name, $_.CommandLine }"
        )
        try:
            r = subprocess.run(
                ["powershell", "-NoProfile", "-NonInteractive", "-Command", ps],
                capture_output=True, text=True, timeout=15,
                encoding=locale.getpreferredencoding(False), errors="ignore")
        except (OSError, subprocess.SubprocessError):
            return None
        found: list[tuple[int, str]] = []
        for line in (r.stdout or "").splitlines():
            parts = line.split("|||")
            if len(parts) >= 3 and parts[0].strip().isdigit():
                if _cmdline_is_hass(parts[2]):
                    found.append((int(parts[0]), parts[1].strip().lower()))
        for pid, image in found:
            if "hass" in image:
                return pid
        return found[0][0] if found else None

    try:
        entries = list(Path("/proc").iterdir())
    except OSError:
        return None   # no /proc (macOS): nothing to scan, stay honest
    me = os.getpid()
    for entry in entries:
        if not entry.name.isdigit() or int(entry.name) == me:
            continue
        pid = int(entry.name)
        # Image name first.  `bash -c "... hass ... --config <root> ..."` carries
        # the exact same words in its own argv (measured: the wrapper shell came
        # back as a hit, one pid ahead of the dummy hass it was running), and
        # killing the shell that launched hass is worse than missing hass.
        image = _proc_image(pid)
        if image and not (image.startswith("python") or "hass" in image):
            continue
        try:
            raw = (entry / "cmdline").read_bytes()
        except OSError:
            continue
        if _cmdline_is_hass(raw.replace(b"\x00", b" ").decode("utf-8", "replace")):
            return pid
    return None


def _ha_instance() -> int | None:
    """PID of the HA that owns HA_ROOT, or None when there provably is none.

    The single authority for "is an instance running": callers no longer keep a
    pid file of their own, so every command asks this one question and gets one
    answer.  It sees instances nothing else can — started by hand, or by an
    earlier run whose records were deleted — which is what keeps `start` from
    launching a second hass that dies on HA's single-instance lock while
    ``_hass_serving()`` answers from the old one.
    """
    try:
        info = json.loads(HA_LOCK_FILE.read_text(encoding="utf-8") or "{}")
        pid = int(info.get("pid") or 0)
    except FileNotFoundError:
        # Not "nothing is running": the lock can be gone while hass keeps
        # running — deleted by hand, by a cleanup tool, or by a `git clean` in
        # the wrong directory.  Measured: with both records removed and hass
        # alive, the old early return printed "hass not running" and left the
        # process running, so `start` would then report a start that was really
        # the old instance answering on 8123.
        return _scan_hass_process()
    except (OSError, ValueError, TypeError, AttributeError):
        return _scan_hass_process()
    if pid > 0 and pid_exists(pid) and _pid_is_hass(pid):
        return pid
    # The lock file outlives every instance (runner.py never unlinks it), so a
    # dead or recycled pid says nothing about what is running *now* — least of
    # all on Windows, where fcntl is None and HA's own single-instance lock is
    # inert, so two instances can genuinely coexist behind a single lock file.
    return _scan_hass_process()


def port_in_use(port: int) -> bool:
    """True when *something* is listening on IPv4 — the protocol is never checked.

    A completed TCP connect only says a socket accepted; the peer may be HTTP,
    SSH, netcat, or anything else, and bind() would fail the same way for all of
    them.  That is exactly the question the port gate asks, so it stays a bare
    connect.  Anything that needs to know whether HA itself is answering must
    use ``_hass_serving()``, which speaks HTTP.

    IPv4 loopback only, deliberately not ``localhost``: HA binds both stacks by
    default (components/http/server.py: ``DEFAULT_BIND = ["0.0.0.0", "::"]``,
    and the deployed configuration.yaml sets no ``server_host``), so 127.0.0.1
    always sees our own instance.  ``localhost`` instead walks the name's whole
    address list — two addresses here — and on Windows a *refused* connect is
    not cheap: measured 2.04s for every closed port (8123, 9, 65000 alike)
    against 0.015s for an open one, so the second attempt doubled this call to
    4.07s and bought nothing.

    No platform branch, on purpose.  The extra address could only ever report a
    process holding ``::1`` alone, which cannot coexist with our own HA (it
    binds ``::`` too) and would surface one step later as a failed bind rather
    than as this gate's clear message.  Linux refuses in microseconds either
    way, so forking behaviour by OS would add a branch that changes nothing
    measurable anywhere.  See _hass_serving for the question this one does not
    answer.
    """
    try:
        s = socket.create_connection(("127.0.0.1", port), timeout=5)
        s.close()
        return True
    except OSError:
        return False


def _hass_serving(timeout: float = 1.5) -> bool:
    """True only once HA answers HTTP — holding the port is not enough.

    The ``http`` component binds its sockets during setup with
    ``start_serving=False`` and starts accepting only when ``frontend`` has
    finished setting up (components/http/server.py: ``async_bind`` vs
    ``start``), so a bare TCP connect succeeds half a second — far more on a
    cold guest — before any request is answered.  A request landing in that gap
    gets EOF instead of a response, which is exactly the RemoteDisconnected that
    used to kill the login POST.
    """
    import urllib.request as _ur
    try:
        with _ur.urlopen(f"http://localhost:{PORT}/", timeout=timeout):
            return True
    except _ur.HTTPError:
        return True     # any status at all proves the server is accepting
    except Exception:
        return False    # refused, reset, or still sitting unaccepted


def _uv_bin() -> Path | None:
    """The uv the installer would use — project-local .tools first, then PATH.

    Same order as install.ps1:416-424 and install.sh:451-462, so the checker
    and the thing it is checking for agree on which uv is authoritative.
    """
    name = "uv.exe" if IS_WIN else "uv"
    local = PROJECT_ROOT / ".tools" / "uv" / name
    if local.exists():
        return local
    found = shutil.which("uv")
    return Path(found) if found else None


def _deps_why() -> str:
    """Empty when .venv satisfies uv.lock, otherwise the reason it does not.

    `uv sync --check` asks uv itself what the lock wants and what is installed,
    and answers without writing anything — no state file of ours to keep
    honest.  --inexact matches the installer's own sync, so the packages HA
    installs at runtime from integration manifests (frontend, hassil, numpy
    ...) are not counted as drift.

    A missing or unrunnable uv is not a mismatch — it means we cannot answer.
    The honest response to "cannot answer" is to let the install start;
    reporting a mismatch would loop the tree through the installer forever.
    """
    if hass_bin() is None:
        return "no hass in .venv — uv sync never completed here"
    uv = _uv_bin()
    if uv is None:
        log("deps: no uv found — cannot verify .venv against uv.lock, continuing")
        return ""
    try:
        r = subprocess.run([str(uv), "sync", "--check", "--inexact"],
                           cwd=str(PROJECT_ROOT), capture_output=True,
                           text=True, timeout=60)
    except (OSError, subprocess.SubprocessError) as e:
        log(f"deps: uv check could not run ({e}) — continuing unverified")
        return ""
    if r.returncode == 0:
        return ""
    # uv puts the verdict on an `error:` line and the evidence above it
    # ("Would install 19 packages", "Would remove ..."), with progress chatter
    # like "Would use project environment at: .venv" ahead of both.  Quote the
    # verdict when there is one, else the first line that names a change.
    lines = [ln.strip() for ln in (r.stderr or r.stdout or "").splitlines() if ln.strip()]
    pick = next((ln for ln in lines if ln.startswith("error:")), "")
    if not pick:
        pick = next((ln for ln in lines if ln.startswith(
            ("Would install", "Would remove", "Would update", "Would replace"))), "")
    if not pick:
        pick = lines[0] if lines else ""
    return "the venv does not match uv.lock" + (f" — {pick}" if pick else "")



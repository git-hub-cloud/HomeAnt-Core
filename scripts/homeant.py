# ── offline auth provisioning (hass stopped) ────────────────────────────────
# HA exposes no public "create user + password" API, so the owner account is
# produced the way HA's own onboarding view does it
# (components/onboarding/views.py: add_auth -> create_user -> link_user), but
# with hass stopped and the stores written in one go.
#
# The owner is the only account we create: it signs in for the Xiaomi OAuth
# flow *and* owns the MCP token.  A second non-admin user bought nothing —
# `auth/long_lived_access_token` mints for whoever is calling, so the extra
# account only sat there while a second credential pair had to be kept in the
# config file for it.
#
# Safety: append-only (never rewrites an existing user/credential); the stores
# are Store(atomic_writes=True); .bak copies are restored on failure.  Worst
# case is a credential without a user — the next login creates it
# (recoverable).  The owner entry itself is never modified.

AUTH_STORE = HA_ROOT / ".storage" / "auth"
PROVIDER_STORE = HA_ROOT / ".storage" / "auth_provider.homeassistant"
ONBOARDING_STORE = HA_ROOT / ".storage" / "onboarding"
OWNER_NAME = "HomeAnt"


def _auth_doc() -> dict:
    """Parsed ``.storage/auth`` → its ``data`` mapping, or ``{}``.

    Never raises: every caller is a gate, and a gate that cannot read its own
    evidence has to answer "not satisfied" rather than take the process down.
    """
    try:
        return json.loads(AUTH_STORE.read_text(encoding="utf-8")).get("data") or {}
    except (OSError, json.JSONDecodeError, AttributeError):
        return {}


def _admin_state() -> dict:
    """Where the cfg USERNAME credential sits → ``{owner, linked, holder}``.

    Read from the same JSON as every other probe, so an install whose owner
    account has no way to sign in is visible *before* hass starts.  That state
    used to be indistinguishable from "configured", which is how every run
    ended up asking the user to add the integration by hand.

    ``holder`` names a *non-owner* user the username is already bound to: we
    refuse to take that account over rather than hand admin rights to whoever
    happens to own the name.
    """
    data = _auth_doc()
    users = {u.get("id"): u for u in (data.get("users") or [])}
    owner_id = next((uid for uid, u in users.items() if u.get("is_owner")), None)
    state = {"owner": owner_id is not None, "linked": False, "holder": None}
    username = cf("USERNAME", "admin")
    for c in (data.get("credentials") or []):
        if (c.get("data") or {}).get("username") != username:
            continue
        uid = c.get("user_id")
        if uid and uid == owner_id:
            state["linked"] = True
        elif uid in users:
            state["holder"] = users[uid].get("name")
        break
    return state


def _provider_has_user(username: str) -> bool:
    """True when ``username`` exists in the store that holds the passwords.

    ``.storage/auth`` only lists users and credential links; the bcrypt secret
    lives in ``.storage/auth_provider.homeassistant``.  An install where the
    first exists but the second does not is *half provisioned*: every gate reads
    "configured", provisioning gets skipped, and the login then fails with
    ``invalid_auth`` — which HA returns both for an unknown user and for a wrong
    password, so the two causes cannot be told apart from the API alone.

    Unreadable store answers False: a gate that cannot read its own evidence has
    to say "not satisfied" rather than take the process down.
    """
    try:
        doc = json.loads(PROVIDER_STORE.read_text(encoding="utf-8"))
        users = (doc.get("data") or {}).get("users") or []
    except (OSError, json.JSONDecodeError, AttributeError):
        return False
    return any((u or {}).get("username") == username for u in users)


def _admin_ready() -> bool:
    """True when cfg USERNAME can sign in as the owner.

    All three stores must agree, not just two: ``.storage/auth`` carries the
    owner plus the credential link, while the bcrypt secret lives in
    ``.storage/auth_provider.homeassistant``.  Checking only the former made a
    half-provisioned install look ready — provisioning was skipped and every
    later login failed.

    The password itself is still not compared: a mismatch surfaces at login, and
    rewriting it here would destroy a password the user changed in the UI.
    """
    if not _provider_has_user(cf("USERNAME", "admin")):
        return False
    state = _admin_state()
    return bool(state["owner"] and state["linked"])


# Mirrors homeassistant.components.onboarding.const.STEPS (HA 2026.10.1:
# user / core_config / integration / analytics).  ALL of them must be marked
# done for HA to treat onboarding as finished — only then does the onboarding
# component's async_setup early-return and deregister /api/onboarding, which
# is what lets the browser skip the wizard and land on the dashboard.  Marking
# just `user` (old behavior) left the other three pending, so /api/onboarding
# kept returning 200 and the frontend got stuck re-checking status instead of
# auto-configuring.
ONBOARDING_STEPS = ("user", "core_config", "integration", "analytics")

# Shape HA's OnboardingStorage persists; keep the major version in sync with
# homeassistant.components.onboarding (STORAGE_VERSION / STORAGE_KEY).
_ONBOARDING_STORE_VERSION = 4
_ONBOARDING_STORE_MINOR = 1


def _mark_onboarding_user_done() -> None:
    """Mark every onboarding step done once an owner exists.

    The repo seed deliberately leaves the onboarding store untouched so a
    *failed* provisioning still leaves the browser onboarding wizard usable
    (HA registers /api/onboarding/users only for steps that are not done).
    Once an owner does exist we mark all steps done — otherwise the wizard
    would either offer to create a second admin account or, with only `user`
    done, get stuck re-checking status instead of redirecting to the dashboard.
    """
    if not AUTH_STORE.exists():
        return
    try:
        doc = json.loads(ONBOARDING_STORE.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        doc = None
    if doc is None:
        # Fresh install: HA has not persisted the onboarding store yet, so
        # create it pre-completed.  If we skip this, HA derives
        # {"done":["user"]} on first start and the wizard/stuck-state stays
        # active.
        doc = {
            "version": _ONBOARDING_STORE_VERSION,
            "minor_version": _ONBOARDING_STORE_MINOR,
            "key": "onboarding",
            "data": {"done": list(ONBOARDING_STEPS)},
        }
        tmp = ONBOARDING_STORE.with_name(ONBOARDING_STORE.name + ".tmp")
        tmp.write_text(json.dumps(doc, indent=2), encoding="utf-8")
        os.replace(tmp, ONBOARDING_STORE)
        log("onboarding: created store with all steps done")
        return
    done = doc.setdefault("data", {}).setdefault("done", [])
    added = [s for s in ONBOARDING_STEPS if s not in done]
    if not added:
        return
    done.extend(added)
    tmp = ONBOARDING_STORE.with_name(ONBOARDING_STORE.name + ".tmp")
    tmp.write_text(json.dumps(doc, indent=2), encoding="utf-8")
    os.replace(tmp, ONBOARDING_STORE)
    log(f"onboarding: marked steps done: {', '.join(added)}")


def _provision_auth() -> bool:
    """Run HA's auth stack in-process (hass stopped) and create the owner."""
    import asyncio
    import logging

    from homeassistant import runner
    from homeassistant.auth import auth_manager_from_config
    from homeassistant.auth.const import GROUP_ID_ADMIN
    from homeassistant.config_entries import ConfigEntries
    from homeassistant.core import HomeAssistant
    from homeassistant.helpers import device_registry as _dr, entity_registry as _er

    admin_name = cf("USERNAME", "admin")
    admin_pw = cf("PASSWORD", "homeant")

    async def _ensure_credential(provider, username: str, password: str) -> None:
        known = {(u or {}).get("username")
                 for u in (provider.data.users if provider.data else [])}
        if username in known:
            return
        await provider.async_add_auth(username, password)

    async def _run() -> bool:
        hass = HomeAssistant(str(HA_ROOT))
        hass.config_entries = ConfigEntries(hass, {})
        await hass.config_entries.async_initialize()
        _dr.async_setup(hass)
        await asyncio.gather(_dr.async_load(hass), _er.async_load(hass))
        hass.auth = await auth_manager_from_config(
            hass, [{"type": "homeassistant"}], [])
        provider = hass.auth.auth_providers[0]
        await provider.async_initialize()

        users = await hass.auth.async_get_users()
        owner = next((u for u in users if u.is_owner), None)

        # Unconditional, not only when the owner is new: an owner can exist with
        # no password on this provider at all — provisioned by an earlier build,
        # or created through the browser wizard — and that is exactly the state
        # in which every later run failed to log in and handed the job back to
        # the user.  _ensure_credential only adds and never rewrites, so a
        # password changed in the UI survives.
        await _ensure_credential(provider, admin_name, admin_pw)
        admin_cred = await provider.async_get_or_create_credentials(
            {"username": admin_name})
        if owner is None:
            owner = await hass.auth.async_create_user(
                OWNER_NAME, group_ids=[GROUP_ID_ADMIN])
            await hass.auth.async_link_user(owner, admin_cred)
            log(f"auth: created owner {admin_name}"
                + ("" if owner.is_owner else " (WARNING: is_owner=False)"))
        else:
            # No-op when the credential already belongs to this owner.  A raise
            # for a *different* holder is unreachable from here: the only caller
            # refuses that case out of the JSON before this function is entered.
            await hass.auth.async_link_user(owner, admin_cred)

        # hass was never started, so async_stop() early-returns on
        # CoreState.not_running and never fires FINAL_WRITE — the delayed
        # auth-store save would be lost.  Fire it by hand and let every Store
        # with a pending write flush (that is exactly what it is for).
        from homeassistant.const import EVENT_HOMEASSISTANT_FINAL_WRITE

        hass.bus.async_fire_internal(EVENT_HOMEASSISTANT_FINAL_WRITE)
        await hass.async_block_till_done()
        # Default logger prints a wall of shutdown noise; keep it quiet.
        logging.getLogger("homeassistant.core").setLevel(logging.WARNING)
        await hass.async_stop(force=True)
        return True

    try:
        return asyncio.run(_run(), loop_factory=runner.create_event_loop)
    except TypeError:               # loop_factory kwarg needs py>=3.12
        return asyncio.run(_run())


def _ensure_auth_offline() -> bool:
    """Provision the owner account into .storage/auth — hass stopped."""
    # Two separate reasons, reported separately: "hass is running" is a fact
    # about our pid, while a busy port only means *somebody* holds 8123 (a
    # dllhost.exe squatting there once made this line blame hass, which sent
    # the reader after a process that was never started).
    if _ha_instance():
        log("auth provision skipped: hass is running")
        return False
    if port_in_use(PORT):
        log(f"auth provision skipped: port {PORT} is held by another process")
        return False
    PROVIDER_STORE.parent.mkdir(parents=True, exist_ok=True)

    # Refused before anything is written: the username is already bound to a
    # non-owner account, and linking the owner to it would either steal that
    # account or hand admin rights to whoever registered the name first.
    taken = _admin_state()["holder"]
    if taken:
        log_red(f"auth: USERNAME '{cf('USERNAME', 'admin')}' already belongs to "
                f"the non-owner user '{taken}' — not taking it over; set another "
                f"USERNAME in homeant.cfg")
        return False

    if _admin_ready():
        _mark_onboarding_user_done()
        return True

    import shutil as _shutil
    backups = []
    for p in (AUTH_STORE, PROVIDER_STORE, ONBOARDING_STORE):
        if p.exists():
            b = p.with_name(p.name + ".bak")
            try:
                _shutil.copy2(p, b)
                backups.append((b, p))
            except OSError as e:
                log(f"auth backup failed ({p.name}): {e}")

    ok = False
    try:
        ok = _provision_auth()
    except Exception as e:  # noqa: BLE001 — never break start on this
        log_red(f"auth provision error: {e}")

    if not ok or not _admin_ready():
        for b, p in backups:
            try:
                _shutil.copy2(b, p)
            except OSError:
                pass
        log_red("auth provision FAILED — restored previous .storage/auth")
        return False
    _mark_onboarding_user_done()
    return True

class _WSConn:
    """Minimal HA auth websocket client (stdlib only, single connection)."""

    def __init__(self, sock: socket.socket, buf: bytes = b"") -> None:
        self._s = sock
        self._buf = buf

    def send(self, payload: dict) -> None:
        data = json.dumps(payload).encode()
        mask = os.urandom(4)
        masked = bytes(b ^ mask[i % 4] for i, b in enumerate(data))
        n = len(data)
        if n < 126:
            hdr = bytes([0x81, 0x80 | n])
        elif n < 65536:
            hdr = bytes([0x81, 0x80 | 126]) + n.to_bytes(2, "big")
        else:
            hdr = bytes([0x81, 0x80 | 127]) + n.to_bytes(8, "big")
        self._s.sendall(hdr + mask + masked)

    def recv(self) -> dict:
        buf = self._buf
        while len(buf) < 2:
            buf += self._s.recv(4096)
        ln = buf[1] & 0x7F
        idx = 2
        if ln == 126:
            while len(buf) < idx + 2:
                buf += self._s.recv(4096)
            ln = int.from_bytes(buf[idx:idx + 2], "big")
            idx += 2
        elif ln == 127:
            while len(buf) < idx + 8:
                buf += self._s.recv(4096)
            ln = int.from_bytes(buf[idx:idx + 8], "big")
            idx += 8
        while len(buf) < idx + ln:
            buf += self._s.recv(4096)
        self._buf = buf[idx + ln:]
        return json.loads(buf[idx:idx + ln].decode())

    def call(self, payload: dict, tries: int = 4) -> dict | None:
        """Send one command, return its `result` frame (None on timeout)."""
        self.send(payload)
        for _ in range(tries):
            res = self.recv()
            if res.get("type") == "result":
                return res
        return None


@contextlib.contextmanager
def _ws_open(bearer: str, timeout: float = 10.0):
    """Open + authenticate a websocket to HA's /api/websocket."""
    s = socket.create_connection(("localhost", PORT), timeout)
    try:
        s.settimeout(timeout)
        key = base64.b64encode(os.urandom(16)).decode()
        s.sendall((
            f"GET /api/websocket HTTP/1.1\r\n"
            f"Host: localhost:{PORT}\r\n"
            "Upgrade: websocket\r\nConnection: Upgrade\r\n"
            f"Sec-WebSocket-Key: {key}\r\n"
            "Sec-WebSocket-Version: 13\r\n"
            f"Authorization: Bearer {bearer}\r\n\r\n"
        ).encode())
        head = b""
        while b"\r\n\r\n" not in head:
            chunk = s.recv(4096)
            if not chunk:
                raise OSError("handshake closed")
            head += chunk
        if b" 101 " not in head.split(b"\r\n", 1)[0]:
            raise OSError("websocket upgrade rejected")
        ws = _WSConn(s, head.split(b"\r\n\r\n", 1)[1])
        first = ws.recv()
        if first.get("type") != "auth_required":
            raise OSError(f"unexpected first frame: {first}")
        ws.send({"type": "auth", "access_token": bearer})
        ok = ws.recv()
        if ok.get("type") != "auth_ok":
            raise OSError(f"auth failed: {ok}")
        yield ws
    finally:
        s.close()


def _ws_llat(bearer: str, timeout: float = 10.0) -> str | None:
    """Create a long-lived access token via HA's websocket API."""
    try:
        with _ws_open(bearer, timeout) as ws:
            stale_id = None
            res = ws.call({"id": 1, "type": "auth/refresh_tokens"})
            if res and res.get("success"):
                for t in res.get("result") or []:
                    if (t.get("client_name") == LLAT_CLIENT_NAME
                            and t.get("type") == "long_lived_access_token"):
                        stale_id = t.get("id")
                        break
            if stale_id:
                res = ws.call({"id": 2, "type": "auth/delete_refresh_token",
                               "refresh_token_id": stale_id})
                if res and res.get("success"):
                    log("llat: revoked stale HomeAnt token")
                else:
                    log(f"llat: revoke stale failed: {(res or {}).get('error')}")
            res = ws.call({
                "id": 3,
                "type": "auth/long_lived_access_token",
                "client_name": LLAT_CLIENT_NAME,
                "lifespan": LLAT_LIFESPAN_DAYS,
            })
            if res and res.get("success"):
                return res.get("result")
            log(f"llat: create failed: {(res or {}).get('error')}")
            return None
    except Exception as e:
        log(f"llat: websocket error: {e}")
        return None


def _ws_purge_normal(bearer: str, timeout: float = 10.0) -> None:
    """Drop the `normal` refresh token this login just minted.

    Every login mints a ~90-day refresh token; without cleanup they pile up in
    .storage/auth.  We revoke exactly the current one and never call
    `auth/delete_all_refresh_tokens`: that one takes every normal token of the
    account, and this account is the owner — someone may well be signed in
    through a browser, whose session this run has no business ending.
    """
    try:
        with _ws_open(bearer, timeout) as ws:
            res = ws.call({"id": 1, "type": "auth/refresh_tokens"})
            current = None
            if res and res.get("success"):
                for t in res.get("result") or []:
                    if t.get("is_current") and t.get("type") == "normal":
                        current = t.get("id")
                        break
            if not current:
                return
            done = False
            try:
                # Revoking the current token drops this socket — expected.
                res = ws.call({"id": 2, "type": "auth/delete_refresh_token",
                               "refresh_token_id": current})
                done = bool(res and res.get("success"))
            except Exception:
                done = True         # socket killed by the revoke itself
            if not done:
                log("auth: admin token revoke returned no result")
    except Exception as e:
        log(f"auth token purge skipped: {e}")


def _token_ok(tok: str) -> bool:
    """Probe GET /api/ with the token (HA answers 200 only for valid auth)."""
    try:
        st, _ = _http_get(f"{MCP_PROBE_BASE}/api/",
                          headers={"Authorization": f"Bearer {tok}"})
        return st == 200
    except Exception:
        return False


def _mcp_token(create: bool = True, fail: dict | None = None) -> str | None:
    """Cached owner LLAT for the MCP endpoint — user-invisible.

    Priority: .mcp-token cache -> login as USERNAME -> create LLAT (ws) -> cache.

    The token belongs to the owner account, so an agent holding it has admin
    rights on this instance.  That is the deliberate trade of this design: one
    account means one credential pair in the config file and no second identity
    to keep in sync, and the token never travels — it is printed for the user to
    paste and cached 0600.

    ``fail`` is an optional out-dict: on failure it gets ``{"kind": "login"}``
    when the credential was rejected, or ``{"kind": "llat"}`` when the login
    worked but HA refused to mint the token.  Those two need different advice,
    so the caller cannot collapse them into one message.
    """
    try:
        tok = MCP_TOKEN_FILE.read_text(encoding="utf-8").strip()
    except OSError:
        tok = ""
    if tok:
        if _token_ok(tok):
            return tok
        log("cached MCP token rejected — recreating")
        if create:
            # Drop the dead token before minting a new one: if minting fails the
            # stale file would otherwise stay behind and `status` would keep
            # reporting a rejected cache instead of an empty one.  Deliberately
            # skipped on the read-only path — status must not mutate state.
            try:
                MCP_TOKEN_FILE.unlink()
            except OSError:
                pass
    if not create:
        return None
    bearer = _login(cf("USERNAME", "admin"), cf("PASSWORD", "homeant"))
    if not bearer:
        if fail is not None:
            fail["kind"] = "login"
        return None
    tok = _ws_llat(bearer)
    if not tok:
        if fail is not None:
            fail["kind"] = "llat"
        return None
    try:
        MCP_TOKEN_FILE.write_text(tok, encoding="utf-8")
        if not IS_WIN:
            os.chmod(MCP_TOKEN_FILE, 0o600)
    except OSError as e:
        log(f"MCP token cache failed: {e}")
    # The login above minted a normal refresh token too; revoke just that one,
    # so a browser session on this same account survives (see _ws_purge_normal).
    _ws_purge_normal(tok)
    return tok


def _mcp_diag() -> tuple[bool, str]:
    """Probe the MCP endpoint with the cached MCP token. Returns (ok, message).

    Reads the cache file directly instead of going through
    ``_mcp_token(create=False)``: that call returns None both when the file is
    missing and when the token was rejected, which made this report "no cached
    .mcp-token" for an install that had one — just an invalid one.
    """
    tok = _cached_mcp_token()
    if not tok:
        return False, "no cached .mcp-token (run: homeant start)"
    if _token_ok(tok):
        return True, "token valid"
    return False, "cached token rejected (start auto-recreates)"


def _mcp_client_config(tok: str) -> dict:
    """Copy-paste config block for MCP clients (token inlined on purpose:
    the user pastes it into any client and it just works, no edits)."""
    return {
        "mcpServers": {
            "homeant": {
                "url": MCP_CLIENT_URL,
                "headers": {"Authorization": f"Bearer {tok}"},
            }
        }
    }


def _cached_mcp_token() -> str | None:
    """The provisioned LLAT, read straight from its cache file.

    Deliberately *not* validated: ``_token_ok()`` does a live ``GET /api/``
    probe, which is exactly what cannot be trusted while the core is still
    starting up.
    """
    try:
        return MCP_TOKEN_FILE.read_text(encoding="utf-8").strip() or None
    except OSError:
        return None


def _ha_core_state() -> tuple[int, str | None]:
    """``(http_status, state)`` from ``GET /api/core/state``.

    HA ships this view for supervisor's "is core running" poll
    (``components/api/__init__.py`` -> ``APICoreStateView``): it reports
    ``hass.state`` as STARTING / RUNNING / ....  That is the authoritative,
    cheap signal for "integrations finished loading" — which is when
    ``homeant_mdns`` registers the ``homeassistant.local`` record — as opposed
    to "the HTTP port is listening", which happens much earlier.
    """
    tok = _cached_mcp_token()
    if not tok:
        return 0, None
    try:
        status, body = _http_get(
            f"{MCP_PROBE_BASE}/api/core/state",
            headers={"Authorization": f"Bearer {tok}"},
            timeout=5.0,
        )
    except Exception:
        return 0, None
    state = body.get("state") if isinstance(body, dict) else None
    return status, state if isinstance(state, str) else None


def _wait_for_ha_running(timeout: float = 120.0, t0: float | None = None) -> bool:
    """Poll ``/api/core/state`` until the core reports RUNNING.

    Returns True only when RUNNING was observed.  False means "not RUNNING
    within the timeout" or "probe unsupported" — advisory, the caller carries
    on to the DNS check either way.
    """
    wait_start = time.monotonic()        # drives the polling deadline
    started = wait_start if t0 is None else t0  # t0 only for the reported duration
    deadline = wait_start + timeout
    announced = False
    unsupported = 0
    if not _cached_mcp_token():
        log("core state probe skipped: no cached MCP token")
        return False
    while time.monotonic() < deadline:
        status, state = _ha_core_state()
        if state == "RUNNING":
            if announced:
                log(f"home assistant running (after {time.monotonic() - started:.1f}s)")
            return True
        if status in (401, 403, 404):
            unsupported += 1
            if unsupported >= 3:
                log(f"core state probe unavailable (HTTP {status}) — continuing")
                return False
        else:
            unsupported = 0
        if not announced:
            log("waiting for Home Assistant to finish starting ...")
            announced = True
        time.sleep(1.0)
    log(f"WARNING: core not RUNNING after {timeout:.0f}s — continuing")
    return False


def _mcp_entry_present() -> bool:
    """True when HA's storage still carries the mcp_server config entry.

    Read straight off disk because that is the only evidence available once
    setup has failed: a loaded entry leaves no trace anywhere else, and a
    missing one is the difference between "the route was never registered" and
    "the route exists but the integration is broken".
    """
    path = HA_ROOT / ".storage" / "core.config_entries"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    entries = data.get("data", {}).get("entries")
    if not isinstance(entries, list):
        return False
    return any(
        isinstance(e, dict) and e.get("domain") == "mcp_server" for e in entries
    )


def _mcp_probe(tok: str, timeout: float = 15) -> str:
    """Empty when /api/mcp really answers an ``initialize`` request.

    Minting a token only proves the login worked.  The route is registered by
    mcp_server's ``async_setup``, which runs only while its config entry is
    loaded — and HA installs that entry's pip requirements at runtime, so the
    first boot after a fresh install can import-fail and leave no route behind.
    Without this probe the run prints SUCCESS and the user discovers the truth
    in their own client, as a 404 on an SSE handshake.

    It probes MCP_PROBE_BASE, not MCP_CLIENT_URL: the facts under test here
    are server-side (is the route registered, does the token answer), and
    loopback is the one address that is always present.  Whether this box can
    resolve MCP_HOSTNAME says nothing about clients, so it is deliberately
    not part of the check.
    The empty ProxyHandler is the other deliberate choice, because an
    HTTP_PROXY in the environment would otherwise route the check through a
    stranger.
    """
    import urllib.request as _ur

    url = f"{MCP_PROBE_BASE}/api/mcp"
    body = json.dumps({
        "jsonrpc": "2.0",
        "id": 1,
        "method": "initialize",
        "params": {
            "protocolVersion": "2025-03-26",
            "capabilities": {},
            "clientInfo": {"name": "homeant", "version": "0"},
        },
    }).encode("utf-8")
    req = _ur.Request(
        url, data=body, method="POST",
        headers={
            "Authorization": f"Bearer {tok}",
            "Content-Type": "application/json",
            "Accept": "application/json, text/event-stream",
        },
    )
    opener = _ur.build_opener(_ur.ProxyHandler({}))
    try:
        with opener.open(req, timeout=timeout) as resp:
            if resp.status == 200:
                return ""
            return f"the MCP endpoint answered HTTP {resp.status} — see home-assistant.log"
    except _ur.HTTPError as e:
        if e.code == 404:
            if not _mcp_entry_present():
                # The seed writes the entry once, guarded by the config/ tree
                # fingerprint; a wiped ~/.homeant/.storage therefore leaves the
                # fingerprint matching and the entry gone for good.  Saying so
                # is the difference between "run start again" (does nothing)
                # and the one command that does put it back.
                return (
                    "the mcp_server integration has no config entry in "
                    f"{HA_ROOT / '.storage' / 'core.config_entries'}, so /api/mcp was "
                    f"never registered — stop hass, delete {SEED_MARKER}, then start "
                    "to re-seed"
                )
            return (
                "the mcp_server integration is not loaded even though its entry "
                f"exists — see {HA_ROOT / 'home-assistant.log'}"
            )
        if e.code == 401:
            return "the core rejected the freshly minted token"
        return f"the MCP endpoint answered HTTP {e.code}"
    except Exception as e:  # noqa: BLE001 - transport failures all read the same
        return f"cannot reach {url}: {type(e).__name__}: {e}"


def _ensure_mcp_ready(fail: dict | None = None, tok: str | None = None) -> str | None:
    """Warm the MCP token cache, verify the endpoint, build the client config.

    Returns the ready-to-paste JSON, or None when no token could be minted
    (agents would get 401) or the endpoint does not actually answer.  Nothing is
    printed here: the reason goes into ``fail`` so ``_finish_setup`` can turn it
    into the single FAIL line, instead of the same problem being described
    twice.

    ``tok`` lets the caller mint the token earlier than this call: the RUNNING
    gate authenticates with it, so the token has to exist before the gate while
    the probe must come after it.
    """
    tok = tok or _mcp_token(fail=fail)
    if not tok:
        return None
    why = _mcp_probe(tok)
    if why:
        if fail is not None:
            fail["kind"] = "endpoint"
            fail["why"] = why
        return None
    return json.dumps(_mcp_client_config(tok), indent=2, ensure_ascii=False)

# ── main ─────────────────────────────────────────────────────────────────────

def _register_cleanup() -> None:
    """Ensure hass (if we started one via cmd_start) gets killed on early exit.

    Detached hass.exe keeps .venv/Scripts/hass.exe locked, which breaks the
    next `uv sync`.  Atexit + signal handlers cover Ctrl+C, exception, and
    premature sys.exit().  Normal completion sets _KEEP_HASS so the running
    hass is left alone — cmd_start already backgrounded it on purpose.

    IMPORTANT: We only clean up hass that *this process* started
    (_WE_STARTED_HASS).  A stale PID file from a previous homeant.py run
    must NEVER trigger cleanup — that hass is not ours to kill.
    """
    import atexit

    _STOPPED = {"yes": False}   # avoid double-stop on Ctrl+C (signal + atexit)
    _KEEP_HASS = {"yes": False} # set True when cmd_start completes normally
    _WE_STARTED_HASS = {"yes": False}  # set True ONLY by cmd_start after launch

    def _cleanup() -> None:
        if _STOPPED["yes"] or _KEEP_HASS["yes"]:
            return
        if not _WE_STARTED_HASS["yes"]:
            return   # not our hass — don't touch it
        if SPAWNED_PID:
            _STOPPED["yes"] = True
            # The in-memory pid, not a lookup: this runs while we are exiting,
            # and the only process it may kill is the one this run launched.
            _stop_pid(SPAWNED_PID)

    atexit.register(_cleanup)

    def _on_sigint(signum, frame):
        _cleanup()
        raise KeyboardInterrupt()   # let main()'s try/except produce the usual "cancelled" msg

    def _on_sigterm(signum, frame):
        _cleanup()
        sys.exit(143)

    signal.signal(signal.SIGINT, _on_sigint)
    if hasattr(signal, "SIGTERM"):   # Windows has no SIGTERM
        signal.signal(signal.SIGTERM, _on_sigterm)

    # Expose setters so cmd_start can mark "keep hass on exit"
    def _mark_keep_hass() -> None:
        _KEEP_HASS["yes"] = True

    def _mark_we_started_hass() -> None:
        _WE_STARTED_HASS["yes"] = True

    # monkey-patch onto module-level so callers can find it
    import sys as _sys
    _sys.modules[__name__]._mark_keep_hass = _mark_keep_hass
    _sys.modules[__name__]._mark_we_started_hass = _mark_we_started_hass  # noqa: F841  (Pylance sees monkey-patch at runtime)


def main() -> int:
    global CFG
    enable_ansi()
    _register_cleanup()   # kill detached hass.exe on any exit path

    parser = argparse.ArgumentParser(
        prog="homeant",
        description="HomeAnt — Control home through Agent.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Config:
  project_root/homeant.cfg

Typical workflow:
  1. uv sync
  2. .\\homeant    start         # Windows — setup + launch HA
     ./homeant    start         # Linux / macOS
  3. re-run the same command after any manual step it asks you for
""",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_start = sub.add_parser(
        "start", help="Bring the install up to date, then start hass")
    # One flag, and only one: it names the situation the online installer puts
    # us in — the release is already unpacked and the venv already synced, so
    # probe nothing and hand nothing back.  `store_true` rather than a boolean
    # value on purpose: `--install false` would parse as the string "false",
    # which is true in Python, and the flag would silently do nothing.
    # A hand-typed `start` never passes it; probing the release host is the
    # point there.
    p_start.add_argument(
        "--no-install", action="store_true",
        help="Do not check for a release or hand back to the installer "
             "(set by the installer for its own final start)")
    p_start.set_defaults(func=cmd_start)

    for name, help_text, func in [
        ("status", "Health check + hass status", cmd_status),
        ("stop", "Stop hass", cmd_stop),
        ("logs", "Stream hass logs", cmd_logs),
    ]:
        p = sub.add_parser(name, help=help_text)
        p.set_defaults(func=func)

    args = parser.parse_args()

    # `start` reads homeant.cfg (USERNAME/PASSWORD/XIAOMI_*).  Everything
    # else (stop/status/logs) only touches PID file, HA_ROOT, or subprocess
    # control.
    if args.command == "start":
        # `start` owns the live config: it is what a fresh install runs and what
        # an upgrade ends with, so it creates the file from the template and
        # appends keys a newer version added. Doing it here, before load_cfg(),
        # is the whole point - the run that just gained a key also gets to use it.
        _reconcile_cfg()
        CFG = load_cfg()

    rc = args.func(args)

    # If the command finished and hass is running in the background, don't kill
    # it.  The purpose of cmd_start is to launch a detached hass that keeps
    # serving after homeant.py exits.  Only early exits (Ctrl+C,
    # exception, failed start) should trigger cleanup via atexit.
    #
    # Pending counts as finished: the whole point of that state is "come back
    # later", and the thing we would come back to — the flow's webhook,
    # the HA API — lives inside this hass process.  Killing it turns every URL
    # already printed into a 404 and drops the pending flow with it.  That is
    # also why PENDING returns 0: zero means "leave the service alone", the one
    # thing both finished states have in common.
    if rc == 0 and callable(globals().get("_mark_keep_hass")) and SPAWNED_PID:
        _mark_keep_hass()

    return rc


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.stderr.write("\n[cancelled]\n")
        sys.exit(130)

def _http_post(url: str, json_body: dict | None = None,
               form_body: dict | None = None,
               headers: dict | None = None, timeout: float = 10.0
               ) -> tuple[int, dict]:
    """Tiny urllib wrapper: POST JSON or form, return (status, parsed_json)."""
    import urllib.request as _ur
    import urllib.parse as _up

    hdrs = dict(headers) if headers else {}
    if json_body is not None:
        data = json.dumps(json_body).encode("utf-8")
        hdrs.setdefault("Content-Type", "application/json")
    elif form_body is not None:
        data = _up.urlencode(form_body).encode("utf-8")
        hdrs.setdefault("Content-Type", "application/x-www-form-urlencoded")
    else:
        data = b""
    req = _ur.Request(url, data=data, headers=hdrs, method="POST")
    try:
        with _ur.urlopen(req, timeout=timeout) as resp:
            body = resp.read().decode("utf-8")
            return resp.status, json.loads(body) if body else {}
    except _ur.HTTPError as e:
        body = e.read().decode("utf-8", errors="replace")
        try:
            return e.code, json.loads(body) if body else {}
        except json.JSONDecodeError:
            return e.code, {"raw": body}


def _http_get(url: str, headers: dict | None = None,
              timeout: float = 10.0) -> tuple[int, dict]:
    """Tiny urllib wrapper: GET, return (status, parsed_json)."""
    import urllib.request as _ur
    hdrs = dict(headers) if headers else {}
    req = _ur.Request(url, headers=hdrs, method="GET")
    try:
        with _ur.urlopen(req, timeout=timeout) as resp:
            body = resp.read().decode("utf-8")
            return resp.status, json.loads(body) if body else {}
    except _ur.HTTPError as e:
        body = e.read().decode("utf-8", errors="replace")
        try:
            return e.code, json.loads(body) if body else {}
        except json.JSONDecodeError:
            return e.code, {"raw": body}


def _login(username: str, password: str) -> str | None:
    """HA login flow → Bearer access_token (the user must already exist).

    The owner is provisioned offline by `_ensure_auth_offline()` while hass is
    stopped, so a plain login flow is all we need here: no
    POST /api/onboarding/users (that view is not even registered once the
    onboarding `user` step is marked done).
    """
    ha_url = f"http://localhost:{PORT}"
    client_id = ha_url + "/"
    redirect = f"{ha_url}/?auth_callback=1"

    status, body = _http_post(
        f"{ha_url}/auth/login_flow",
        json_body={"handler": ["homeassistant", None],
                   "client_id": client_id, "redirect_uri": redirect},
    )
    if status != 200:
        log(f"login_flow create failed: HTTP {status}")
        return None
    flow_id = body.get("flow_id")

    status2, body2 = _http_post(
        f"{ha_url}/auth/login_flow/{flow_id}",
        json_body={"client_id": client_id,
                   "username": username, "password": password},
    )
    # No raw-body dump here.  It printed HA's whole login-flow dict (flow_id,
    # data_schema, ...) and every word of it is noise to whoever is standing at
    # the console: the only fact they can act on is that the credential was
    # refused, and the caller states that in one line.
    if body2.get("type") != "create_entry":
        return None
    flow_code = body2.get("result")

    status3, body3 = _http_post(
        f"{ha_url}/auth/token",
        form_body={"grant_type": "authorization_code", "code": flow_code,
                   "client_id": client_id, "redirect_uri": redirect},
    )
    if status3 != 200:
        log(f"token exchange failed: HTTP {status3}")
        return None
    return body3.get("access_token")


def _get_access_token() -> str | None:
    """Admin bearer — only needed for the config flow."""
    return _login(cf("USERNAME", "admin"), cf("PASSWORD", "homeant"))



def _xiaomi_already_configured() -> bool:
    """True only when a *live* xiaomi_home entry exists in core.config_entries.

    A disabled entry does not count: HA never loads it, so the integration is
    not actually working and the OAuth stage below still has to run.  Treating
    it as configured would print the MCP config and call the install done while
    xiaomi_home sits there doing nothing.
    """
    ce = HA_ROOT / ".storage" / "core.config_entries"
    if not ce.exists():
        return False
    try:
        data = json.loads(ce.read_text(encoding="utf-8"))
        return any(e.get("domain") == "xiaomi_home" and not e.get("disabled_by")
                   for e in data.get("data", {}).get("entries", []))
    except Exception:
        return False


def _xiaomi_step_payload(step_id: str) -> dict | None:
    """Hardcoded step payloads — we know exactly what xiaomi_home asks."""
    if step_id == "eula":
        return {"eula": cf("XIAOMI_EULA", True)}

    if step_id == "auth_config":
        return {
            "cloud_server": cf("XIAOMI_CLOUD_SERVER", "cn"),
            "integration_language": cf("XIAOMI_LANGUAGE", "zh-Hans"),
            "network_detect_config": cf("XIAOMI_NETWORK_DETECT", True),
        }

    if step_id == "network_detect_config":
        return {
            "network_detect_addr": "",
            "check_network_deps": True,
        }

    return None


# The flow a previous run left waiting: only its id is remembered, so the next
# run resumes that flow instead of starting a second one (see _xiaomi_live_flow).
XIAOMI_FLOW_FILE = HA_ROOT / ".xiaomi-flow"

# Every HTTP call touching that flow makes HA load the integration and probe the
# Xiaomi cloud, so 180s instead of the 10s `_http_post` default: a warm instance
# answers in ~7s, a cold one needs well over 10s, and the resulting TimeoutError
# is not an HTTPError — it used to escape `_http_post` and kill the run outright.
XIAOMI_FLOW_TIMEOUT = 180


def _xiaomi_live_flow(token: str) -> dict | None:
    """The flow a previous run left behind, if this hass still knows about it.

    Only the id is remembered, because HA offers no way to list in-progress
    flows: ``GET /api/config/config_entries/flow`` answers 405 (that path is
    POST-only) and there is no REST equivalent of the websocket list command.

    A pending flow does NOT survive a hass restart, so a 404 here is normal
    rather than exceptional — a stop + start spends its own flow every time.
    The id therefore only ever resolves when the service was left running,
    which is precisely the case this exists for.
    """
    try:
        flow_id = XIAOMI_FLOW_FILE.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    if not flow_id:
        return None
    status, flow = _http_get(
        f"http://localhost:{PORT}/api/config/config_entries/flow/{flow_id}",
        headers={"Authorization": f"Bearer {token}"},
    )
    if status != 200 or not isinstance(flow, dict) or "flow_id" not in flow:
        XIAOMI_FLOW_FILE.unlink(missing_ok=True)
        return None
    return flow


def _oauth_pending_url(flow: dict) -> str | None:
    """The OAuth URL a flow is parked on, or None if there is not one."""
    placeholders = flow.get("description_placeholders") or {}
    m = re.search(r'href="([^"]+)"', placeholders.get("link_left", ""))
    return m.group(1) if m else None


def _xiaomi_answer(flow: dict) -> dict | None:
    """The payload that answers the step ``flow`` is parked on, or None."""
    step_id = flow.get("step_id")

    pre_oauth = _xiaomi_step_payload(step_id)
    if pre_oauth is not None:
        return pre_oauth

    if step_id == "homes_select":
        # Pick every home the account exposes.
        schema = flow.get("data_schema") or {}
        homes_opts: object = []
        if isinstance(schema, list):
            for field in schema:
                if isinstance(field, dict) and field.get("name") == "home_infos":
                    homes_opts = field.get("default") or field.get("options") or []
                    break
        elif isinstance(schema, dict):
            hi = (schema.get("properties") or {}).get("home_infos", {})
            homes_opts = hi.get("default") or hi.get("options") or []

        if isinstance(homes_opts, dict):
            selected = list(homes_opts.keys())
        elif isinstance(homes_opts, list):
            selected = [h[0] if isinstance(h, (list, tuple)) else h for h in homes_opts]
        elif homes_opts:
            selected = list(homes_opts)
        else:
            selected = []
        return {"home_infos": selected, "area_name_rule": "room",
                "advanced_options": False}

    if step_id == "advanced_options":
        return {"advanced_options": False}

    return None


def _xiaomi_start_flow(token: str) -> dict | None:
    """Create a xiaomi_home config flow; returns its first state.

    The POST makes HA load the integration and probe the Xiaomi cloud, which is
    why it gets XIAOMI_FLOW_TIMEOUT rather than the 10s default — see the note
    there for what happens when a timeout shorter than the load is used.
    """
    status, flow = _http_post(
        f"http://localhost:{PORT}/api/config/config_entries/flow",
        json_body={"handler": "xiaomi_home"},
        headers={"Authorization": f"Bearer {token}"},
        timeout=XIAOMI_FLOW_TIMEOUT,
    )
    if status != 200 or "flow_id" not in flow:
        log(f"flow start failed: HTTP {status}")
        return None
    log("xiaomi_home: config flow started")
    return flow


def _xiaomi_walk(token: str, flow: dict) -> tuple[str, str | None]:
    """Answer steps until the flow finishes or needs a human.

    Returns ``("done" | "waiting" | "failed", oauth_url)``.  ``waiting`` is not
    a timeout: the flow is parked on the OAuth step and only a browser can move
    it, so the caller reports pending and the next run resumes from right here.
    """
    ha_url = f"http://localhost:{PORT}"
    headers = {"Authorization": f"Bearer {token}"}
    flow_id = flow["flow_id"]

    for _ in range(20):
        ftype = flow.get("type")
        step_id = flow.get("step_id")

        if ftype == "create_entry":
            log("xiaomi_home: config entry created")
            return "done", None
        if ftype == "abort":
            reason = flow.get("errors") or flow.get("abort_reason") or "unknown"
            log(f"xiaomi_home: flow aborted — {reason}")
            return "failed", None
        if step_id == "oauth":
            url = _oauth_pending_url(flow)
            if not url:
                log("xiaomi_home: no OAuth URL found")
                return "failed", None
            return "waiting", url

        payload = _xiaomi_answer(flow)
        if payload is None:
            log(f"xiaomi_home: unknown step '{step_id}' — aborting")
            return "failed", None

        # Same timeout as flow creation: answering a step can also reach the
        # Xiaomi cloud (the miot login).
        status, flow = _http_post(
            f"{ha_url}/api/config/config_entries/flow/{flow_id}",
            json_body=payload, headers=headers,
            timeout=XIAOMI_FLOW_TIMEOUT,
        )
        if status != 200:
            log(f"xiaomi_home: step '{step_id}' rejected — HTTP {status}")
            return "failed", None

    log("xiaomi_home: flow did not settle after 20 steps")
    return "failed", None


def _open_oauth_url(url: str) -> bool:
    """Give the flow's OAuth URL to a browser, if one can be reached.

    Returns True when the caller still has to print the URL:
      * WSL — no GUI browser, and the callback terminates on the Windows host,
        so it has to be opened there.
      * headless Linux — no DISPLAY/WAYLAND, so a launch attempt would only
        hand the URL to a console browser and steal the terminal (see
        has_desktop).
      * anything else — a ``webbrowser.open`` that returned False (no browser
        installed / X11 forwarding that leads nowhere).

    False means the browser took it and there is nothing left to show.  The
    URL is never lost either way.
    """
    if is_wsl() or not has_desktop():
        return True
    if webbrowser.open(url):
        log("opened browser → OAuth login")
        return False
    return True


def _xiaomi_advance() -> tuple[str, str | None]:
    """Move xiaomi_home setup as far as one run can, without ever waiting.

    Returns ``(state, url)``: ``state`` is ``"done"``, ``"waiting"``,
    ``"rejected"`` or ``"failed"`` — the caller turns each into one of the three
    printed states — and ``url`` is the OAuth link to print, or None when it was
    already handed to a browser.

    Polling for the OAuth callback (the old shape, up to 600s) bought nothing:
    under WSL the callback is followed by a browser on the Windows host, and on
    native the user may take as long as they like.  So instead of waiting, each
    run picks up the flow the previous one left behind — the browser comes back
    to that flow's webhook — and advances it wherever it stopped: ``homes_select``
    and ``advanced_options`` are answered here, no human needed.  Only when there
    is no live flow does a new one get started.  Re-running IS the retry.
    """
    token = _get_access_token()
    if not token:
        # "rejected": the offline provisioning above is supposed to guarantee a
        # working credential, so a rejected login means the cfg is wrong — the
        # caller turns it into a FAIL naming the file.  `_login` already logged
        # HA's own reason, and nothing asks the user to open the web UI.
        return "rejected", None
    try:
        # A flow left pending by an earlier run owns the webhook the user's
        # browser is going to hit, so it is resumed first — a second flow would
        # never receive that callback and the entry would never appear.
        flow = _xiaomi_live_flow(token)
        if flow is not None:
            log("xiaomi_home: resuming the flow from the previous run")
        else:
            flow = _xiaomi_start_flow(token)
            if flow is None:
                return "failed", None
            XIAOMI_FLOW_FILE.write_text(flow["flow_id"], encoding="utf-8")

        state, url = _xiaomi_walk(token, flow)
        if state == "waiting":
            # The browser gets first refusal; printing is the fallback, not the
            # other way round.  Whatever it hands back unconsumed is the
            # caller's to show after its own PENDING line.
            if url and not _open_oauth_url(url):
                url = None
            return state, url
        # done or failed — either way the id is spent, and keeping it would
        # make the next run chase a flow that will never move again.
        XIAOMI_FLOW_FILE.unlink(missing_ok=True)
        return state, None
    finally:
        # The admin bearer ends here: revoke this login's refresh token so no
        # admin credential outlives the run, while every other token of the
        # account stays intact — the browser session must survive.
        _ws_purge_normal(token)







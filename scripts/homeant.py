# ── config ─────────────────────────────────────────────────────────────────

def load_cfg() -> dict:
    """Parse homeant.cfg → flat dict (KEY=VALUE, all strings)."""
    cfg: dict = {}
    if not CONFIG_FILE.exists():
        log(f"config not found: {CONFIG_FILE}")
        return cfg
    for raw in CONFIG_FILE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        cfg[k.strip()] = v.strip()
    return cfg


def cf(k: str, default=None):
    """Read a config key with optional default."""
    v = CFG.get(k, default)
    if v is None:
        return default
    if isinstance(default, bool):
        return v.lower() in ("1", "true", "yes", "on")
    if isinstance(default, int):
        try:
            return int(v)
        except ValueError:
            return default
    return v


def log(msg: str) -> None:
    """Print a [homeant] line, coloured by its severity marker.

    Only ``FAIL  `` and ``WARN  `` are markers — everything else is a normal
    line — so the colour is derived from the text rather than passed in by
    each caller: red for FAIL, yellow for WARN, plain otherwise.  Matching
    the two spaces keeps words like ``WARNING:`` out of it: that is prose,
    not a badge.  _COLOR is defined below but resolved at call time.
    """
    color = "31" if msg.startswith("FAIL  ") else "33" if msg.startswith("WARN  ") else ""
    if color and _COLOR:
        print(f"\033[{color}m[homeant] {msg}\033[0m", flush=True)
    else:
        print(f"[homeant] {msg}", flush=True)


def log_partial(msg: str) -> None:
    """Open a status line without a newline — the caller ticks dots into it.

    Used for phases with no progress callback of their own (hass cold start):
    a silent console reads as a hang, so the caller appends one dot per second
    via log_tick() and ends the line itself before logging the outcome.
    """
    print(f"[homeant] {msg}", end="", flush=True)


def log_tick() -> None:
    """One liveness dot, appended to a line opened by log_partial()."""
    print(".", end="", flush=True)


_COLOR = sys.stdout.isatty()


def log_red(msg: str) -> None:
    if _COLOR:
        print(f"\033[31m[homeant] {msg}\033[0m", flush=True)
    else:
        print(f"[homeant] {msg}", flush=True)


def log_state(label: str, msg: str) -> None:
    """Print the run's closing verdict: SUCCESS / PENDING / FAIL.

    Every path out of the post-start stages ends with one of these, so the last
    line of a run cannot be mistaken for a finished install.  The word is
    print-only — callers return 0 or non-zero and never the state itself, so
    nothing downstream has to agree on a vocabulary.

    PENDING still returns 0: the files are in place and the service is up, only
    a human step is left, and re-running the command is the retry.  Reporting it
    as a failure is how a good setup gets reinstalled in a loop that cannot end
    differently.
    """
    color = {"SUCCESS": "32", "PENDING": "33", "FAIL": "31"}[label]
    if _COLOR:
        print(f"\033[{color}m[homeant] {label}: {msg}\033[0m", flush=True)
    else:
        print(f"[homeant] {label}: {msg}", flush=True)



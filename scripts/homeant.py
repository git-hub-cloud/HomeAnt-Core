def _python_bin() -> Path | None:
    """This tree's interpreter — PROJECT_ROOT/.venv, never the cwd's.

    cwd was the starting point until 2026-10-31, which made the answer depend
    on where the command was typed instead of on which tree is running: from
    the home directory, an absolute-path call to another install picked up
    the home directory's own .venv (a different uv, no hass) and reported
    "uv sync never completed here", while the same tree judged itself fine
    from its own directory.  Two verdicts for one install is how a healthy
    tree gets reinstalled for no reason.
    """
    p = PROJECT_ROOT / ".venv" / ("Scripts" if IS_WIN else "bin") / \
        ("python.exe" if IS_WIN else "python")
    return p if p.exists() else None


def _hass_bin() -> Path | None:
    """hass sits beside the interpreter, whichever layout the venv uses."""
    py = _python_bin()
    if py is None:
        return None
    p = py.parent / ("hass.exe" if IS_WIN else "hass")
    return p if p.exists() else None



_CONFIG_DIR = PROJECT_ROOT / "config"

# Files whose top-level keys are seed-owned: a template entry REPLACES the same
# key in the deployed copy, while keys only the deployed file has (UI-created
# entries) are kept.
#
# scripts.yaml: keys are script IDs, and a script's `sequence` is an ordered
# action chain — merging it item-wise appends new steps to a stale chain instead
# of replacing it, which corrupts the script. Replacing the file wholesale is
# not an option either: HA's script UI (components/config/script.py,
# EditKeyBasedConfigView) rewrites the whole file, so any script created in the
# UI lives in the same mapping and would be dropped.
_SEED_ENTRY_REPLACE_FILES = {"scripts.yaml"}


def _deep_merge_dict(tpl: dict, cur: dict) -> dict:
    """Recursive merge: add template keys missing in cur, never overwrite.

    - dict in both → recurse into children
    - list in both → de-duplicate merge (by dict identity or element equality)
    - scalar/list in cur only → keep cur (user wins)
    - key only in tpl → add from tpl

    A bare ``key:`` parses as ``None`` and is carried through untouched: HA
    itself rewrites every top-level ``None`` to ``{}`` while loading the config
    (homeassistant/config.py, load_yaml_config_file), so normalising it here
    would only make two equivalent files compare as different and force a
    pointless rewrite of the deployed copy.
    """
    result = dict(cur)
    for k, tv in tpl.items():
        if k not in result:
            result[k] = tv
        elif isinstance(tv, dict) and isinstance(result[k], dict):
            result[k] = _deep_merge_dict(tv, result[k])
        elif isinstance(tv, list) and isinstance(result[k], list):
            result[k] = _merge_lists(tv, result[k])
        # else: cur has scalar/list/None, leave as-is
    return result


def _dict_id_key(d: dict) -> tuple | None:
    """Return a best-effort identity key for a dict element in a list.

    Recognises common ID field patterns used by HA storage files:
      - issues:         (domain, issue_id)
      - entries/devices: id / entry_id / device_id
      - areas:          area_id / name
    Returns None if no known ID fields found — caller falls back to full-content compare.
    """
    if "domain" in d and "issue_id" in d:
        return ("domain", "issue_id", d["domain"], d["issue_id"])
    if "id" in d:
        return ("id", d["id"])
    if "entry_id" in d:
        return ("entry_id", d["entry_id"])
    if "device_id" in d:
        return ("device_id", d["device_id"])
    if "area_id" in d:
        return ("area_id", d["area_id"])
    return None


def _freeze(value):
    """Hashable full-content key for list de-duplication.

    YAML/JSON elements nest arbitrarily (an action's ``if: then: - service:``
    chain), so ``frozenset(d.items())`` raises TypeError on any dict or list
    value. Freeze recursively instead: dicts become key-sorted tuples, lists
    become tuples, scalars pass through.
    """
    if isinstance(value, dict):
        return ("dict", tuple(sorted(((k, _freeze(v)) for k, v in value.items()),
                                     key=lambda kv: str(kv[0]))))
    if isinstance(value, (list, tuple)):
        return ("list", tuple(_freeze(v) for v in value))
    try:
        hash(value)
    except TypeError:
        return ("repr", repr(value))
    return ("scalar", value)


def _merge_lists(tpl: list, cur: list) -> list:
    """Merge two lists: keep all cur items, append tpl items not already present.

    For lists of dicts with recognisable ID fields (domain+issue_id, id, etc.),
    de-duplicate by that identity key so user's entry wins over template.
    For scalar lists or unknown dict shapes, de-dup by full value/content.
    """
    if not cur:
        return list(tpl)
    if not tpl:
        return list(cur)

    # Detect if we're merging dicts with a known identity key
    first_cur = cur[0]
    if isinstance(first_cur, dict):
        id_key = _dict_id_key(first_cur)
        if id_key is not None:
            # Build set of existing identity keys from cur
            cur_keys = {_dict_id_key(c) for c in cur
                        if isinstance(c, dict) and _dict_id_key(c) is not None}
            merged = list(cur)
            for t_item in tpl:
                if isinstance(t_item, dict):
                    tk = _dict_id_key(t_item)
                    if tk is not None and tk not in cur_keys:
                        merged.append(t_item)
                        cur_keys.add(tk)
            return merged

    # Fallback: scalar lists or unknown dict shapes → full-content dedup
    merged = list(cur)
    cur_frozen = {_freeze(c) for c in cur}
    for t_item in tpl:
        frozen = _freeze(t_item)
        if frozen not in cur_frozen:
            merged.append(t_item)
            cur_frozen.add(frozen)
    return merged


def _merge_file(tpl_path: Path, dst_path: Path) -> bool:
    """Merge template file into dst. Auto-detect format (.yaml / .json).

    Merge rules:
      - keys missing in dst are added from the template; existing values win
      - HA storage entries present in both adopt the template: on entry_id
        match the data dict is replaced; on a unique-domain match the whole
        entry is (id included), so the merge de-duplicates instead of
        appending — the sole overwrite path, for seed entries whose *values*
        changed (mcp_server) on an already-initialized install; skipped while
        hass is running (HA rewrites these files from memory on shutdown)
      - YAML carrying custom tags (!include & co.) is merged at text level by
        _merge_file_tags — safe_load cannot construct those tags
      - files in _SEED_ENTRY_REPLACE_FILES replace per top-level key instead
        (see the constant): seed-owned entries follow the template, deployed-only
        entries survive

    Returns True if dst was written (something new was merged in).
    """
    if not dst_path.exists():
        return False  # nothing to merge into (fresh files are copied, not merged)
    suffix = tpl_path.suffix.lower()
    is_yaml = suffix in (".yaml", ".yml")
    is_json = suffix == ".json" or suffix == "" \
        or ".storage" in (tpl_path.parent.name, dst_path.parent.name)
    if not (is_yaml or is_json):
        return False  # unknown format

    if is_yaml:
        import yaml
        tpl_text = tpl_path.read_text(encoding="utf-8")
        dst_text = dst_path.read_text(encoding="utf-8")
        try:
            tpl = yaml.safe_load(tpl_text) or {}
            cur = yaml.safe_load(dst_text) or {}
        except yaml.YAMLError:
            # Custom tags (!include / !secret / !include_dir_*) are not
            # constructible by safe_load. Skipping those files is what kept
            # deployed configs from ever picking up new keys — merge at text
            # level instead.
            return _merge_file_tags(tpl_text, dst_text, dst_path)
    else:
        # HA storage files are JSON: no suffix (auth) or dotted core.*
        # naming under .storage/ (core.config_entries)
        try:
            tpl = json.loads(tpl_path.read_text(encoding="utf-8"))
            cur = json.loads(dst_path.read_text(encoding="utf-8"))
        except Exception as e:
            log(f"  merge skipped (parse error: {e})")
            return False

    if not isinstance(tpl, dict) or not isinstance(cur, dict):
        return False

    entries_synced = _sync_storage_entries(tpl, cur)
    if tpl_path.name in _SEED_ENTRY_REPLACE_FILES:
        replaced = False
        for key, val in tpl.items():
            if key not in cur or cur[key] != val:
                cur[key] = val  # seed-owned entry: template wins over deployed
                log(f"  {dst_path.name}: seed entry '{key}' adopted")
                replaced = True
        if not replaced and not entries_synced:
            return False  # deployed already matches the seed
        merged = cur
    else:
        merged = _deep_merge_dict(tpl, cur)
        if merged == cur and not entries_synced:
            return False  # nothing new to add

    # Write back
    dst_path.parent.mkdir(parents=True, exist_ok=True)
    if is_yaml:
        if (tpl_path.name in _SEED_ENTRY_REPLACE_FILES
                and set(cur) <= set(tpl)):
            # Nothing deployed-only to preserve → adopt the seed file verbatim
            # so its comments and formatting survive (safe_dump drops both).
            dst_path.write_bytes(tpl_path.read_bytes())
            return True
        import yaml
        dst_path.write_text(
            yaml.safe_dump(merged, allow_unicode=True, sort_keys=False),
            encoding="utf-8",
        )
    else:
        dst_path.write_text(
            json.dumps(merged, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
    return True


def _merge_file_tags(tpl_text: str, dst_text: str, dst_path: Path) -> bool:
    """Add-only merge for YAML carrying custom tags (!include / !secret ...).

    ``yaml.safe_load`` cannot construct custom tags, so include-bearing
    configs used to fall through as "parse error" and silently never picked
    up new template keys (a deployed configuration.yaml kept its old content
    forever). Re-serialising the loaded dict is not an option either: dumping
    would inline every ``!include`` target and destroy the wiring that lets
    the UI own scenes.yaml / automations.yaml.

    So only the *text* of each missing template key is spliced into dst
    (indentation-adjusted, nested mappings recursed into), leaving the rest
    of the file byte-identical. The result is re-composed before writing and
    dropped if the top-level keys still do not all show up.

    Returns True if dst was written.
    """
    import yaml

    try:
        tpl_root = yaml.compose(tpl_text, Loader=yaml.SafeLoader)
        dst_root = yaml.compose(dst_text, Loader=yaml.SafeLoader)
    except yaml.YAMLError as e:
        log(f"  merge skipped (parse error: {e})")
        return False

    if not isinstance(tpl_root, yaml.MappingNode):
        return False  # only mapping-shaped configs can be key-merged
    if dst_root is None:  # empty dst adopts the template verbatim
        dst_path.write_text(tpl_text, encoding="utf-8")
        return True
    if not isinstance(dst_root, yaml.MappingNode):
        return False

    edits: list[tuple[int, list[str]]] = []
    _collect_yaml_inserts(tpl_text.splitlines(), tpl_root, dst_root, 0, edits)
    if not edits:
        return False  # dst already has every template key

    merged = dst_text.splitlines()
    for line, block in sorted(edits, key=lambda e: e[0], reverse=True):
        merged[line + 1:line + 1] = block
    merged_text = "\n".join(merged) + "\n"

    try:
        check = yaml.compose(merged_text, Loader=yaml.SafeLoader)
    except yaml.YAMLError as e:
        log(f"  merge skipped (merged yaml unparsable: {e})")
        return False
    if not _yaml_mapping_keys(tpl_root) <= _yaml_mapping_keys(check):
        log("  merge skipped (keys still missing after splice)")
        return False

    dst_path.parent.mkdir(parents=True, exist_ok=True)
    dst_path.write_text(merged_text, encoding="utf-8")
    return True


def _collect_yaml_inserts(tpl_lines: list[str], tpl_map, dst_map,
                          indent: int, edits: list) -> None:
    """Queue text insertions for template keys absent from dst_map.

    ``indent`` is the column dst_map's children sit at; template blocks are
    shifted by the difference so they land at the right depth.
    """
    import yaml

    dst_children: dict[str, object] = {}
    for k, v in dst_map.value:
        if isinstance(k, yaml.ScalarNode):
            dst_children.setdefault(k.value, v)

    missing = []
    nested = []
    for tk, tv in tpl_map.value:
        if not isinstance(tk, yaml.ScalarNode):
            continue
        dv = dst_children.get(tk.value)
        if dv is None:
            missing.append((tk, tv))
        elif (isinstance(tv, yaml.MappingNode) and not tv.flow_style
              and isinstance(dv, yaml.MappingNode) and not dv.flow_style):
            nested.append((tv, dv))

    if missing:
        anchor = _yaml_insert_anchor(dst_map)
        delta = indent - missing[0][0].start_mark.column
        if anchor is not None and delta >= 0:
            block: list[str] = []
            for tk, tv in missing:
                piece = _yaml_slice(tpl_lines, tk, tv, delta)
                if not piece:
                    continue
                if block and indent == 0:
                    block.append("")  # blank line between new top-level keys
                block += piece
            if block:
                if indent == 0:
                    block.insert(0, "")  # blank line before the new section
                edits.append((anchor, block))

    for tv, dv in nested:
        child_indent = _yaml_child_indent(dv)
        if child_indent is not None:
            _collect_yaml_inserts(tpl_lines, tv, dv, child_indent, edits)


def _yaml_insert_anchor(map_node) -> int | None:
    """Line index after which a new sibling key can be spliced in."""
    if not map_node.value or map_node.flow_style:
        return None  # empty or flow mapping: no block anchor
    key, value = map_node.value[-1]
    end = value.end_mark
    if end.column == 0 and end.line > key.start_mark.line:
        return end.line - 1  # end mark already points past the content
    return end.line


def _yaml_child_indent(map_node) -> int | None:
    """Column of map_node's children (None when it has none)."""
    if not map_node.value:
        return None
    return map_node.value[0][0].start_mark.column


def _yaml_slice(tpl_lines: list[str], key_node, val_node, delta: int) -> list[str]:
    """Raw text of one template key/value pair, shifted by ``delta`` columns."""
    start = key_node.start_mark.line
    end = val_node.end_mark.line
    if val_node.end_mark.column == 0 and end > start:
        end -= 1
    out: list[str] = []
    for line in tpl_lines[start:end + 1]:
        if not line.strip():
            out.append("")
        elif delta > 0:
            out.append(" " * delta + line)
        elif delta < 0:
            if line[:-delta].strip():
                return []  # cannot de-indent safely: skip this insertion
            out.append(line[-delta:])
        else:
            out.append(line)
    return out


def _yaml_mapping_keys(node) -> set[str]:
    import yaml

    if not isinstance(node, yaml.MappingNode):
        return set()
    return {k.value for k, _ in node.value if isinstance(k, yaml.ScalarNode)}


def _sync_storage_entries(tpl: dict, cur: dict) -> bool:
    """Reconcile HA storage entries with the template (in place on cur).

    _deep_merge_dict never overwrites existing values, so an install whose
    storage entry predates a seed value change (mcp_server) would keep stale
    data forever. Runs before the merge, pairing template entries against the
    pre-merge runtime state:

      - entry_id match                  → runtime entry adopts the seed data
      - else unique domain on both sides → runtime entry adopts the seed entry
        wholesale (data + entry_id), so the merge de-duplicates by id instead
        of appending a second entry for the same domain

    Only safe while hass is not running: HA holds entries in memory and
    rewrites these files on shutdown.
    """
    tpl_data = tpl.get("data")
    cur_data = cur.get("data")
    if not isinstance(tpl_data, dict) or not isinstance(cur_data, dict):
        return False
    tpl_entries = [e for e in tpl_data.get("entries", []) if isinstance(e, dict)]
    cur_entries = cur_data.get("entries")
    if not tpl_entries or not isinstance(cur_entries, list):
        return False

    pairs = []
    for te in tpl_entries:
        hit = next((e for e in cur_entries
                    if isinstance(e, dict)
                    and e.get("entry_id") == te.get("entry_id")), None)
        if hit is None:
            same = [e for e in cur_entries
                    if isinstance(e, dict)
                    and e.get("domain") == te.get("domain")]
            if len(same) != 1:
                continue  # absent (merge deploys it) or ambiguous (leave alone)
            pairs.append((same[0], te, True))
        elif hit.get("data") != te.get("data"):
            pairs.append((hit, te, False))
    if not pairs:
        return False

    if _ha_instance():
        return False
    for hit, te, wholesale in pairs:
        if wholesale:
            hit.clear()
            hit.update(te)
        else:
            hit["data"] = te.get("data", {})
    return True


def _deploy_config_files() -> None:
    """Walk config/ dir, copy or merge each file into HA_ROOT.

    Rules per file:
      - dst missing  → copy template
      - dst exists   → _merge_file (add missing keys; HA storage entries synced)
    """
    import shutil as _shutil

    if not _CONFIG_DIR.exists():
        return

    for tpl in _CONFIG_DIR.rglob("*"):
        if not tpl.is_file():
            continue

        rel = tpl.relative_to(_CONFIG_DIR)
        dst = HA_ROOT / rel

        if not dst.exists():
            dst.parent.mkdir(parents=True, exist_ok=True)
            _shutil.copy(tpl, dst)
        else:
            _merge_file(tpl, dst)

    log(f"deploying config → {HA_ROOT}")


# ── seed gate: deploy once per seed fingerprint ────────────────────────────

def _seed_digest() -> str | None:
    """sha256 over config/ — every path plus its bytes, in sorted order.

    The fingerprint is the *input* (what this release ships), never "when did we
    last run": a version bump that changes a seed file deploys, a bump that does
    not, does not.  Byte comparison also means an edit to a seed that ships the
    same content as the last release is not mistaken for a change.
    """
    import hashlib

    if not _CONFIG_DIR.is_dir():
        return None
    h = hashlib.sha256()
    for p in sorted(_CONFIG_DIR.rglob("*")):
        if not p.is_file() or "__pycache__" in p.parts or p.suffix == ".pyc":
            continue
        h.update(p.relative_to(_CONFIG_DIR).as_posix().encode("utf-8"))
        h.update(b"\0")
        h.update(p.read_bytes())
        h.update(b"\0")
    return h.hexdigest()


def _seed_marker() -> dict:
    """Read .seed-state as a dict; anything unreadable reads as "no marker"."""
    try:
        d = json.loads(SEED_MARKER.read_text(encoding="utf-8"))
        return d if isinstance(d, dict) else {}
    except (OSError, ValueError):
        return {}


def _seed_ready() -> bool:
    """True when the deployed seed matches the one this release ships.

    Also checks that the vendored custom_components landed: they come from
    vendor/, so they are not covered by the config/ fingerprint, and deleting
    ~/.homeant/custom_components would otherwise leave the fingerprint intact
    while xiaomi_home silently stopped existing.
    """
    seed = _seed_digest()
    if not seed or _seed_marker().get("seed") != seed:
        return False
    cc_src = PROJECT_ROOT / "vendor" / "ha_xiaomi_home" / "custom_components"
    if cc_src.is_dir():
        for d in cc_src.iterdir():
            if d.is_dir() and not d.name.startswith("_") \
                    and not (HA_ROOT / "custom_components" / d.name).is_dir():
                return False
    return True


def _seed_present() -> bool:
    """True when configuration.yaml — the seed's marker file — is on disk.

    Deliberately weaker than ``_seed_ready``: this answers "was this tree
    deleted", not "is the deployed copy current".  A new release changes the
    fingerprint, and treating that as "missing" would turn every `start` on a
    healthy running instance into a restart — the idempotency this command
    promises.  configuration.yaml is the marker because _ensure_seed always
    writes it and merely merges the rest.

    Both `status` (reports it) and `start` (recovers from it) ask this one
    question, so the two commands cannot disagree about the state of the tree.
    """
    return (HA_ROOT / "configuration.yaml").exists()


def _write_seed_marker() -> None:
    """Record the fingerprint of what was deployed.

    ``seed`` is the only field read back (by ``_seed_ready``), so the marker
    carries nothing else — a timestamp or a host name would be write-only.
    """
    SEED_MARKER.write_text(
        json.dumps({"seed": _seed_digest()}), encoding="utf-8")


def _install_custom_components() -> None:
    """Copy vendored integrations into HA_ROOT/custom_components.

    config/custom_components/ is deployed separately by _deploy_config_files();
    this one only covers what ships under vendor/.
    """
    import shutil as _shutil

    cc_src = PROJECT_ROOT / "vendor" / "ha_xiaomi_home" / "custom_components"
    cc_dst = HA_ROOT / "custom_components"
    if not cc_src.exists():
        return
    cc_dst.mkdir(parents=True, exist_ok=True)
    for domain in cc_src.iterdir():
        if domain.is_dir() and not domain.name.startswith("_"):
            _shutil.copytree(domain, cc_dst / domain.name, dirs_exist_ok=True)
            log(f"installed custom_components/{domain.name}")


def _ensure_seed() -> None:
    """Deploy the repo seed if — and only if — the fingerprint says so.

    Satisfied means nothing happens, which is what keeps a hand-edited
    ~/.homeant/configuration.yaml alive across runs.  The whole body is
    copy-or-merge, so a partial deploy can never roll anything back.
    """
    if _seed_ready():
        return
    HA_ROOT.mkdir(parents=True, exist_ok=True)
    if _CONFIG_DIR.exists():
        _deploy_config_files()
    _install_custom_components()
    _write_seed_marker()



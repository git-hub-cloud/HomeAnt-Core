# ── hosts: homeassistant.local (OAuth callback host) ─────────────────

def _hosts_path() -> Path | None:
    """The Windows hosts file as seen from WSL, or None when /mnt/c is absent.

    WSL-only by design.  Everywhere else — Windows included — Home Assistant's
    zeroconf integration advertises ``homeassistant.local`` over mDNS, so the
    name resolves on its own and there is no entry to look for.  Inside the
    guest mDNS never reaches the resolver and the browser that follows the
    OAuth callback runs on the Windows side, so the 9p-mounted Windows copy is
    the only file that matters — never the guest's own /etc/hosts.
    """
    for base in ("/mnt/c", "/c"):
        p = (Path(base) / "Windows" / "System32" / "drivers" / "etc" / "hosts")
        if p.exists():
            return p
    return None


def _hosts_has_ha_local() -> bool | None:
    """True/False for a live loopback entry, None when the file is unreadable.

    Read-only by design: the Windows hosts file rejects writes even from WSL
    root — ``sudo test -w`` reports writable (CAP_DAC_OVERRIDE clears the Linux
    check) but the 9p server re-applies the Windows ACL and the write fails —
    so this can only report, never repair.
    """
    path = _hosts_path()
    if path is None:
        return None
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    for line in text.splitlines():
        fields = line.split("#", 1)[0].split()
        # 127.0.0.1 is required here, not a name and not another loopback
        # address: a hosts line maps address -> name, so a name in the first
        # column maps nothing, and ::1 is worse than useless — WSL2's localhost
        # forwarding only covers IPv4 on the Windows side, where an IPv6
        # loopback connect completes the handshake and then hangs with no bytes.
        # Both names are required: the browser follows OAUTH_HOSTNAME and the
        # MCP client follows MCP_HOSTNAME, so a line carrying only one of them
        # lets half the traffic through.  Match case-insensitively — hosts
        # files are case-insensitive and users retype these lines by hand.
        if len(fields) >= 2 and fields[0] == "127.0.0.1":
            names = {f.lower() for f in fields[1:]}
            if all(n.lower() in names for n in (OAUTH_HOSTNAME, MCP_HOSTNAME)):
                return True
    return False


def is_wsl() -> bool:
    """True when running inside WSL (Windows Subsystem for Linux).

    WSL2 has no mDNS resolver for ``.local`` and no GUI browser, so the
    OAuth callback host (homeassistant.local) must resolve on the
    Windows host instead, and the OAuth URL is printed for the user to
    open there.
    """
    if os.environ.get("WSL_DISTRO_NAME"):
        return True
    try:
        return "microsoft" in Path("/proc/version").read_text(encoding="utf-8").lower()
    except OSError:
        return False


def has_desktop() -> bool:
    """True when this host can actually put a window on a screen.

    Windows and macOS always have a desktop session, so only Linux needs
    asking.  There the session is proven by ``DISPLAY`` (X11) or
    ``WAYLAND_DISPLAY`` (Wayland); a bare server has neither.  The distinction
    matters because ``webbrowser`` is not headless-safe: with no display it
    falls back to the console browsers it registers (``www-browser``, ``lynx``,
    ``w3m``), which would try to take over the terminal instead of showing a
    page.  A server therefore gets the URL printed, never a launch attempt.

    ``DISPLAY`` can also be set by X11 forwarding over SSH or leaked into a
    container; those are best-effort and are covered by the caller checking
    what ``webbrowser.open`` returns.
    """
    if IS_WIN or sys.platform == "darwin":
        return True
    return bool(os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY"))



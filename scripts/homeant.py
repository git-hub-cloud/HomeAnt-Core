def _vtuple(v: str) -> tuple:
    """'0.1.0' -> (0, 1, 0). Non-numeric segments collapse to 0."""
    parts = [int(p) if p.isdigit() else 0 for p in v.split(".")]
    return tuple((parts + [0, 0, 0])[:3])


def _local_version() -> str | None:
    try:
        text = (PROJECT_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    except OSError:
        return None
    m = re.search(r'(?m)^\s*version\s*=\s*"([^"]+)"', text)
    return m.group(1) if m else None


def _remote_version() -> str | None:
    """Latest released version, read off the online installer on the release
    host.

    The stamp INSTALLER_URL points at doubles as the version manifest — see the
    comment on that constant. Any failure is non-fatal: start must never block
    on this.
    """
    try:
        import urllib.request as _ur
        with _ur.urlopen(INSTALLER_URL, timeout=CONNECT_TIMEOUT) as resp:
            body = resp.read().decode("utf-8", "replace")
    except Exception:
        return None
    m = re.search(VERSION_RE, body)
    return m.group(1) if m else None


def _ask_update(version: str) -> bool:
    """Y/n prompt. Never updates unattended (no tty / piped stdin)."""
    try:
        if not sys.stdin or not sys.stdin.isatty():
            return False
        ans = input(f"[homeant] install {version} now? [Y/n] ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        return False
    return ans in ("", "y", "yes")


def _run_installer(version: str | None, repairing: bool = False) -> int:
    """Hand the work to the online installer; return the child's exit code.

    Two callers, one channel. A newer release (`repairing=False`) and a venv
    that no longer matches uv.lock (`repairing=True`) both need the same thing:
    the installer's download → stop → replace → uv sync → `start` sequence.
    Nothing of that is duplicated here — a second implementation is how an
    upgrade ends up behaving differently from a fresh install. There is also no
    fallback to "just start what is in memory": by the time the installer
    fails, the files under our feet may already be the new ones, so the honest
    answer is its exit code.

    Four decisions, each one measured before it landed here:
      * No stdio capture: the download progress redraws itself with \\r, so
        the child must own the real terminal or every frame becomes a line.
      * stdin is never the terminal: Windows passes DEVNULL, unix passes the
        fetched script to `sh -s`, so nothing down there can compete with the
        user for keystrokes.
      * unix feeds the script on stdin instead of `curl | sh`: a pipeline
        discards curl's exit status, so a 404 body would run as an empty
        script and report success.
      * Windows lets PowerShell fetch it, because `.Content` is a byte[] for
        `application/octet-stream` — the text has to be decoded explicitly
        from RawContentStream. `scriptblock::Create` then parses it before a
        single line runs, and `-ExecutionPolicy Bypass` is pointless:
        in-memory evaluation is not subject to it.
    """
    if repairing:
        log("dependencies incomplete — handing over to the online installer ...")
    else:
        log(f"installing {version} — handing over to the online installer ...")

    if IS_WIN:
        inner = (
            "$ProgressPreference='SilentlyContinue';"
            f"$r=Invoke-WebRequest -UseBasicParsing -Uri '{INSTALLER_URL}' -TimeoutSec {CONNECT_TIMEOUT};"
            "$s=[Text.Encoding]::UTF8.GetString($r.RawContentStream.ToArray());"
            "& ([scriptblock]::Create($s)) --upgrade"
        )
        argv = ["powershell", "-NoProfile", "-Command", inner]
        body = None
    else:
        import urllib.request as _ur

        try:
            with _ur.urlopen(INSTALLER_URL, timeout=CONNECT_TIMEOUT) as resp:
                body = resp.read()
        except Exception as e:
            log_red(f"update: cannot fetch the installer — {e}")
            return 1
        # same two checks install.sh makes on the script it fetches: a non-2xx
        # status raises above, and an empty body would otherwise run as a
        # successful no-op
        if not body.strip():
            log_red("update: the installer came back empty")
            return 1
        argv = ["sh", "-s", "--", "--upgrade"]

    try:
        if body is None:                    # Windows: PowerShell fetches it
            return subprocess.run(
                argv, cwd=str(PROJECT_ROOT), stdin=subprocess.DEVNULL).returncode
        # unix: the text we just fetched *is* stdin for `sh -s`
        return subprocess.run(
            argv, input=body, cwd=str(PROJECT_ROOT)).returncode
    except OSError as e:
        log_red(f"update: cannot run the installer — {e}")
        return 1


def _cfg_values(text: str) -> dict[str, str]:
    """KEY -> value, using load_cfg()'s own rules (skip blank / #, strip both)."""
    out: dict[str, str] = {}
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        k, v = s.split("=", 1)
        out[k.strip()] = v.strip()
    return out


def _cfg_new_keys_block(template_text: str, have: dict[str, str]) -> str:
    """Template lines for the keys the live file lacks, comments included.

    A bare ``KEY=value`` would leave the user guessing what the key does, and
    the template already documents every key right above it, so carry the
    comment block over with the key. The closing comment before the *next*
    key belongs to that key, not this one, which is why the buffer is reset
    both on a known key and on the first unknown one.

    The header block at the top describes the two files as a pair, not any
    single key, so it is skipped: iterating starts at the first real key.
    """
    lines = template_text.splitlines()
    start = next((i for i, line in enumerate(lines)
                  if line.strip() and not line.strip().startswith("#")
                  and "=" in line), len(lines))
    out: list[str] = []
    pending: list[str] = []
    for line in lines[start:]:
        s = line.strip()
        if not s or s.startswith("#"):
            pending.append(line)
            continue
        key = s.split("=", 1)[0].strip()
        if key in have:
            pending.clear()
            continue
        out.extend(pending)
        out.append(line)
        pending.clear()
    return "\n".join(out).strip("\n")


def _reconcile_cfg() -> None:
    """Bring homeant.cfg up to date with the shipped template.

    Additive only — it never rewrites a value the user already set:

      ① no live cfg      → copy the template (fresh install)
      ② nothing missing  → return without touching the file, mtime included
      ③ keys missing     → append those keys at the end, comments and all

    Rule ② is what makes this safe to call on every `start`: a no-op run must
    not look like a change, or every reinstall would show a modified config.
    Rule ③ is what lets a version bump add a key without resetting USERNAME /
    PASSWORD / per-machine paths.
    """
    if not CFG_TEMPLATE.is_file():
        return                       # release without a template: nothing to do
    import shutil as _shutil

    if not CONFIG_FILE.is_file():
        try:
            _shutil.copyfile(CFG_TEMPLATE, CONFIG_FILE)
            # copyfile() gives the new file the process umask - 0644 on a stock
            # Linux - and this file holds PASSWORD in clear text.  Windows has no
            # mode bits to set here (only the read-only flag) and cannot deny the
            # owner, so a refusal is swallowed rather than turned into a dead
            # install: an unreadable config would be the worse failure.
            try:
                os.chmod(CONFIG_FILE, 0o600)
            except OSError:
                pass
        except OSError as e:
            log_red(f"config: cannot create {CONFIG_FILE.name} — {e}")
            return
        log(f"config created from {CFG_TEMPLATE.name}")
        return

    # Same rule on every start, not only at creation: an install that predates
    # this line still carries a 0644 config, and rule ② returns without touching
    # the file at all - so the mode has to be asserted here, before the early
    # returns, or those installs would never converge.
    try:
        os.chmod(CONFIG_FILE, 0o600)
    except OSError:
        pass

    tpl_text = CFG_TEMPLATE.read_text(encoding="utf-8", errors="replace")
    # newline="" on the read as well as the write: read_text() would fold CRLF
    # into LF in memory, so the check below could never see a "\r\n" and a
    # CRLF config would come out with every line rewritten.
    with CONFIG_FILE.open("r", encoding="utf-8", errors="replace", newline="") as fh:
        text = fh.read()
    have = _cfg_values(text)
    missing = [k for k in _cfg_values(tpl_text) if k not in have]
    if not missing:
        return

    block = _cfg_new_keys_block(tpl_text, have)
    if not block:
        return
    # Keep the file's own line endings: writing "\n" into a CRLF file (or the
    # reverse) rewrites every existing line, which is exactly the "diff noise
    # on a no-op upgrade" this function is supposed to avoid.
    nl = "\r\n" if "\r\n" in text else "\n"
    if text and not text.endswith(("\n", "\r")):
        text += nl
    text += nl + f"# --- keys added by this version (from {CFG_TEMPLATE.name}) ---" + nl
    text += block.replace("\n", nl) + nl
    try:
        with CONFIG_FILE.open("w", encoding="utf-8", newline="") as fh:
            fh.write(text)
    except OSError as e:
        log_red(f"config: cannot append to {CONFIG_FILE.name} — {e}")
        return
    log(f"config: added {len(missing)} key(s) to {CONFIG_FILE.name}: "
        f"{', '.join(missing)}")


def _check_newer_version() -> str | None:
    """Detect-only: return the version the user agreed to install, else None.

    Nothing is written here — a check stays a check until the answer is yes.
    This is the one place we deliberately differ from the installers: they
    never compare versions (running them *is* the install), while an already
    installed tree has to notice the newer release itself.
    """
    local, remote = _local_version(), _remote_version()
    if not local or not remote or _vtuple(remote) <= _vtuple(local):
        return None
    log(f"new version available: {remote} (you have {local})")
    if not _ask_update(remote):
        # Declining is a normal answer, not a failure — just say so and move on.
        log(f"staying on {local}")
        return None
    return remote


def cmd_status(args) -> int:
    """Health check.  Normal lines carry no marker; a marker means trouble.

    Only FAIL / WARN are prefixed.  A passing check needs no badge — the
    absence of one is the pass signal — and that keeps every healthy line in
    the same plain ``key: value`` shape as the rest of the CLI's output.
    """
    checks = [
        ("HA_ROOT", HA_ROOT.exists(), str(HA_ROOT)),
    ]
    all_ok = True
    for name, ok, path in checks:
        if not ok:
            all_ok = False
            log(f"FAIL  {name}: {path}")
        else:
            log(f"{name}: {path}")

    # configuration.yaml gets no success line — its path is implied by HA_ROOT
    # above — so only its absence is worth reporting.
    if HA_ROOT.exists() and not _seed_present():
        all_ok = False
        log(f"FAIL  configuration.yaml: missing under {HA_ROOT}")

    # Same instance detection as start/stop — one predicate, so the two commands
    # cannot tell different stories.  That used to happen: after HA_ROOT was
    # deleted while hass kept serving from memory, start found the process by
    # scanning and said "running" while status, left with a deleted pid file,
    # said "not running" and blamed a stranger for holding the port.
    listening = port_in_use(PORT)
    # The scan is the expensive half — seconds on Windows, where it walks the
    # process table through PowerShell — so it only runs when something could
    # actually be found: a free port means no serving instance, whatever the
    # records say.
    pid = _ha_instance() if listening else None
    if pid:
        log(f"hass: running (PID {pid})")
    else:
        all_ok = False
        if listening:
            log(f"FAIL  hass: not running — port :{PORT} held by another process")
        else:
            log(f"FAIL  hass: not running")

    # OAuth gets no success badge either, and deliberately no effect on the exit
    # code: it is the one stage that waits on a browser, so "not configured"
    # describes an install still in progress, not a broken one — `start` is what
    # resumes it.  Same predicate as the gate in _finish_setup (a live config
    # entry), read from disk, so the two commands cannot disagree and no probe
    # request is spent finding out.
    #
    # A flow that is still open is reported apart from a missing one, because
    # the storage file cannot tell them apart and the user's next move differs.
    # "unfinished" means the flow exists but never created its entry — the
    # browser step is already done (or the URL was never opened), and the entry
    # is one `start` away.  Calling that "not configured" sends the user back to
    # redo an authorization they already gave, which is the exact confusion this
    # line exists to prevent.  .xiaomi-flow is written when a flow is created and
    # unlinked when it succeeds or goes stale, so it is honest evidence at the
    # price of one stat() — no request, no token.
    if _xiaomi_already_configured():
        log("oauth: xiaomi_home configured")
    elif XIAOMI_FLOW_FILE.exists():
        log("WARN  oauth: xiaomi_home flow unfinished — run: homeant start to finish it")
    else:
        log("WARN  oauth: xiaomi_home not configured (run: homeant start)")

    if pid and listening:
        m_ok, m_msg = _mcp_diag()
        log(f"mcp: {m_msg}" if m_ok else f"WARN  mcp: {m_msg}")
        tok = _mcp_token(create=False)
        if tok:
            log("mcp config — paste into your MCP client:")
            print(json.dumps(_mcp_client_config(tok), indent=2, ensure_ascii=False))
            # Endpoint probe reports only on failure.  "token valid" above is
            # already the answer to the question the reader came with, so a
            # success line just restates it; a *failing* probe is the one fact
            # the token check cannot see (route not registered yet), so it keeps
            # its line — and being a marker, it also carries the WARN badge.
            why = _mcp_probe(tok, timeout=5)
            if why:
                log(f"WARN  mcp endpoint: not answering — {why}")
        # Two blocks, split by the machine each line is typed on — that is the
        # distinction the reader needs, and it is what one shared heading got
        # wrong before ("sudo ufw allow" sat under a "from another machine"
        # heading although it runs here).
        #
        # "on this server" and not "checked on this server": nothing in this
        # block is a measurement.  Whether 8123 is *allowed* needs root on every
        # platform (ufw status, iptables -S), and a non-root reading misleads in
        # both directions — it alarms on an allowed port and hides a blocked
        # one.  Detecting which firewall is installed (ufw, firewalld, none) only
        # decided whether to show a reminder; it never answered the question, so
        # it does not get to print a status either.  All platforms, all states,
        # one line, phrased as the action to take.
        #
        # No address is printed, deliberately.  Any single value would be the
        # default route's source — a VPN tunnel or a Hyper-V switch as easily as
        # the NIC the client sits behind — so on a multi-homed box it is right
        # for one subnet and wrong for the next (the dev box here has eight IPv4
        # addresses and two default routes).  The user knows which address they
        # are testing against; naming one only invites the wrong check.
        #
        # No port line either: this block only runs inside
        # `if pid and listening`, and pid was derived from listening, so it
        # could only ever print "listening".  Whether HA is bound to all
        # interfaces needs the socket table, which is not read here.
        log("on this server:")
        print(f"  firewall: not checked, please allow tcp/{PORT}", flush=True)
        log("needs another machine:")
        print(f"  ping: {MCP_HOSTNAME} — must answer this server's IP,"
              " not 127.0.0.1", flush=True)
    else:
        # Both blocks describe how to reach a running server, so they are skipped
        # entirely when there is none — the FAIL line above already says why.
        log("WARN  mcp: hass not running")

    return 0 if all_ok else 1


def _login_rejected_hint() -> None:
    """Print the one FAIL line for a refused credential, split by what the stores say.

    HA answers ``invalid_auth`` both for "no such user" and for "wrong password"
    (deliberately — no enumeration), so the API cannot say which.  The files
    can, and the two causes have opposite fixes:

    * user missing from the password store → half provisioned; re-provisioning
      adds it from nothing, so nothing can be lost.
    * user present but the bcrypt does not match ``PASSWORD`` → somebody changed
      the password (in the UI, most likely).  We must NOT rewrite it: the cfg
      is the copy that is out of date, and ``async_change_password`` here would
      silently undo the user's own change.
    """
    username = cf("USERNAME", "admin")
    if _provider_has_user(username):
        log_state("FAIL", f"admin login rejected — the password in {PROVIDER_STORE.name} "
                          f"does not match PASSWORD in {CONFIG_FILE}; fix whichever one "
                          f"is wrong, then re-run")
    else:
        log_state("FAIL", f"admin login rejected — '{username}' is missing from "
                          f"{PROVIDER_STORE.name}; run 'homeant stop' then "
                          f"'homeant start' to re-provision")


def _finish_setup(mcp_cfg: str | None, mcp_fail: dict | None = None) -> int:
    """Run the post-start stages in order, each gating the next.

    The chain is hosts → OAuth → MCP, and every exit prints one of three words —
    ``SUCCESS`` (done), ``PENDING`` (waiting on a human step — re-running this
    command is the retry) or ``FAIL`` (broken) — while returning 0 or 1.  The
    word is for the reader; the code says only whether anything needs fixing,
    which is why PENDING returns 0.  A stage that is not satisfied returns
    without running the next one, and nothing is cached between runs, so the
    sequence resumes from the top every time and is idempotent by construction.

    1. **hosts** (WSL only) — the Windows hosts file must map
       ``homeassistant.local`` to 127.0.0.1.  Every other platform ignores this
       stage: HA's own zeroconf broadcast does the job there.  Consulted only
       while OAuth is still incomplete — once the config entry exists the
       callback host is history, so a finished install goes straight to MCP
       instead of demanding a hosts entry forever.
    2. **oauth** — xiaomi_home must have a config entry.  Never waited on: the
       run advances the flow as far as it goes, surfaces the URL, and returns
       pending.  MCP is NOT printed here — setup is not done.
    3. **mcp** — ``mcp_cfg`` was produced before this call but after the
       RUNNING gate: the token is minted early (the gate needs it), the probe
       runs only once the core is up.  Its stanza opens the final block and the
       config follows, so nothing scrolls past what users copy out.
    """
    if _xiaomi_already_configured():
        log("xiaomi_home already configured — skipping OAuth")
        # Any id remembered from an earlier run is spent: the entry exists, so
        # there is no flow left to resume.
        XIAOMI_FLOW_FILE.unlink(missing_ok=True)
    else:
        # ── stage 1: callback host (WSL only) ────────────────────────────────
        if is_wsl() and not _hosts_has_ha_local():
            log_state("PENDING", "add the hosts entry, then re-run")
            # WSL cannot write it: the 9p server re-applies the Windows ACL even
            # to root, so the entry has to be created from the Windows side.
            # The address stays the IPv4 literal — see _hosts_has_ha_local for
            # why neither a name nor ::1 can stand in for it.  One line, both
            # names: hosts syntax allows several names per address, and two
            # entries would be two chances to drift apart.
            hosts_line = f"127.0.0.1 {OAUTH_HOSTNAME} {MCP_HOSTNAME}"
            print(r"    # PowerShell as Administrator at Windows")
            print(rf'    Add-Content -Path "$env:windir\System32\drivers\etc\hosts" -Value "{hosts_line}"')
            return 0
        # ── stage 2: OAuth, never waited on ──────────────────────────────────
        state, oauth_url = _xiaomi_advance()
        if state == "waiting":
            if oauth_url:
                # One sentence carrying both halves of the old two-line message —
                # what to do and what to re-run.  The URL follows on its own bare
                # line: it gets copied, and a prefix would be pasted with it.
                where = "your Windows browser" if is_wsl() else "your browser"
                log_state("PENDING", f"open this URL in {where} to finish setup, then re-run: homeant start")
                print(f"  {oauth_url}", flush=True)
            else:
                log_state("PENDING", "finish OAuth in the browser, then re-run: homeant start")
            return 0
        if state == "rejected":
            # The only way to get here is a rejected login.  Which of the two
            # causes it is decides the fix, and it is not always the cfg — see
            # _login_rejected_hint.  Not a browser problem either way.
            _login_rejected_hint()
            return 1
        # `done` means HA itself returned a create_entry result — that is the
        # integration's own terminal answer, so nothing is re-checked here.
        # Re-reading core.config_entries cannot confirm it anyway: HA writes
        # that file through async_delay_save(SAVE_DELAY=1), so a fresh entry is
        # still in memory when this line runs, and the `state` field is never
        # persisted at all.  The only thing a disk check adds is a one-second
        # race against a file that is guaranteed to be stale.
        if state != "done":
            log_state("FAIL", "xiaomi_home setup did not complete — see the lines above")
            return 1
        log("xiaomi_home setup complete")

    # ── stage 3: MCP config, last ────────────────────────────────────────────
    if not mcp_cfg:
        # Different failures, different fixes: a rejected credential is a
        # missing user or an out-of-date cfg (see _login_rejected_hint); a
        # refused token mint means the login worked and the core is the one
        # saying no; an endpoint that does not answer means the token is fine
        # but the integration behind it is not serving.  Collapsing them into
        # one line would send half the users to the wrong file.
        kind = (mcp_fail or {}).get("kind")
        if kind == "login":
            _login_rejected_hint()
        elif kind == "llat":
            log_state("FAIL", "signed in, but the core refused to create the MCP token — see the lines above, then re-run")
        elif kind == "endpoint":
            log_state("FAIL", (mcp_fail or {}).get("why") or "the MCP endpoint did not answer")
        else:
            log_state("FAIL", "no MCP token available — see the lines above")
        return 1
    log_state("SUCCESS", "mcp ready — paste this config into your client:")
    print(mcp_cfg, flush=True)
    return 0


def cmd_start(args) -> int:
    """Start hass, first bringing the install up to date.

    The single entry point: a fresh install, an upgrade and a plain "is it up?"
    all land here.  Every stage it runs is a gate, so a second invocation finds
    nothing left to do.
    """
    global SPAWNED_PID
    # Version check comes first: a newer release may ship a different
    # dependency probe, so the old build must not be the one deciding whether
    # this host is usable. Detection is read-only — nothing is touched until
    # the user says yes.
    # `--no-install` is what the installer passes to its own tail: it has just
    # unpacked the newest release and synced the venv, so probing the release
    # host and handing back to the installer are the two things that must not
    # happen again. Without it the chain py → installer → py would only end when the
    # network did.
    newer = None if args.no_install else _check_newer_version()
    if newer:
        return _run_installer(newer)

    # Dependency gate. Repair is never done here: the installer is the only
    # thing that knows how to download, replace and sync, and a second in-tree
    # copy of that is how two paths drift apart.
    #
    # An unsatisfied gate is not an error to be confirmed — it is a statement
    # that this tree is not the released one: uv reports the environment as
    # outdated, or hass is missing outright. `start` is defined as "make this
    # host serve the release", so it converges instead of asking: hand-editing
    # uv.lock is a deliberate deviation, and a prompt would only ask the user
    # to re-decide something they already decided by editing the file. The one
    # exception is `--no-install`: we just came from the installer and it is
    # still not fixed, so looping would only re-download the same bytes.
    why = _deps_why()
    if why:
        if args.no_install:
            log_state("FAIL", f"dependencies incomplete — {why}. "
                              f"Re-run the installer: {INSTALLER_URL}")
            return 1
        log(f"deps: {why}")
        return _run_installer(None, repairing=True)

    HA_ROOT.mkdir(parents=True, exist_ok=True)

    # `start` is idempotent: a running hass already *is* the state we were asked
    # for, so stopping it would only interrupt the user.  Hand-edited config
    # therefore needs an explicit stop + start, not a bare `start`.
    pid = _ha_instance()
    if pid:
        log(f"hass already running (PID {pid})")

    # A hass still running out of a HA_ROOT that lost its configuration.yaml is
    # answering from memory alone: .storage writes fail, so every stage below
    # would report a success that evaporates on the next boot.  That is not the
    # state `start` was asked for, so it recovers instead of reporting — stop,
    # fall through, and let the cold path deploy the seed again.  Same predicate
    # `status` uses for its FAIL line: one fact, so the two cannot disagree.
    if pid and not _seed_present():
        log(f"hass running without configuration.yaml under {HA_ROOT} — redeploying")
        if not _stop_pid(pid):
            # Deploying under a live hass would be undone by its own shutdown
            # flush, so this path stops rather than tries.
            log_state("FAIL", f"hass (PID {pid}) did not exit — "
                              f"cannot redeploy its configuration under it")
            return 1
        pid = None

    if pid:
        # The three setup stages are still owed, and this rerun is exactly how a
        # first install resumes: the user just added the hosts entry or finished
        # OAuth in a browser.  Returning `status` here would answer a question
        # nobody asked and never move the chain forward.
        #
        # "Already running" can also mean "started 3 seconds ago", so the same
        # ordering as the cold path applies: token first, gate, then the probe.
        mcp_fail: dict = {}
        tok = _mcp_token(fail=mcp_fail)
        if mcp_fail.get("kind") == "login" and not _provider_has_user(cf("USERNAME", "admin")):
            # Half provisioned: .storage/auth has the owner but the password
            # store has no such user, so *no* password can ever match and
            # editing the cfg is a dead end.  Provisioning needs hass stopped,
            # so fall through to the cold path — it re-provisions and spawns in
            # the same pass, which also bounds the recovery to one attempt (the
            # cold path never returns here).
            log("admin user missing from the password store — re-provisioning")
            if not _stop_pid(pid):
                log_state("FAIL", f"hass (PID {pid}) did not exit — cannot re-provision its "
                                  f"admin account under a running instance")
                return 1
            pid = None
        else:
            _wait_for_ha_running()
            return _finish_setup(_ensure_mcp_ready(mcp_fail, tok=tok), mcp_fail)

    # No hass of ours is running at this point, so a listening 8123 belongs to
    # somebody else: the boot below would fail its bind, while the readiness
    # loop cheerfully reported "ready in 0.4s" because all it asks is whether
    # *something* answers on the socket.  The installer refuses the same case
    # before it downloads anything; this is the same verdict for the
    # `start`-only path, and it runs before the seed and the auth provisioning
    # touch anything.
    if port_in_use(PORT):
        log_state("FAIL", f"port {PORT} is already in use by another program — "
                          f"stop it, then run 'homeant start' again")
        return 1

    # Deploy the repo seed while hass is down (copy-or-merge per file; storage
    # entry sync refuses while hass is running).  Skipped outright when the
    # seed fingerprint already matches — see _ensure_seed.
    _ensure_seed()

    # Provision the owner into .storage/auth while hass is down — HA has no
    # runtime API for "create user with password".
    _ensure_auth_offline()

    hb = hass_bin()
    assert hb is not None
    cmd = [str(hb), "--ignore-os-check", "--config", str(HA_ROOT)]

    log_partial("starting hass ")
    t_boot = time.monotonic()

    if IS_WIN:
        _DETACHED_PROCESS = 0x00000008
        _CREATE_NO_WINDOW = 0x08000000
        _CREATE_NEW_PROCESS_GROUP = 0x00000200
        _STARTF_USESHOWWINDOW = 0x00000001
        _SW_HIDE = 0
        si = subprocess.STARTUPINFO()
        si.dwFlags = _STARTF_USESHOWWINDOW
        si.wShowWindow = _SW_HIDE
        p = subprocess.Popen(
            cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            creationflags=_DETACHED_PROCESS | _CREATE_NO_WINDOW | _CREATE_NEW_PROCESS_GROUP,
            close_fds=True, startupinfo=si,
        )
    else:
        p = subprocess.Popen(
            cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            start_new_session=True,
        )

    SPAWNED_PID = p.pid
    if callable(globals().get("_mark_we_started_hass")):
        _mark_we_started_hass()  # type: ignore[name-defined]  # noqa: F821  (monkey-patched by _register_cleanup)

    # wait for HA ready - one dot per second, same cadence as the installer's
    # extract ticker: a cold start takes tens of seconds and a silent console
    # reads as a hang.  "Ready" means answering HTTP, not just holding the port:
    # 0.5s (or much more, cold) passes between the socket being bound and the
    # server accepting, and anything we send in that gap is dropped.
    #
    # The ceiling is 5 minutes, not 1, because a cold start is only fast on a
    # local filesystem.  Measured on WSL2 with the tree on /mnt/d (drvfs/9p):
    # the first boot after a fresh extract needed 86s to answer HTTP, the same
    # tree warm needed 8s - the difference is the first read of ~19k source
    # files through the 9p server, not anything wrong with HA.  A 60s ceiling
    # killed that boot 26 seconds before it finished, and reported it as
    # "did not come up".  Only the clock got longer: a dead process still
    # breaks out on the next tick, so a genuinely broken boot is reported just
    # as fast as before.
    for _ in range(300):
        log_tick()
        time.sleep(1)
        if pid_exists(p.pid) and _hass_serving():
            print(flush=True)
            log(f"hass started (PID {p.pid}, ready in {time.monotonic() - t_boot:.1f}s)")
            # Two separate moments, in this order:
            #
            # 1. Mint/cache the MCP token BEFORE the RUNNING gate: the gate
            #    authenticates with it, so on a fresh install (no .mcp-token
            #    yet) it would otherwise bail out immediately with "core state
            #    probe skipped" — dead exactly when it matters most.
            # 2. Probe the endpoint only AFTER the gate.  "Answering HTTP" and
            #    "integrations loaded" are seconds apart — measured on this
            #    machine: port ready 4.1s, core RUNNING 11.4s — and mcp_server's
            #    /api/mcp route exists only once its config entry is set up.
            #    Probing in that gap 404s, and since the verdict is frozen into
            #    mcp_fail it survives the gate and is printed as the final
            #    answer a minute later.
            mcp_fail: dict = {}
            tok = _mcp_token(fail=mcp_fail)
            _wait_for_ha_running(t0=t_boot)
            return _finish_setup(_ensure_mcp_ready(mcp_fail, tok=tok), mcp_fail)
        if not pid_exists(p.pid):
            break
    print(flush=True)
    log_state("FAIL", f"hass did not come up — check {HASS_LOG}")
    return 1


def _stop_pid(pid: int) -> bool:
    """Kill the hass at `pid`; True once it is provably gone.

    Windows: /F from the first attempt.  ``taskkill /T`` without /F cannot touch
    a detached console process — measured: exit 128, "can only be terminated
    forcefully" — so the old nice-then-force dance burned a guaranteed 10s on
    every stop.  There is no graceful path to preserve anyway: hass is started
    with DETACHED_PROCESS, so it has no console to receive Ctrl+C.

    POSIX: SIGTERM the process *group* when the pid leads one.  `start` uses
    start_new_session=True, so pid == pgid, and this is exactly what install.sh
    does with `kill -TERM -$pid` — signalling only the leader would leave the
    workers holding the venv.  A hass started some other way may share the
    caller's group, and signalling *that* would take the user's shell down with
    it, hence the pgid == pid test.

    The return value matters: SIGKILL is asynchronous, and the caller may be
    about to rewrite .storage/auth or .storage/core.config_entries.  A dying
    hass flushes its own stores on the way out, so "sent the signal" is not
    "safe to write" — both platforms therefore wait for the process to actually
    disappear before reporting success.
    """
    log(f"stopping hass (PID {pid}) ...")
    if IS_WIN:
        subprocess.run(["taskkill", "/PID", str(pid), "/F", "/T"], capture_output=True)
        for _ in range(20):
            if not pid_exists(pid):
                return True
            time.sleep(0.5)
        return False
    try:
        pgid = os.getpgid(pid)
    except ProcessLookupError:
        pgid = None
    signal_fn = os.killpg if pgid == pid else os.kill
    target = pgid if pgid == pid else pid
    try:
        signal_fn(target, signal.SIGTERM)
    except (ProcessLookupError, PermissionError):
        pass
    for _ in range(60):
        if not pid_exists(pid):
            return True
        time.sleep(0.5)
    try:
        signal_fn(target, signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        pass
    # SIGKILL cannot be ignored, but the process still needs scheduling time to
    # die; without this wait the very next write races its exit flush.
    for _ in range(20):
        if not pid_exists(pid):
            return True
        time.sleep(0.5)
    return False


def cmd_stop(args) -> int:
    pid = _ha_instance()
    if not pid:
        log("hass not running")
        return 0

    if not _stop_pid(pid):
        log_state("FAIL", f"hass (PID {pid}) is still running — "
                          f"it may be stuck in shutdown; try again or kill it by hand")
        return 1
    log("hass stopped")
    return 0


def cmd_logs(args) -> int:
    if not HASS_LOG.exists():
        log(f"no hass log at {HASS_LOG}")
        return 1
    log(f"streaming {HASS_LOG} (Ctrl+C to exit)")
    try:
        with open(HASS_LOG, "r", encoding="utf-8", errors="replace") as f:
            f.seek(0, 2)
            while True:
                line = f.readline()
                if not line:
                    time.sleep(0.2)
                    continue
                sys.stdout.write(line)
                sys.stdout.flush()
    except KeyboardInterrupt:
        print()
        return 0


